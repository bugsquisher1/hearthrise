// tools/balance-lab/dials.mjs — THE LAB'S DIALS, applied to the ENGINE'S OWN DATA ROWS for one run and put back after.
//
// Nothing here forks a formula: a dial moves a data row the engine already reads (src/data/monsters.js MONSTERS,
// src/data/hunt-tiers.js through tierRowOf), the same road tools/balance-sim/worker.mjs's what-ifs take, and the run
// reads it through the engine's own code (atTier, payKill). applyDials answers the undo; the worker calls it
// before a run and the undo after, so a baseline played next reads today's data digit for digit.
//
// ── THE DIALS JSON ("Copy dials as JSON"; schema hearthrise.balance-dials/1) ───────────────────────────────────────
//   {
//     "schema":  "hearthrise.balance-dials/1",
//     "engine":  "0.2.104",                     the game version the lab bundled (src/build-info.js)
//     "ground":  "mosslight_glade",             the ground whose rows the tier dials were read from
//     "monsters": { "dmgPm": 1000, "hpPm": 1000, "xpPm": 1000, "goldPm": 1000 },
//                every monster's atk (its to-hit and its blow, as a tier's power), HP, Level XP a kill and coin a kill,
//                permille of its row; 1000 = the row as written
//     "tiers": { "normal":    { "pull": [0,0,0,0], "dmgPm": 1000, "hpPm": 1000, "xpPm": 1000 },
//                "dangerous": { "pull": [3,5,5,6], "dmgPm": 1400, "hpPm": 1000, "xpPm": 1100 },
//                "deadly":    { "pull": [8,8,8,8], "dmgPm": 1600, "hpPm": 1000, "xpPm": 1200 } },
//                one row per tier in src/data/balance-sheet.js TIER_DIALS's shape: pull = monsters a pull for 1..4
//                heroes (0 = the ground as it stands), then permilles on top of the monster dials. Coin never moves
//                with a tier (Tyler 2026-11-07).
//     "scale":   { "toLevel": null | N, "fromLevel": the ground's floor }   PREVIEW of a scaled hunt: every monster on
//                the ground read from the stat formula N - floor Levels higher (balance-sheet.js formulaStats), the
//                ratios applied to its own row; item drops unchanged. Only when the bundle holds the formula.
//     "run":     { "ground", "tier", "party": [{ "style", "level", "gear" }], "hours", "seeds" }   what was played
//   }
// The formula generator (tools/gen-ground-stats.mjs) and the tier table (lane/b-tier-dials) read `tiers` as written;
// `monsters` is a global multiplier on top of the rows they write.
import { MONSTERS } from '../../src/data/monsters.js';
import * as TIERS from '../../src/data/hunt-tiers.js';
import { COMBAT_BALANCE } from '../../src/core/combat.js';
/* GENERATED by build.mjs: `export * from src/data/balance-sheet.js` when that file exists, else nothing (the lab then
   grades on Tyler's 10-25 targets and has no scale preview) */
import * as SHEET from './virtual/sheet.mjs';

export const DIALS_SCHEMA = 'hearthrise.balance-dials/1';
export const TIER_KEYS = Object.freeze(['normal', 'dangerous', 'deadly']);
const PM = 1000;

/** Does this bundle hold the stat formula and the target sheet (src/data/balance-sheet.js)? */
export const hasSheet = () => typeof SHEET.formulaStats === 'function' && !!SHEET.BALANCE_SHEET;

/** A tier row as the dials read it, from whatever shape hunt-tiers.js holds: { pull[4], dmgPm, hpPm, xpPm }. */
export function tierDialOf(row) {
  const r = row || {};
  /* the sheet's TIER_DIALS hold ONE pull for every group (2026-11-08); an engine row, one per party size */
  return { pull: Array.isArray(r.pull) ? r.pull.slice(0, 4).concat([0, 0, 0, 0]).slice(0, 4) : Number.isInteger(r.pull) ? [r.pull, r.pull, r.pull, r.pull] : [0, 0, 0, 0],
    dmgPm: Number.isFinite(r.dmgPm) ? r.dmgPm : Number.isFinite(r.powerPm) ? r.powerPm : PM,
    hpPm: Number.isFinite(r.hpPm) ? r.hpPm : PM, xpPm: Number.isFinite(r.xpPm) ? r.xpPm : PM };
}

/** Today's data for a ground: the tier rows the engine plays, and which tiers the ground offers. */
export function tierDefaults(groundId) {
  const offered = typeof TIERS.tiersOf === 'function' ? TIERS.tiersOf(groundId) : ['normal'];
  return { offered, tiers: Object.fromEntries(TIER_KEYS.map((t) => [t, tierDialOf(TIERS.tierRowOf(groundId, t))])) };
}

/** The dials that change nothing: today's rows for `groundId`. */
export function defaultDials(groundId) {
  return { schema: DIALS_SCHEMA, ground: groundId, monsters: { dmgPm: PM, hpPm: PM, xpPm: PM, goldPm: PM }, tiers: tierDefaults(groundId).tiers, scale: { toLevel: null } };
}

/** The sheet's own tier rows for a ground whose band starts at `floor` (balance-sheet.js tierRowFor, else its TIER_DIALS whole): the designer's proposal, or null. */
export function sheetTierDials(floor) {
  if (!hasSheet()) return null;
  try {
    if (typeof SHEET.tierRowFor === 'function') return Object.fromEntries(TIER_KEYS.map((t) => [t, tierDialOf(SHEET.tierRowFor(floor, t))]));
    if (SHEET.TIER_DIALS) return Object.fromEntries(TIER_KEYS.map((t) => [t, tierDialOf(SHEET.TIER_DIALS[t])]));
  } catch (e) { /* a sheet mid-change: no proposal rather than a wrong one */ }
  return null;
}

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/* THE SCALED-HUNT PREVIEW: per monster, the stat formula read `shift` Levels higher over the formula at its own
   Level ('regular' role: a role is a multiplier, so it cancels in the ratio), and the to-hit base moved by the same
   difference; the ground's floor moves by the same shift. Answers { id: { hp, atk, xp, gp, baseAccDelta, level } } ratios and
   deltas, or null without the formula. A formula that refuses its input stops the run with its reason (never a guess). */
export function scaleOf(monsterIds, shift, floor) {
  if (!hasSheet() || !Number.isInteger(shift) || shift === 0) return null;
  const out = {};
  for (const id of monsterIds) {
    const m = MONSTERS[id];
    if (!m || !Number.isInteger(m.level)) continue;
    /* the ground's floor moves with it: a scaled ground is the formula read at a higher floor too */
    const at = (L, F) => SHEET.formulaStats({ level: Math.max(1, L), role: 'regular', tier: m.tier, floor: Math.max(1, F) });
    let a, b;
    try { a = at(m.level, floor); b = at(m.level + shift, floor + shift); } catch (e) { throw new Error('the scale preview: the stat formula refused (' + e.message + ')'); }
    const mean = (g) => (g[0] + g[1]) / 2;
    out[id] = { hp: b.hp / a.hp, atk: b.atk / a.atk, xp: b.xp / a.xp, gp: mean(b.gp) / mean(a.gp), baseAccDelta: b.baseAcc - a.baseAcc, level: Math.max(1, m.level + shift) };
  }
  return out;
}

/**
 * Move the engine's rows for one run of `tier` on `groundId`. `dials` as defaultDials answers (any field may be
 * missing = unchanged); `monsterIds` the ground's monsters (the scale preview's scope). Answers undo().
 * The tier row is written in the shape hunt-tiers.js holds today: a field it lacks (hpPm before lane/b-tier-dials)
 * is applied on the monster rows instead, the same multiplier the engine would apply.
 */
export function applyDials(dials, { groundId, tier, monsterIds }) {
  const undo = [];
  const set = (obj, k, v) => { undo.push([obj, k, Object.prototype.hasOwnProperty.call(obj, k), obj[k]]); obj[k] = v; };
  const d = dials || {};
  const mon = { dmgPm: PM, hpPm: PM, xpPm: PM, goldPm: PM, ...(d.monsters || {}) };
  /* THE TIER ROW: written only where the dial differs from today's row */
  const today = TIERS.tierRowOf(groundId, tier);
  const want = d.tiers && d.tiers[tier] ? { ...tierDialOf(today), ...d.tiers[tier] } : tierDialOf(today);
  let hpOnRows = PM;
  if (!same(want, tierDialOf(today))) {
    const next = { ...today, id: tier, pull: want.pull.slice() };
    if ('powerPm' in today || !('dmgPm' in today)) next.powerPm = want.dmgPm; else next.dmgPm = want.dmgPm;
    if ('hpPm' in today) next.hpPm = want.hpPm; else hpOnRows = want.hpPm;
    next.xpPm = want.xpPm;
    /* an unfrozen row is the one the engine reads (a ground's own row today; the one table's row after lane/b-tier-dials):
       move it in place. A frozen one (today's shared Normal) gets a ground's own row beside it, as balance-sim's what-ifs do. */
    if (!Object.isFrozen(today)) {
      for (const [k, v] of Object.entries(next)) set(today, k, v);
    } else if (TIERS.GROUND_TIERS && typeof TIERS.GROUND_TIERS === 'object' && !Object.isFrozen(TIERS.GROUND_TIERS)) {
      if (!TIERS.GROUND_TIERS[groundId]) set(TIERS.GROUND_TIERS, groundId, {});
      set(TIERS.GROUND_TIERS[groundId], tier, next);
    } else {
      throw new Error('balance-lab dials: hunt-tiers.js holds a shape the lab cannot write (a frozen row and no per-ground table); update tools/balance-lab/dials.mjs');
    }
    const read = tierDialOf(TIERS.tierRowOf(groundId, tier));
    if (read.xpPm !== want.xpPm || read.dmgPm !== want.dmgPm) {
      for (let i = undo.length - 1; i >= 0; i--) { const [o, k, had, v] = undo[i]; if (had) o[k] = v; else delete o[k]; }
      throw new Error('balance-lab dials: wrote the ' + tier + ' row on ' + groundId + ' but the engine reads another (hunt-tiers.js changed shape); update tools/balance-lab/dials.mjs');
    }
  }
  /* THE MONSTER ROWS: atk and Level XP stay fractional (atTier already makes them so on a harder tier; the engine
     floors a blow and rounds a kill's XP), HP and coin stay whole (a unit's HP, the coin roll's integer range) */
  const scale = d.scale && Number.isInteger(d.scale.toLevel) && Number.isInteger(d.scale.fromLevel) ? scaleOf(monsterIds || [], d.scale.toLevel - d.scale.fromLevel, d.scale.fromLevel) : null;
  const hpPm = (mon.hpPm * hpOnRows) / PM;
  if (mon.dmgPm !== PM || hpPm !== PM || mon.xpPm !== PM || mon.goldPm !== PM || scale) {
    for (const [id, row] of Object.entries(MONSTERS)) {
      const s = scale && scale[id];
      const atk = (mon.dmgPm / PM) * (s ? s.atk : 1), hp = (hpPm / PM) * (s ? s.hp : 1), xp = (mon.xpPm / PM) * (s ? s.xp : 1), gold = (mon.goldPm / PM) * (s ? s.gp : 1);
      if (atk !== 1 && Number.isFinite(row.atk)) set(row, 'atk', row.atk * atk);
      if (hp !== 1 && Number.isFinite(row.hp)) set(row, 'hp', Math.max(1, Math.round(row.hp * hp)));
      if (xp !== 1 && Number.isFinite(row.xp)) set(row, 'xp', row.xp * xp);
      if (gold !== 1 && Array.isArray(row.gp)) {
        const lo = Math.max(0, Math.round(row.gp[0] * gold));
        set(row, 'gp', [lo, Math.max(lo, Math.round(row.gp[1] * gold))]);
      }
      if (s) {
        set(row, 'level', s.level);
        /* the to-hit base moves by the formula's own difference (a row without one fights at the engine's default) */
        if (s.baseAccDelta) set(row, 'baseAcc', (Number.isFinite(row.baseAcc) ? row.baseAcc : COMBAT_BALANCE.monsterBaseAccuracy) + s.baseAccDelta);
      }
    }
  }
  return function restore() {
    for (let i = undo.length - 1; i >= 0; i--) { const [o, k, had, v] = undo[i]; if (had) o[k] = v; else delete o[k]; }
    undo.length = 0;
  };
}

/** What the monster dials actually move on these monsters (coin and HP round to whole numbers): mean % per field. */
export function effectiveMonsterChange(dials, monsterIds) {
  const m = { dmgPm: PM, hpPm: PM, xpPm: PM, goldPm: PM, ...((dials && dials.monsters) || {}) };
  const acc = { hp: [0, 0], gold: [0, 0] };
  for (const id of monsterIds) {
    const r = MONSTERS[id];
    if (!r) continue;
    if (Number.isFinite(r.hp)) { acc.hp[0] += r.hp; acc.hp[1] += Math.max(1, Math.round((r.hp * m.hpPm) / PM)); }
    if (Array.isArray(r.gp)) {
      const lo = Math.max(0, Math.round((r.gp[0] * m.goldPm) / PM));
      acc.gold[0] += r.gp[0] + r.gp[1]; acc.gold[1] += lo + Math.max(lo, Math.round((r.gp[1] * m.goldPm) / PM));
    }
  }
  const pct = (a) => (a[0] ? Math.round((1000 * a[1]) / a[0]) / 10 : 100);
  return { dmgPct: m.dmgPm / 10, hpPct: pct(acc.hp), xpPct: m.xpPm / 10, goldPct: pct(acc.gold) };
}

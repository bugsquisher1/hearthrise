#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-bounty-monsters.mjs — GENERATE THE SERVER MONSTER→TIER CATALOGUE.
//
// The bounty turn-in RPC (2026-08-23-bounty.sql) must own the bounty's TIER,
// because tier drives the gold+marks reward and the combat-level gate. Tier
// lives on each monster in src/data/monsters.js and NOWHERE server-side, so
// this generator emits `public.hr_bounty_monsters (monster_id, tier)` from that
// single source. Copying game DATA into SQL by hand is the failure src/main.js
// `unifyObject` was written about; this file is machine-written from the data
// and drift-guarded (tests/bounty-drift.mjs), so the copy cannot rot.
//
//   Regenerate:  node tools/gen-bounty-monsters.mjs
//   Verify:      node tools/gen-bounty-monsters.mjs --check   (run in run-smoke)
//
// Emits ONLY ids + tier — no hp, no reward, no game number beyond the tier the
// bounty economy already keys on. The reward MULTIPLIER tables live inline in
// 2026-08-23-bounty.sql (drift-guarded against src/core/bounty.js), not here.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { MONSTERS } from '../src/data/monsters.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'supabase', 'migrations', '2026-08-23-bounty-monsters.generated.sql');

function rows() {
  return Object.keys(MONSTERS).sort().map((id) => {
    const t = MONSTERS[id].tier;
    if (!(t >= 1 && t <= 6)) throw new Error(`monster ${id} has out-of-range tier ${t}`);
    if (!/^[a-z0-9_]+$/.test(id)) throw new Error(`monster id ${id} is not [a-z0-9_]`);
    return [id, t | 0];
  });
}

export function render() {
  const r = rows();
  const digest = createHash('sha256').update(JSON.stringify(r)).digest('hex');
  const values = r.map(([id, t]) => `  ('${id}', ${t})`).join(',\n');
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE BOUNTY MONSTER→TIER CATALOGUE  (GENERATED — DO NOT EDIT)
--
--   Generated by tools/gen-bounty-monsters.mjs from src/data/monsters.js.
--   Any hand edit is reverted by the next generation and FAILS
--   \`node tools/gen-bounty-monsters.mjs --check\` (a preflight in run-smoke).
--
--   monster digest: ${digest}
--   ${r.length} monsters
--
-- Read by hr_accept_bounty (2026-08-23-bounty.sql) to derive the bounty's tier
-- server-side. Ids + tier only — no game number beyond tier. Idempotent: a
-- truncate+insert inside the migration transaction, so a re-apply is a no-op.
-- ════════════════════════════════════════════════════════════════════════

do $$
begin
  if to_regclass('public.hr_bounty_monsters') is null then
    create table public.hr_bounty_monsters (
      monster_id text primary key,
      tier       int  not null check (tier between 1 and 6)
    );
    alter table public.hr_bounty_monsters enable row level security;
  end if;
end $$;

-- Read-only catalogue: readable by everyone signed in, written by NO client.
drop policy if exists hr_bounty_monsters_sel on public.hr_bounty_monsters;
create policy hr_bounty_monsters_sel on public.hr_bounty_monsters for select using (true);
revoke all on public.hr_bounty_monsters from anon, authenticated, service_role;
grant select on public.hr_bounty_monsters to anon, authenticated, service_role;

truncate table public.hr_bounty_monsters;
insert into public.hr_bounty_monsters (monster_id, tier) values
${values};

do $$
declare v_n int;
begin
  select count(*) into v_n from public.hr_bounty_monsters;
  if v_n <> ${r.length} then
    raise exception 'hr_bounty_monsters has % rows, expected ${r.length}', v_n;
  end if;
end $$;
`;
}

const wanted = render();
if (process.argv.includes('--check')) {
  const have = await readFile(OUT, 'utf8').catch(() => '');
  if (have.replace(/\r\n/g, '\n') !== wanted.replace(/\r\n/g, '\n')) {
    console.error('gen-bounty-monsters --check FAILED: '
      + '2026-08-23-bounty-monsters.generated.sql is stale. Run: node tools/gen-bounty-monsters.mjs');
    process.exit(1);
  }
  console.log('gen-bounty-monsters --check: catalogue matches src/data/monsters.js');
} else {
  await writeFile(OUT, wanted);
  console.log(`wrote ${OUT}`);
}

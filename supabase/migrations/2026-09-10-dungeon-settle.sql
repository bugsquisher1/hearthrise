-- ── 1. player_ledger.kind must admit 'dungeon' — PROGRAMMATIC, ADDITIVE ────
-- Inserted at an anchor rather than restating the array (the 2026-09-08-hero-slot
-- precedent), so it removes nothing and cannot silently delete a kind a later
-- file added if it is re-applied out of order.
do $$
declare v_def text; v_new text;
begin
  select pg_get_constraintdef(oid) into v_def from pg_constraint
   where conrelid = 'public.player_ledger'::regclass and conname = 'player_ledger_kind_check';
  if v_def is null then
    raise exception 'player_ledger_kind_check is absent — this verb''s journal row would be '
                    'unconstrained, and every other writer assumes the constraint exists';
  end if;
  if position('''dungeon''' in v_def) > 0 then
    raise notice 'player_ledger.kind already admits ''dungeon'' — widen skipped';
    return;
  end if;
  if position('''accrue''::text' in v_def) = 0 then
    raise exception 'player_ledger_kind_check has no ''accrue''::text anchor (%) — refusing to '
                    'rewrite a constraint whose shape this file cannot account for', v_def;
  end if;
  v_new := replace(v_def, '''accrue''::text', '''dungeon''::text, ''accrue''::text');
  execute 'alter table public.player_ledger drop constraint player_ledger_kind_check';
  execute 'alter table public.player_ledger add constraint player_ledger_kind_check ' || v_new;
  raise notice 'player_ledger.kind widened to admit ''dungeon'' (insertion, nothing removed)';
end $$;

-- ── 2. hr_dungeon_settle ───────────────────────────────────────────────────
-- The sequence is hr_unlock_buy's, deliberately: identity seam → catalogue (no
-- lock) → rate → advisory lock → idempotency → protected block (row lock,
-- version, gates, key debit, loot roll, scrip credit, journal) → record the
-- decision.
create or replace function public.hr_dungeon_settle(
  p_user uuid, p_slot int, p_version bigint, p_intent_id uuid,
  p_dungeon_id text, p_mode text, p_quality numeric)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  -- BLAST RADIUS, not balance (the clan_deposit / hr_unlock_buy rule). Far above
  -- honest play (each run yields <= 57 scrip and costs a real server-held key),
  -- far below "grind the whole Quartermaster in a day". Designer-tunable fuses
  -- (ruling 2026-09-05): 5,000 GROSS-EARNED scrip/UTC-day and 250 settles/UTC-day.
  c_daily_scrip_cap constant bigint := 5000;
  -- Per-day settle COUNT fuse (anti-replay insurance): 250 settles/UTC-day, all
  -- dungeons + modes combined. NOT 25 — 250 is the ruling.
  c_daily_count_cap constant int := 250;

  v_uid    uuid;
  v_role   text;
  v_slot   int := coalesce(p_slot, 0);
  v_dun    public.hr_dungeons%rowtype;
  v_st     public.player_state%rowtype;
  v_cached jsonb;
  v_intent text;
  v_out    jsonb;
  v_settled jsonb;
  v_msg text; v_det text; v_sqlstate text;
  v_clv    int;
  v_q      numeric;
  v_scrip  bigint;
  v_today  bigint;
  v_count_today int;
  v_last_auto timestamptz;
  v_key    text;
  v_have   bigint;
  v_items  jsonb := '{}'::jsonb;
  v_qty_total bigint := 0;
  v_day    text;
  r        record;
  v_rc     numeric; v_rq numeric; v_qty bigint;
begin
  -- ── (0) IDENTITY SEAM. hr_unlock_buy's, verbatim in effect: the engine may
  --        act for a user it has already verified; nobody else may name a user.
  --        current_user is the OWNER inside a definer function, so the ROLE GUC
  --        is what is read.
  v_role := coalesce(nullif(current_setting('role', true), 'none'), session_user);
  if v_role = 'hr_engine' then
    v_uid := coalesce(p_user, auth.uid());
  else
    v_uid := auth.uid();
    if p_user is not null and p_user is distinct from v_uid then
      perform public.hr_record_rejection(v_uid, v_slot, 'dungeon_settle', 'forbidden_impersonation',
        jsonb_build_object('claimed_user', p_user, 'role', v_role));
      return jsonb_build_object('ok', false, 'error', 'forbidden_impersonation');
    end if;
  end if;
  if v_uid is null then return jsonb_build_object('ok', false, 'error', 'not_signed_in'); end if;
  if p_intent_id is null then return jsonb_build_object('ok', false, 'error', 'missing_intent_id'); end if;

  -- ── (1) SHAPE + CATALOGUE, BEFORE ANY LOCK. A refusal that is a fact about
  --        the request or the catalogue needs no character and no lock, so a
  --        client looping on a bad id cannot contend on a real player's row.
  if p_mode is null or p_mode not in ('auto', 'manual', 'scavenger') then
    return jsonb_build_object('ok', false, 'error', 'bad_mode', 'mode', p_mode);
  end if;
  if p_dungeon_id is null then
    return jsonb_build_object('ok', false, 'error', 'unknown_dungeon');
  end if;
  select * into v_dun from public.hr_dungeons where dungeon_id = p_dungeon_id;
  if v_dun.dungeon_id is null then
    return jsonb_build_object('ok', false, 'error', 'unknown_dungeon',
      'detail', jsonb_build_object('dungeon', p_dungeon_id));
  end if;
  -- The name carries the dungeon AND the mode, because intent_mismatch compares
  -- exactly this string and the mode changes what the write does (auto pays a
  -- cooldown, manual/scavenger do not).
  v_intent := 'dungeon_settle:' || v_dun.dungeon_id || ':' || p_mode;

  -- ── (2) RATE. The `apply` budget, NOT a new namespace (hr_unlock_buy's rule:
  --        a second writer with its own allowance doubles a compromised engine's
  --        reachable write rate). Outside the protected block, sampled.
  if not public.hr_rate_ok(v_uid, 'apply', 240, interval '1 minute') then
    if public.hr_rate_sample_weight(public.hr_rate_over(v_uid, 'apply') - 240) > 0 then
      perform public.hr_record_rejection(v_uid, v_slot, 'dungeon_settle', 'rate_limited',
        jsonb_build_object('limit', 240, 'per', '1 minute'),
        public.hr_rate_sample_weight(public.hr_rate_over(v_uid, 'apply') - 240));
    end if;
    return jsonb_build_object('ok', false, 'error', 'rate_limited');
  end if;

  -- ── (3) SERIALISE THIS CHARACTER — the SAME advisory key hr_apply takes, so a
  --        settle cannot race an accrual on one character.
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text || ':' || v_slot::text, 0));

  -- ── (4) IDEMPOTENCY, per (KEY, INTENT, SLOT). player_intents is ONE namespace
  --        for every verb, so a key claimed for another intent/slot is REFUSED,
  --        not answered with that intent's decision. ONLY SUCCESSES ARE CACHED
  --        (see §(5)); a matching success replays with FRESH state + the original
  --        settled receipt + replayed:true (the hr_unlock_buy replay shape).
  select public.hr_intent_replay(v_uid, v_slot, p_intent_id, v_intent) into v_cached;
  if v_cached ->> 'error' = 'intent_mismatch' then return v_cached; end if;
  if v_cached is not null then
    return public.hr_state_of(v_uid, v_slot) || v_cached || jsonb_build_object('replayed', true);
  end if;

  -- ══ THE PROTECTED BLOCK ═══════════════════════════════════════════════════
  -- All-or-nothing. Every rejection raises through hr_reject (HR000) and the
  -- handler undoes the whole block, so there is no state in which the key left
  -- and the reward did not arrive (or vice versa).
  begin
    select * into v_st from public.player_state
      where user_id = v_uid and slot = v_slot for update;
    if v_st.user_id is null then perform public.hr_reject('no_character'); end if;

    -- (a) OPTIMISTIC CONCURRENCY — MANDATORY. A missing version IS a conflict.
    if p_version is null or p_version <> v_st.version then
      perform public.hr_reject('version_conflict', jsonb_build_object('version', v_st.version));
    end if;

    -- (b) COMBAT LEVEL >= req_lv — derived from player_skills with the SAME
    --     formula the leaderboard uses (hr_lb_combat_level), never a client
    --     level. Unlevelled skills coalesce to level 1, matching src/core/xp.js.
    select public.hr_lb_combat_level(
      coalesce(max(public.hr_level_from_xp(xp)) filter (where skill_id = 'attack'),    1),
      coalesce(max(public.hr_level_from_xp(xp)) filter (where skill_id = 'strength'),  1),
      coalesce(max(public.hr_level_from_xp(xp)) filter (where skill_id = 'defense'),   1),
      coalesce(max(public.hr_level_from_xp(xp)) filter (where skill_id = 'hitpoints'), 1),
      coalesce(max(public.hr_level_from_xp(xp)) filter (where skill_id = 'prayer'),    1),
      coalesce(max(public.hr_level_from_xp(xp)) filter (where skill_id = 'ranged'),    1),
      coalesce(max(public.hr_level_from_xp(xp)) filter (where skill_id = 'magic'),     1))
      into v_clv
      from public.player_skills where user_id = v_uid and slot = v_slot;
    v_clv := coalesce(v_clv, 1);
    if v_clv < v_dun.req_lv then
      perform public.hr_reject('level_locked',
        jsonb_build_object('have', v_clv, 'need', v_dun.req_lv));
    end if;

    -- (c) COOLDOWN — auto mode only, read from now() + the append-only ledger
    --     (never a stored counter a client can reset: the b288 lesson). Manual
    --     and scavenger deliberately have no cooldown; their limiter is the key
    --     debit + the per-day scrip cap.
    if p_mode = 'auto' and v_dun.cooldown_s > 0 then
      select max(at) into v_last_auto from public.player_ledger
       where user_id = v_uid and slot = v_slot and kind = 'dungeon'
         and meta->>'dungeon' = v_dun.dungeon_id and meta->>'mode' = 'auto';
      if v_last_auto is not null
         and now() < v_last_auto + make_interval(secs => v_dun.cooldown_s) then
        perform public.hr_reject('on_cooldown',
          jsonb_build_object('ready_at', v_last_auto + make_interval(secs => v_dun.cooldown_s)));
      end if;
    end if;

    -- (d) SCRIP. Clamp the ONE client value to [0,1], SELF-ONLY, and apply it to
    --     the server-owned base. round(base * clamp) — the awardDungeonScrip
    --     formula, now server-owned.
    v_q := least(greatest(coalesce(p_quality, 1), 0), 1);
    v_scrip := round(v_dun.scrip_base * v_q)::bigint;

    -- (e) PER-DAY SCRIP EARN CAP (blast radius) — summed from the append-only
    --     ledger for this character-day, the clan_deposit pattern. Checked BEFORE
    --     the key is debited, so a capped-out run costs no key.
    --     ⚠ POSITIVE-SCRIP ROWS ONLY (Designer ruling 2026-09-05, Condition-3):
    --     the sum GROSS-EARNS. A Quartermaster spend (kind='dungeon',
    --     meta.op='qm_buy', meta.scrip < 0 — 2026-09-11-quartermaster-buy.sql)
    --     must NOT reduce the cap's used total, or a spend→earn→spend loop would
    --     launder the daily earn ceiling. The `(meta->>'scrip')::bigint > 0` filter
    --     is EXPLICIT (not "sum every dungeon row") precisely so a future QM-row
    --     shape change can never fold a spend back into the earn sum.
    v_day := public.hr_utc_day_key(now());
    select coalesce(sum((meta->>'scrip')::bigint), 0) into v_today
      from public.player_ledger
     where user_id = v_uid and slot = v_slot and kind = 'dungeon'
       and (meta->>'scrip')::bigint > 0
       and public.hr_utc_day_key(at) = v_day;
    if v_today + v_scrip > c_daily_scrip_cap then
      perform public.hr_reject('daily_cap',
        jsonb_build_object('dim', 'scrip', 'used', v_today, 'add', v_scrip,
                           'limit', c_daily_scrip_cap, 'day', v_day));
    end if;

    -- (e2) PER-DAY SETTLE COUNT CAP (anti-replay insurance, Designer ruling
    --      2026-09-05): at most 250 SETTLES/UTC-day, all dungeons + modes combined.
    --      Counts SETTLE rows only (meta.op='settle'); a Quartermaster spend
    --      (meta.op='qm_buy') is not a settle and is deliberately excluded, so the
    --      count fuse cannot be inflated or evaded by QM traffic. Checked BEFORE
    --      the key debit too, so a count-capped run costs no key.
    select count(*) into v_count_today
      from public.player_ledger
     where user_id = v_uid and slot = v_slot and kind = 'dungeon'
       and meta->>'op' = 'settle'
       and public.hr_utc_day_key(at) = v_day;
    if v_count_today >= c_daily_count_cap then
      perform public.hr_reject('daily_cap',
        jsonb_build_object('dim', 'count', 'used', v_count_today,
                           'limit', c_daily_count_cap, 'day', v_day));
    end if;

    -- (f) THE KEY — present + consumed under the row lock. THE load-bearing gate:
    --     a run costs a real server-held key (b501 folded key drops into combat
    --     drops, so keys live in player_inventory). Without a key the settle
    --     refuses; keys are never re-granted here.
    v_key := v_dun.cost_key;
    select qty into v_have from public.player_inventory
     where user_id = v_uid and slot = v_slot and item_id = v_key for update;
    v_have := coalesce(v_have, 0);
    if v_have < 1 then
      perform public.hr_reject('insufficient_item',
        jsonb_build_object('item_id', v_key, 'have', v_have, 'need', 1));
    end if;
    if v_have = 1 then
      delete from public.player_inventory
       where user_id = v_uid and slot = v_slot and item_id = v_key;
    else
      update public.player_inventory set qty = v_have - 1
       where user_id = v_uid and slot = v_slot and item_id = v_key;
    end if;

    -- (g) LOOT — SERVER-ROLLED from the generated catalogue with the SEEDED
    --     PRNG, and NOT scaled by any client value (p_quality touches scrip
    --     only), so a forged quality cannot inflate loot. Each row salts hr_seed
    --     with the dungeon, the run key (p_intent_id) and the ordinal, so the
    --     roll is deterministic and replayable from the ledger yet unpredictable
    --     (the 256-bit secret). Additive upsert (the muster-chest idiom).
    for r in select ord, item_id, qty_min, qty_max, chance
               from public.hr_dungeon_loot
              where dungeon_id = v_dun.dungeon_id order by ord loop
      v_rc := (public.hr_seed(v_uid, v_slot,
                 'dungeon:' || v_dun.dungeon_id || ':' || p_intent_id::text || ':' || r.ord || ':c')
               & 4294967295)::numeric / 4294967296.0;
      if v_rc < r.chance then
        v_rq := (public.hr_seed(v_uid, v_slot,
                   'dungeon:' || v_dun.dungeon_id || ':' || p_intent_id::text || ':' || r.ord || ':q')
                 & 4294967295)::numeric / 4294967296.0;
        v_qty := r.qty_min + floor(v_rq * (r.qty_max - r.qty_min + 1))::bigint;
        insert into public.player_inventory as pi (user_id, slot, item_id, qty)
          values (v_uid, v_slot, r.item_id, v_qty)
          on conflict (user_id, slot, item_id) do update set qty = pi.qty + excluded.qty;
        v_items := v_items || jsonb_build_object(r.item_id, v_qty);
        v_qty_total := v_qty_total + v_qty;
      end if;
    end loop;

    -- (h) SCRIP CREDIT + version bump. accrued_to UNTOUCHED (a run is not an
    --     activity change — stamping it would confiscate the elapsed accrual
    --     window, hr_unlock_buy's rule).
    update public.player_state
       set dungeon_scrip = dungeon_scrip + v_scrip,
           version = version + 1,
           updated_at = now()
     where user_id = v_uid and slot = v_slot;

    -- (i) THE JOURNAL. ONE row, kind='dungeon'. qty_in/gold_in/xp_in = 0 explicit
    --     (a fixed server-owned reward, kept OUT of the accrual daily inflow
    --     budget, like the muster credit). The scrip movement is meta->>'scrip';
    --     meta.dungeon + meta.mode are read by the cooldown query above.
    --     ⚠ meta.op='settle' is the EXPLICIT row-kind discriminator (Designer
    --     ruling 2026-09-05): the earn-cap (e) sums positive scrip and the count-
    --     cap (e2) counts op='settle', so a Quartermaster spend row (op='qm_buy',
    --     negative scrip — 2026-09-11-quartermaster-buy.sql) can never fold into
    --     either fuse. A settle ALWAYS earns >= 0 scrip and carries op='settle'.
    insert into public.player_ledger
      (user_id, slot, kind, intent, gold, gold_in, xp_in, qty_in, gems_in, meta)
    values
      (v_uid, v_slot, 'dungeon', v_intent, 0, 0, 0, 0, 0,
       jsonb_build_object('op', 'settle',
                          'dungeon', v_dun.dungeon_id, 'mode', p_mode, 'quality', v_q,
                          'key_spent', v_key, 'scrip', v_scrip,
                          'items', v_items, 'item_qty', v_qty_total, 'idem', p_intent_id));


// ════════════════════════════════════════════════════════════════════════
// src/core/gold-estimate.js — ABOUT HOW MUCH GOLD AN HOUR A GROUND PAYS, BEFORE SUPPLIES (lane/gold-per-hour, systems, 2026-11-22;
//   Tyler 2026-11-22: "About N gold an hour, before supplies" on each Danger scale ground in the Hunts window).
//
// THE RULE. For a hero of Level L on a scale ground at a Risk:
//
//   none     under the ground's band floor (src/data/hunts.js band[0]): nothing measured there, and the window already warns
//   step     = min(levelStep(L), the ground's band top)          (src/core/wage.js levelStep; src/data/hunts.js band[1])
//   gold     = floor(wage(step) x riskPm / 1000)                 (src/core/wage.js wage; src/data/gold-estimate.js riskPm)
//   estimate = gold rounded to two significant figures, halves up (4,886 is 4,900; 640 is 640; 12,345 is 12,000)
//
// WHY THE STEP IS THE HERO'S LEVEL, NOT THE HELD DANGER STEP. The wage is the Steady reference hour at a step of 04's absolute unit, where a
// hero of Level L whose kit is at Level holds step L; the engine's wave-1 Danger step counts from each ground's own rows (Muster Barrows'
// 590 is not Level 590), so it is not a step the wage can read (src/data/wage.js: "today every caller passes a Level"). The held step is
// also written by whichever Risk last played the ground (Careful holds ~170 steps under Steady at Level 60: r9/summary.txt), so reading it
// beside a Risk's own ratio would count the Risk twice. So the estimate is at the depth a Steady company of the hero's Level is EXPECTED to
// hold, and the Risk is its ratio. Wave 2 (bands in absolute steps) swaps levelStep(L) for the hero's held step on the ground.
// WHY THE BAND TOP. Pay stops growing at the top of a ground (12-targets.md 3.2): a hero past it earns what the top pays, and the next ground
// pays more. WHY NONE UNDER THE FLOOR. The wage grows only 0.4% a Level, so a Level 10 hero would read nearly a Level 60's gold on a
// ground that kills it: no company was measured under the band's floor, so the line is left out rather than promise gold that is not there.
//
// Every number is a whole integer and every step exact, so the SQL twin (hr_gold_estimate, generated by tools/gen-gold-estimate.mjs) reaches
// the same gold. The client never runs this: it renders the server's `gold_estimate` section.
//
// PURE ESM, dual-runtime. No clock, no randomness.
// ════════════════════════════════════════════════════════════════════════
import { wage, levelStep } from './wage.js';
import { DANGER_GROUNDS } from '../data/danger.js';
import { HUNTS } from '../data/hunts.js';
import { GOLD_ESTIMATE } from '../data/gold-estimate.js';

const own = (o, k) => typeof k === 'string' && Object.prototype.hasOwnProperty.call(o, k);

/** The scale grounds the estimate is made for, each with its Level band: [{ hunt, floor, top }], sorted by id. A scale ground with no hunt
    row or no whole band is left out (no line, never a guess). */
export function estimateGrounds() {
  const byId = new Map(HUNTS.map((h) => [h.id, h]));
  return Object.keys(DANGER_GROUNDS).sort().flatMap((hunt) => {
    const h = byId.get(hunt), b = h && Array.isArray(h.band) ? h.band : [];
    return Number.isSafeInteger(b[0]) && Number.isSafeInteger(b[1]) && b[0] >= 0 && b[1] >= Math.max(1, b[0]) ? [{ hunt, floor: b[0], top: b[1] }] : [];
  });
}

/** Whole gold `g` to two significant figures, halves up. */
export function roundAbout(g) {
  if (!(g >= 100)) return Math.max(0, Math.floor(g));
  let h = 1;
  while (g >= h * 100) h *= 10;
  return Math.floor((g + h / 2) / h) * h;
}

/** About how much gold an hour `hunt` pays a hero of Level `level` at `risk`, before supplies; null off the scale, for an unknown Risk,
    or under the ground's band floor. */
export function goldEstimate(hunt, risk, level) {
  const g = estimateGrounds().find((x) => x.hunt === hunt);
  if (!g || !own(GOLD_ESTIMATE.riskPm, risk) || levelStep(level) < g.floor) return null;
  const step = Math.min(levelStep(level), g.top);
  return roundAbout(Math.floor((wage(step) * GOLD_ESTIMATE.riskPm[risk]) / 1000));
}

#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-social-catalogue.mjs — GENERATE THE SOCIAL LAYER'S SERVER RULES (lane/c-social, FB-12).
//
// The data is the one source; the server's copies are written from it, never typed twice:
//   hr_clan_rules        one row   src/data/clans.js CLAN_RULES (the founding price 25-6, name and tag lengths, browser, invite days)
//   hr_chat_global_rule  one row   src/data/chat-channels.js GLOBAL_BATCH (31-1: Global's batch cadence)
//   hr_chat_slow_mode    a row a step  src/data/chat-channels.js SLOW_MODE (31-1: Global's slow mode)
//   hr_friend_link_rule  one row   src/data/chat-channels.js FRIEND_LINK (GR-72: how new an account must be)
// supabase/migrations/1041-social-clans.sql and 1044-friend-link.sql read them; this file runs before both.
//
// THE FORWARD-FILE RULE: an applied file is history and is never regenerated in place; a moved row is a new file (OUT_NAME).
//
//   node tools/gen-social-catalogue.mjs            write OUT_NAME
//   node tools/gen-social-catalogue.mjs --check    exit 1 if OUT_NAME is not what it would write
//   node tools/gen-social-catalogue.mjs --selftest every refusal bites
//
// REFUSES (throws, nothing written): a price that is not a whole positive number of gold; a name or tag length out of the clans
// table's own bounds; slow mode steps that are not strictly rising in both the room's rate and the wait; a batch that waits longer than
// it sends, or more lines than a message holds; a friend link window past 30 days.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_NAME = '1040-social-catalogue.generated.sql';
const OUT = join(ROOT, 'supabase', 'migrations', OUT_NAME);

const int = (v, lo, hi, what) => { if (!Number.isInteger(v) || v < lo || v > hi) throw new Error('gen-social-catalogue: ' + what + ' ' + v + ' outside [' + lo + ', ' + hi + ']'); return v; };

/** The four tables' rows from the data (D: { clan, batch, slow, link }), checked. */
export function catalogueOf(D) {
  const c = D.clan || {};
  const clan = {
    found: int(c.foundGold, 1, 1000000000, 'foundGold'),
    nameMin: int(c.nameMin, 3, 24, 'nameMin'), nameMax: int(c.nameMax, 3, 24, 'nameMax'),
    tagMin: int(c.tagMin, 1, 8, 'tagMin'), tagMax: int(c.tagMax, 1, 8, 'tagMax'),
    browser: int(c.browserMax, 1, 200, 'browserMax'), invite: int(c.inviteDays, 1, 90, 'inviteDays'),
  };
  if (clan.nameMin > clan.nameMax || clan.tagMin > clan.tagMax) throw new Error('gen-social-catalogue: a length whose least is past its most');
  const b = D.batch || {};
  const batch = { every: int(b.everyS, 1, 59, 'everyS'), settle: int(b.settleS, 0, 30, 'settleS'), max: int(b.maxLines, 1, 500, 'maxLines') };
  if (batch.settle >= batch.every) throw new Error('gen-social-catalogue: a batch that waits ' + batch.settle + ' s to send every ' + batch.every + ' s');
  const slow = (Array.isArray(D.slow) ? D.slow : []).map((s, i) => ({ rate: int(s.linesPerMin, 1, 100000, 'SLOW_MODE[' + i + '].linesPerMin'), gap: int(s.gapS, 1, 3600, 'SLOW_MODE[' + i + '].gapS') }));
  if (!slow.length) throw new Error('gen-social-catalogue: no slow mode step');
  for (let i = 1; i < slow.length; i++) {
    if (slow[i].rate <= slow[i - 1].rate || slow[i].gap <= slow[i - 1].gap) throw new Error('gen-social-catalogue: slow mode step ' + i + ' does not tighten as the room grows');
  }
  const link = { hours: int((D.link || {}).newAccountHours, 1, 720, 'newAccountHours') };
  return { clan, batch, slow, link };
}

/** The SQL for the catalogue `c`. */
export function buildSql(c) {
  const steps = c.slow.map((s) => `(${s.rate}, ${s.gap})`).join(', ');
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE SOCIAL LAYER'S SERVER RULES  (GENERATED — DO NOT EDIT)
--
--   Generated by tools/gen-social-catalogue.mjs from src/data/clans.js (CLAN_RULES) and src/data/chat-channels.js (GLOBAL_BATCH,
--   SLOW_MODE, FRIEND_LINK). Any hand edit FAILS \`node tools/gen-social-catalogue.mjs --check\`.
--
-- STATUS: supabase/migration-notes/${OUT_NAME}.json (STAGED until the Coordinator applies it; lane/c-social, backend-architect, FB-12).
-- The Coordinator applies (tools/apply-migration.mjs, one file, never inside begin/commit). ON THE EA SECURITY LIST with
-- 1041-social-clans.sql: hr_clan_rules.found_gold is a price.
-- WHAT: four server-only catalogues, each rewritten whole. No function, grant or client verb.
-- ORDER: before 1041-social-clans.sql and 1044-friend-link.sql, which read them (the name sorts first in its sequence).
-- Idempotent: the tables are made if absent and every row rewritten whole, so a second apply is byte-identical. No begin/commit.
-- REVERSIBLE: drop the four tables (1036 and 1038 first: they read them).
-- ════════════════════════════════════════════════════════════════════════

-- ── §1 THE TABLES ────────────────────────────────────────────────────────────
create table if not exists public.hr_clan_rules (
  id          boolean primary key default true check (id),
  found_gold  bigint  not null check (found_gold between 1 and 1000000000),
  name_min    int     not null check (name_min between 1 and 24),
  name_max    int     not null check (name_max between 1 and 24),
  tag_min     int     not null check (tag_min between 1 and 8),
  tag_max     int     not null check (tag_max between 1 and 8),
  browser_max int     not null check (browser_max between 1 and 200),
  invite_days int     not null check (invite_days between 1 and 90),
  check (name_min <= name_max and tag_min <= tag_max)
);
create table if not exists public.hr_chat_global_rule (
  id        boolean primary key default true check (id),
  every_s   int not null check (every_s between 1 and 59),
  settle_s  int not null check (settle_s between 0 and 30),
  max_lines int not null check (max_lines between 1 and 500)
);
create table if not exists public.hr_chat_slow_mode (
  lines_per_min int primary key check (lines_per_min between 1 and 100000),
  gap_s         int not null check (gap_s between 1 and 3600)
);
create table if not exists public.hr_friend_link_rule (
  id        boolean primary key default true check (id),
  new_hours int     not null check (new_hours between 1 and 720)
);
comment on table public.hr_clan_rules is '${OUT_NAME}: the clan rules (src/data/clans.js CLAN_RULES). Server-only.';
comment on table public.hr_chat_global_rule is '${OUT_NAME}: how Global is sent (src/data/chat-channels.js GLOBAL_BATCH; 31-1). Server-only.';
comment on table public.hr_chat_slow_mode is '${OUT_NAME}: Global''s slow mode, by the room''s lines in the last minute (src/data/chat-channels.js SLOW_MODE; 31-1). Server-only.';
comment on table public.hr_friend_link_rule is '${OUT_NAME}: how new an account must be to use a friend link (src/data/chat-channels.js FRIEND_LINK; GR-72). Server-only.';
alter table public.hr_clan_rules enable row level security;
alter table public.hr_chat_global_rule enable row level security;
alter table public.hr_chat_slow_mode enable row level security;
alter table public.hr_friend_link_rule enable row level security;
revoke all on public.hr_clan_rules from public, anon, authenticated, service_role;
revoke all on public.hr_chat_global_rule from public, anon, authenticated, service_role;
revoke all on public.hr_chat_slow_mode from public, anon, authenticated, service_role;
revoke all on public.hr_friend_link_rule from public, anon, authenticated, service_role;

-- ── §2 THE ROWS ──────────────────────────────────────────────────────────────
delete from public.hr_clan_rules;
insert into public.hr_clan_rules (id, found_gold, name_min, name_max, tag_min, tag_max, browser_max, invite_days)
  values (true, ${c.clan.found}, ${c.clan.nameMin}, ${c.clan.nameMax}, ${c.clan.tagMin}, ${c.clan.tagMax}, ${c.clan.browser}, ${c.clan.invite});
delete from public.hr_chat_global_rule;
insert into public.hr_chat_global_rule (id, every_s, settle_s, max_lines) values (true, ${c.batch.every}, ${c.batch.settle}, ${c.batch.max});
delete from public.hr_chat_slow_mode;
insert into public.hr_chat_slow_mode (lines_per_min, gap_s) values ${steps};
delete from public.hr_friend_link_rule;
insert into public.hr_friend_link_rule (id, new_hours) values (true, ${c.link.hours});

-- ── §3 SELF-CHECK (CLAUDE.md §4) ──────────────────────────────────────────────
-- The rows are exactly the generated sets; no client role reaches a table.
do $$
declare v_role text; v_t text;
begin
  if not exists (select 1 from public.hr_clan_rules r where r.id and (r.found_gold, r.name_min, r.name_max, r.tag_min, r.tag_max, r.browser_max, r.invite_days)
                   = (${c.clan.found}::bigint, ${c.clan.nameMin}, ${c.clan.nameMax}, ${c.clan.tagMin}, ${c.clan.tagMax}, ${c.clan.browser}, ${c.clan.invite}))
     or (select count(*) from public.hr_clan_rules) <> 1 then
    raise exception 'social-catalogue: hr_clan_rules is not the generated row'; end if;
  if not exists (select 1 from public.hr_chat_global_rule r where r.id and (r.every_s, r.settle_s, r.max_lines) = (${c.batch.every}, ${c.batch.settle}, ${c.batch.max}))
     or (select count(*) from public.hr_chat_global_rule) <> 1 then
    raise exception 'social-catalogue: hr_chat_global_rule is not the generated row'; end if;
  if (select count(*) from public.hr_chat_slow_mode) <> ${c.slow.length}
     or exists (select 1 from (values ${steps}) d(lines_per_min, gap_s)
                 where not exists (select 1 from public.hr_chat_slow_mode s where s.lines_per_min = d.lines_per_min and s.gap_s = d.gap_s)) then
    raise exception 'social-catalogue: hr_chat_slow_mode is not the generated set'; end if;
  if not exists (select 1 from public.hr_friend_link_rule r where r.id and r.new_hours = ${c.link.hours}) or (select count(*) from public.hr_friend_link_rule) <> 1 then
    raise exception 'social-catalogue: hr_friend_link_rule is not the generated row'; end if;
  foreach v_t in array array['hr_clan_rules', 'hr_chat_global_rule', 'hr_chat_slow_mode', 'hr_friend_link_rule'] loop
    foreach v_role in array array['anon', 'authenticated'] loop
      if has_table_privilege(v_role, ('public.' || v_t)::regclass, 'select,insert,update,delete') then
        raise exception 'social-catalogue: % reaches %', v_role, v_t; end if;
    end loop;
  end loop;
end $$;
`;
}

export async function loadData(root) {
  const u = (p) => pathToFileURL(join(root, p)).href;
  const C = await import(u('src/data/clans.js'));
  const H = await import(u('src/data/chat-channels.js'));
  return { clan: C.CLAN_RULES, batch: H.GLOBAL_BATCH, slow: H.SLOW_MODE, link: H.FRIEND_LINK };
}

async function selftest() {
  const D = await loadData(ROOT);
  let bad = 0;
  const expectThrow = (name, Dx) => { try { catalogueOf(Dx); console.error('  MISSED  ' + name); bad++; } catch { console.log('  caught  ' + name); } };
  expectThrow('a price of no gold', { ...D, clan: { ...D.clan, foundGold: 0 } });
  expectThrow('a price that is not whole', { ...D, clan: { ...D.clan, foundGold: 100.5 } });
  expectThrow('a name shorter than the table allows', { ...D, clan: { ...D.clan, nameMin: 2 } });
  expectThrow('a tag whose least is past its most', { ...D, clan: { ...D.clan, tagMin: 5, tagMax: 4 } });
  expectThrow('a slow mode that loosens as the room grows', { ...D, slow: [{ linesPerMin: 12, gapS: 30 }, { linesPerMin: 30, gapS: 10 }] });
  expectThrow('no slow mode at all', { ...D, slow: [] });
  expectThrow('a batch that waits longer than it sends', { ...D, batch: { ...D.batch, settleS: D.batch.everyS } });
  expectThrow('a friend link window past 30 days', { ...D, link: { newAccountHours: 721 } });
  if (bad) { console.error('gen-social-catalogue --selftest: ' + bad + ' refusal(s) did not bite'); process.exit(1); }
  console.log('gen-social-catalogue --selftest: every refusal bites');
}

async function main() {
  if (process.argv.includes('--selftest')) return selftest();
  const wanted = buildSql(catalogueOf(await loadData(ROOT)));
  if (process.argv.includes('--check')) {
    const have = await readFile(OUT, 'utf8').catch(() => '');
    if (have.replace(/\r\n/g, '\n') !== wanted) { console.error('gen-social-catalogue --check FAILED: ' + OUT_NAME + ' is stale. Run: node tools/gen-social-catalogue.mjs'); process.exit(1); }
    console.log('gen-social-catalogue --check: ' + OUT_NAME + ' matches src/data/clans.js and src/data/chat-channels.js');
    return;
  }
  await writeFile(OUT, wanted);
  console.log('gen-social-catalogue: wrote ' + OUT_NAME);
}

if (isMain(import.meta.url)) main().catch((e) => { console.error(e && e.stack ? e.stack : e); process.exit(1); });

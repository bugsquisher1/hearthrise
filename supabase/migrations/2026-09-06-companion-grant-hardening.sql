   where n.nspname = 'public' and p.proname = 'hr_companion_grant';
  if v_n <> 1 then
    raise exception '§3(a): % definitions of hr_companion_grant exist. This file REPLACES one body; '
                    'an overload means the pre-hardening function is still callable.', v_n;
  end if;

  -- (b) THE ACL IS BYTE-IDENTICAL ACROSS THE REPLACE. Fails closed if §0's
  --     hand-off is unreadable, which means the file was not applied in one
  --     transaction and this assertion would otherwise be silently vacuous.

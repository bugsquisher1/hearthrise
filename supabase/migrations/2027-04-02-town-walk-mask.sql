-- STATUS: STAGED, NOT APPLIED. The Coordinator applies (tools/apply-migration.mjs, one file, never inside begin/commit).
-- Pre-EA: applies on its passing §2. On the EA Security list (a client verb's body; it moves no value).
-- ORDER: after 2027-04-02-rate-refusals-recorded.sql (§0 pins ITS image of hr_town_move) and after
-- 2027-04-02-town-walk-mask.generated.sql (the mask and its reader). BEFORE any client that draws a town map whose blocking
-- tiles differ from the mask's (none today: the mask is cut from v0.2.114's Havora, the map production serves).
-- It touches none of hr_apply, hr_state_of, hr_load or the settle path. DB-ONLY: no hr-accrue change, no client change
-- (src/session/town-presence.js already treats a refused publish as not sent, and an honest hero's feet never leave the
-- mask: src/world/steer-local.js walks open tiles from a server stand, and the mask is those tiles).
--
-- ── THE RULE ─────────────────────────────────────────────────────────────────
-- hr_town_move takes a tile to stand on (p_x, p_y) and a tile walked to (p_gx, p_gy). BOTH must be on the town map's walk
-- mask (hr_town_walk, generated by tools/gen-town-walk.mjs from the map the World draws: open, and walked to from the
-- map's start). Off the mask the publish is refused `off_mask` and journalled (hr_rejections, verb town_move, the four
-- numbers in the detail); the stored tile, the body and its stand are NOT touched, so everyone keeps seeing the hero where
-- it last honestly stood. A map with no mask refuses `catalogue_missing`, journalled too: a position is never taken
-- unchecked (the generated file's own self-check holds a mask for every town map and every stand on it).
--
-- ── WHAT ─────────────────────────────────────────────────────────────────────
--   hr_town_move RESTATED WHOLE from 2027-04-02-rate-refusals-recorded.sql's image (§0 pins it): four lines added, each
--       marked `-- TOWN-WALK-MASK` (one variable, the read, the two refusals), after the rectangle check and before the
--       hunting check, the floor and the write. §2(g) takes them back out and requires the pinned pre-image.
--
-- ── NOT HERE (stated, not forgotten) ─────────────────────────────────────────
-- A SPEED BOUND (the audit's second half: "a per-call distance cap from the stored position and elapsed time"). A hero can
-- still publish any ON-mask tile, so it can appear to jump across town. Bounding that needs the client's walk pace and
-- every server placement (a stand given by hr_town_go, a hunt's return, a first publish) agreed in one contract with the
-- Systems Engineer; refusing an honest hero for lag would be worse than the jump, which shows no wall-walking and moves
-- no value. Listed for the EA Security review.
--
-- ── EXPLOIT SURFACE DELTA ───────────────────────────────────────────────────
-- Narrows a client door; opens none. hr_town_walk_ok and hr_town_walk hold no client grant. The refusal answers with the
-- caller's own four numbers and nothing of the map. The journal row is the caller's own (one a slot, day and code).
--
-- ── CONCURRENCY / IDEMPOTENCY ───────────────────────────────────────────────
-- One more PK read (hr_town_walk, one row a town, kept inline) before the write hr_town_move already made; no lock added,
-- none reordered. A refused publish writes only the caller's hr_rejections row. A second apply: §0 accepts this file's
-- own image; `create or replace` (byte-identical).
--
-- ── COST AT 100x ────────────────────────────────────────────────────────────
-- A walking hero publishes at most once a second (the client's floor; 90 a minute at the server's): one extra indexed
-- read of a 2.8 KB row each. 2,000 players walking at once is 2,000 such reads a second at the very worst, each a single
-- page. Rows: one a town map. Refusals: none from an honest client; a forging one is rate-limited to 90 a minute and
-- writes one journal row a day.
--
-- REVERSIBILITY: re-apply 2027-04-02-rate-refusals-recorded.sql's hr_town_move (the pre-image §0 pins); the mask table
-- and its reader may stay (nothing else reads them). No data moves. No begin/commit (CLAUDE.md §2).

#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-ground-tiers.mjs — GENERATE THE SERVER'S TIER CATALOGUE (hr_ground_tiers).
//
// src/data/hunt-tiers.js GROUND_TIERS is the one source of a ground's harder tiers (pull per party size, the monsters'
// power, the XP a kill pays). The engine reads the data; the server reads hr_ground_tiers when it freezes a hunt's pull
// (hr_hunt_tier_set, the freeze in 2027-02-27-hunt-tiers.sql). This writes the rows, rewritten whole, and a self-check.
// tests/hunt-core/hunt-tiers.mjs `catalogue` holds the file's insert equal to the data digit for digit (the CI guard).
//
// THE FORWARD-FILE RULE: an applied file is history and is never regenerated in place; new rows are a new dated file
// (OUT_NAME). 2027-02-27-hunt-tiers.sql (APPLIED) made the table and its first rows by hand.
//   2027-03-19-tier-risk.generated.sql (lane/b-tier-risk, Tyler 2026-11-06 "Yes, make it risky"): a lone hero's
//   harder tier on Wickstead and the Glade carries real risk; parties keep their pulls.
//   2027-03-20-glade-bite-tiers.generated.sql (lane/b-glade-bite, Tyler 2026-11-07 "make it 20% harder"): the Glade's monsters hit 1.2x
//   on Normal in their own rows, so its tier powers come down to keep each tier where it was played.
//
//   node tools/gen-ground-tiers.mjs            write OUT_NAME
//   node tools/gen-ground-tiers.mjs --check    exit 1 if OUT_NAME is not what it would write
//   node tools/gen-ground-tiers.mjs --selftest every refusal bites
//
// REFUSES (throws, nothing written): a row the table's checks would refuse (power 1000-4000, XP 1000-2000, four pulls
// of 0-12), a harder tier that isn't harder and better paid than the one before, and the Glade's or the Warrens'
// Deadly without its full box (Tyler 10-18).
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_NAME = '2027-03-20-glade-bite-tiers.generated.sql';
const OUT = join(ROOT, 'supabase', 'migrations', OUT_NAME);
const HARDER = ['dangerous', 'deadly'];
const FULL_BOX_GROUNDS = ['mosslight_glade', 'coppercap_warrens'];

/** The SQL for `tiers` (GROUND_TIERS' shape). */
export function buildSql(tiers) {
  const rows = [];
  for (const [ground, byTier] of Object.entries(tiers)) {
    let was = { powerPm: 1000, xpPm: 1000 };
    for (const id of HARDER) {
      const t = byTier[id];
      if (!t) throw new Error('gen-ground-tiers: ' + ground + ' has no ' + id + ' row');
      if (!Array.isArray(t.pull) || t.pull.length !== 4 || t.pull.some((p) => !Number.isInteger(p) || p < 0 || p > 12)) throw new Error('gen-ground-tiers: ' + ground + ' ' + id + ' pull ' + t.pull);
      if (!Number.isInteger(t.powerPm) || t.powerPm < 1000 || t.powerPm > 4000) throw new Error('gen-ground-tiers: ' + ground + ' ' + id + ' power ' + t.powerPm);
      if (!Number.isInteger(t.xpPm) || t.xpPm < 1000 || t.xpPm > 2000) throw new Error('gen-ground-tiers: ' + ground + ' ' + id + ' XP ' + t.xpPm);
      if (!(t.powerPm > was.powerPm) || !(t.xpPm > was.xpPm)) throw new Error('gen-ground-tiers: ' + ground + ' ' + id + ' is not harder and better paid than the tier before');
      was = t;
      rows.push([ground, id, t.pull, t.powerPm, t.xpPm]);
    }
  }
  for (const g of FULL_BOX_GROUNDS) if (tiers[g] && tiers[g].deadly.pull.some((p) => p !== 8)) throw new Error('gen-ground-tiers: ' + g + ' Deadly lost its full box');
  const values = rows.map(([g, id, pull, p, x]) => `  ('${g}', '${id}', '{${pull.join(',')}}'::int[], ${p}, ${x})`).join(',\n');
  /* the self-check's copy is written another way on purpose: the catalogue guard reads the insert's form only */
  const check = rows.map(([g, id, pull, p, x]) => `(${["'" + g + "'", "'" + id + "'", 'array[' + pull.join(',') + ']', p, x].join(',')})`).join(',\n      ');
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE HARDER TIERS' CATALOGUE  (GENERATED — DO NOT EDIT)
--
--   Generated by tools/gen-ground-tiers.mjs from src/data/hunt-tiers.js GROUND_TIERS. Any hand edit FAILS
--   \`node tools/gen-ground-tiers.mjs --check\` and tests/hunt-core/hunt-tiers.mjs \`catalogue\`.
--
-- WHAT: hr_ground_tiers (made by 2027-02-27-hunt-tiers.sql, APPLIED) rewritten whole, ${rows.length} rows: per ground and tier the
-- pull for one to four heroes (0 = the ground as it stands), the monsters' power and the XP a kill pays, permille. Normal is
-- no row and doesn't move. ROWS ONLY: no table, function, grant or client verb changes. The server reads the pull when it
-- freezes a hunt; the engine reads the same numbers from the data, so the hr-accrue deploy carrying this GROUND_TIERS
-- follows AT ONCE (a hunt already running keeps the pull it froze; its blows read the deployed engine).
-- NEW IN 2027-03-20 (lane/b-glade-bite, Tyler 2026-11-07 "make it 20% harder"): the Glade's monsters hit 1.2x on Normal in their
-- own rows (src/data/monsters.js, the engine), and a tier multiplies them, so the Glade's Dangerous power goes 1400 to 1200 and its
-- Deadly 1600 to 1350: each tier plays where it did. Every other row is as in 2027-03-19.
-- ORDER: after 2027-03-19-tier-risk.generated.sql. No begin/commit (CLAUDE.md §2).
-- ════════════════════════════════════════════════════════════════════════

-- ── §0 PRECONDITIONS ─────────────────────────────────────────────────────────
do $mig$
begin
  if to_regclass('public.hr_ground_tiers') is null then
    raise exception 'PRECONDITION: apply 2027-02-27-hunt-tiers.sql first (the table this file fills)'; end if;
end $mig$;

-- ── §1 THE ROWS ──────────────────────────────────────────────────────────────
comment on table public.hr_ground_tiers is
  '${OUT_NAME}: the harder tiers a ground offers (src/data/hunt-tiers.js through tools/gen-ground-tiers.mjs; tests/hunt-core/hunt-tiers.mjs holds the two equal). Read by hr_hunt_tier_set and the freeze. No row = not offered. Normal is no row.';
delete from public.hr_ground_tiers;
insert into public.hr_ground_tiers (hunt_id, tier, pull, power_pm, xp_pm) values
${values};

-- ── §2 SELF-CHECK (CLAUDE.md §4) ──────────────────────────────────────────────
-- The rows are exactly the generated set; on every ground Deadly is harder and better paid than Dangerous; the Glade and the
-- Warrens keep their full box on Deadly; no client reaches the table.
do $$
declare v_role text;
begin
  if (select count(*) from public.hr_ground_tiers) <> ${rows.length}
     or exists (select 1 from (values
      ${check}) d(hunt_id, tier, pull, power_pm, xp_pm)
                 where not exists (select 1 from public.hr_ground_tiers t where t.hunt_id = d.hunt_id and t.tier = d.tier
                                     and t.pull = d.pull and t.power_pm = d.power_pm and t.xp_pm = d.xp_pm)) then
    raise exception 'tier-risk: hr_ground_tiers is not the generated %-row set', ${rows.length}; end if;
  if exists (select 1 from public.hr_ground_tiers a join public.hr_ground_tiers b on b.hunt_id = a.hunt_id and b.tier = 'deadly'
              where a.tier = 'dangerous' and (b.power_pm <= a.power_pm or b.xp_pm <= a.xp_pm)) then
    raise exception 'tier-risk: a ground''s Deadly is not harder and better paid than its Dangerous'; end if;
  if exists (select 1 from public.hr_ground_tiers t where t.tier = 'deadly' and t.hunt_id in ('mosslight_glade', 'coppercap_warrens') and t.pull <> array[8,8,8,8]) then
    raise exception 'tier-risk: the Glade or the Warrens lost its full box on Deadly'; end if;
  foreach v_role in array array['anon', 'authenticated'] loop
    if has_table_privilege(v_role, 'public.hr_ground_tiers', 'select,insert,update,delete') then
      raise exception 'tier-risk: % reaches hr_ground_tiers', v_role; end if;
  end loop;
end $$;
`;
}

async function loadTiers(root) {
  const { BUILD } = await import(pathToFileURL(join(root, 'src/build-info.js')).href);
  return (await import(pathToFileURL(join(root, 'src/data/hunt-tiers.js')).href + '?v=' + BUILD.version)).GROUND_TIERS;
}

async function selftest() {
  const T = await loadTiers(ROOT);
  let bad = 0;
  const copy = () => JSON.parse(JSON.stringify(T));
  const expectThrow = (name, edit) => { const t = copy(); edit(t); try { buildSql(t); console.error('  MISSED  ' + name); bad++; } catch { console.log('  caught  ' + name); } };
  expectThrow('a Deadly no harder than its Dangerous', (t) => { t.wickstead.deadly.powerPm = t.wickstead.dangerous.powerPm; });
  expectThrow('a Deadly paying no more than its Dangerous', (t) => { t.mosslight_glade.deadly.xpPm = t.mosslight_glade.dangerous.xpPm; });
  expectThrow('a power the table refuses', (t) => { t.wickstead.deadly.powerPm = 4500; });
  expectThrow('three pulls for four sizes', (t) => { t.wickstead.dangerous.pull = [0, 4, 4]; });
  expectThrow('the Glade without its full box', (t) => { t.mosslight_glade.deadly.pull = [4, 8, 8, 8]; });
  expectThrow('a ground with no Deadly', (t) => { delete t.millrace_sewer.deadly; });
  const sql = buildSql(T);
  const inserts = [...sql.matchAll(/\('([a-z_]+)', '([a-z]+)', '\{([0-9,]+)\}'::int\[\], (\d+), (\d+)\)/g)].length;
  if (inserts !== Object.keys(T).length * HARDER.length) { console.error('  MISSED  the catalogue guard would read ' + inserts + ' rows'); bad++; }
  else console.log('  caught  a self-check the catalogue guard would read twice');
  if (bad) { console.error('gen-ground-tiers --selftest: ' + bad + ' refusal(s) did not bite'); process.exit(1); }
  console.log('gen-ground-tiers --selftest: every refusal bites');
}

async function main() {
  if (process.argv.includes('--selftest')) return selftest();
  const wanted = buildSql(await loadTiers(ROOT));
  if (process.argv.includes('--check')) {
    const have = await readFile(OUT, 'utf8').catch(() => '');
    if (have.replace(/\r\n/g, '\n') !== wanted) { console.error('gen-ground-tiers --check FAILED: ' + OUT_NAME + ' is stale. Run: node tools/gen-ground-tiers.mjs'); process.exit(1); }
    console.log('gen-ground-tiers --check: ' + OUT_NAME + ' matches src/data/hunt-tiers.js GROUND_TIERS');
    return;
  }
  await writeFile(OUT, wanted);
  console.log('gen-ground-tiers: wrote ' + OUT_NAME);
}

if (isMain(import.meta.url)) main().catch((e) => { console.error(e && e.stack ? e.stack : e); process.exit(1); });

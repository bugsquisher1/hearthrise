#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-time-blocks.mjs — GENERATE THE SERVER'S BOUGHT-TIME CATALOGUE (lane/r8-hunting-day; 04-math-strategy.md section 11).
//
// src/data/time-blocks.js is the one source of the block rule (TIME_BLOCKS: a block's minutes, the day's cap, the growth and the
// price levers, one row a kind). The server reads this table when it quotes and sells a block (1058-hunting-blocks.sql
// hr_time_quote, hr_time_buy). This writes it whole, with the SQL twin of the price and a self-check:
//   hr_time_blocks                    per kind: block_min, per_day, growth_num, growth_den, base, per_level
//   hr_time_block_price(kind, L, n)   time-blocks.js blockPrice: the gold block n of the day costs a hero of Level L (null past the cap)
//
// THE FORWARD-FILE RULE: an applied file is history and is never regenerated in place; new rows are a new sequence file (OUT_NAME).
//
//   node tools/gen-time-blocks.mjs            write OUT_NAME
//   node tools/gen-time-blocks.mjs --check    exit 1 if OUT_NAME is not what it would write
//   node tools/gen-time-blocks.mjs --selftest every refusal bites
//
// mutant-anchors: none — --selftest plants defects in an in-memory copy of the data; no tracked file is patched
//
// REFUSES (throws, nothing written): a table time-blocks.js validate() refuses (a non-positive number, a later block cheaper than the
// one before it, a ruled number moved), a kind that is not a lower-case word, and an empty table.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';
import { sourceQuery } from './lib/version-stamp.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_NAME = '1058-hunting-blocks-catalogue.generated.sql';
const OUT = join(ROOT, 'supabase', 'migrations', OUT_NAME);
/* the Levels the SQL twin is pinned at, each at every block of the day (the self-check) */
export const PIN_LEVELS = Object.freeze([1, 10, 50, 300, 2000]);

async function load(root) {
  return import(pathToFileURL(join(root, 'src/data/time-blocks.js')).href + sourceQuery(root));
}

/** The resolved rows of the data, refused on a defect. */
export function rowsOf(data) {
  const problems = data.validate();
  if (problems.length) throw new Error('gen-time-blocks: ' + problems.join('; '));
  const kinds = Object.keys(data.TIME_BLOCKS).sort();
  if (!kinds.length) throw new Error('gen-time-blocks: the table holds no kind');
  const rows = kinds.map((kind) => {
    const R = data.TIME_BLOCKS[kind];
    if (!/^[a-z]{1,16}$/.test(kind)) throw new Error('gen-time-blocks: kind ' + kind + ' is not a lower-case word');
    return { kind, blockMin: R.blockMin, perDay: R.perDay, growthNum: R.growthNum, growthDen: R.growthDen, base: R.base, perLevel: R.perLevel };
  });
  const pins = [];
  for (const r of rows) {
    for (const L of PIN_LEVELS) for (let n = 1; n <= r.perDay + 1; n++) pins.push({ kind: r.kind, L, n, price: data.blockPrice({ kind: r.kind, level: L, n }) });
  }
  return { rows, pins };
}

export function buildSql(r) {
  const values = r.rows.map((x) => `  ('${x.kind}', ${x.blockMin}, ${x.perDay}, ${x.growthNum}, ${x.growthDen}, ${x.base}, ${x.perLevel})`).join(',\n');
  const pinValues = r.pins.map((p) => `    ('${p.kind}', ${p.L}, ${p.n}, ${p.price === null ? 'null' : p.price}::bigint)`).join(',\n');
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE BOUGHT-TIME CATALOGUE  (GENERATED — DO NOT EDIT)
--
--   Generated by tools/gen-time-blocks.mjs from src/data/time-blocks.js (TIME_BLOCKS, blockPrice).
--   Any hand edit FAILS \`node tools/gen-time-blocks.mjs --check\`.
--
-- WHAT (lane/r8-hunting-day, backend-architect, 2026-11-22; Tyler's rulings of 2026-11-22, 04-math-strategy.md section 11): the block
-- rule the server reads, so no number is typed twice. hr_time_blocks (${r.rows.length} row${r.rows.length === 1 ? '' : 's'}: ${r.rows.map((x) => x.kind).join(', ')}), rewritten whole;
-- hr_time_block_price(kind, level, n), internal (no client grant), the twin of time-blocks.js blockPrice, pinned to the JS value at
-- Levels ${PIN_LEVELS.join(', ')} for every block of the day and the first one past it (§3).
-- READERS: 1058-hunting-blocks.sql's quote (hr_time_quote), the \`time_blocks\` section and the verb hr_time_buy. The client reads only
-- the section. The price's base and per_level are a LEVER (econ.hunt-block) until wage(L) exists.
-- ORDER: 1058 in its name, before 1058-hunting-blocks.sql (which reads this table). Idempotent: the table is made if missing and its
-- rows rewritten whole, the function restated, so a second apply is byte-identical. No begin/commit (CLAUDE.md §2).
-- EXPLOIT SURFACE: none added. A catalogue table, RLS on, no policy, no grant to any client role; one internal function revoked from
-- every client role. No value moves here.
-- REVERSIBLE: drop the function and the table (after 1058-hunting-blocks.sql's readers are gone).
-- ════════════════════════════════════════════════════════════════════════

-- ── §0 PRECONDITIONS ─────────────────────────────────────────────────────────
do $mig$
begin
  if to_regclass('public.player_ledger') is null then
    raise exception 'PRECONDITION: the ledger first (player_ledger)'; end if;
end $mig$;

-- ── §1 THE TABLE ─────────────────────────────────────────────────────────────
create table if not exists public.hr_time_blocks (
  kind       text   primary key check (kind ~ '^[a-z]{1,16}$'),
  block_min  int    not null check (block_min between 1 and 1440),
  per_day    int    not null check (per_day between 1 and 24),
  growth_num int    not null check (growth_num >= 1),
  growth_den int    not null check (growth_den >= 1),
  base       bigint not null check (base >= 1),
  per_level  bigint not null check (per_level >= 0),
  check (growth_num >= growth_den)
);
alter table public.hr_time_blocks enable row level security;
revoke all on public.hr_time_blocks from public, anon, authenticated, service_role;
comment on table public.hr_time_blocks is '${OUT_NAME}: bought time, one row a kind (src/data/time-blocks.js through tools/gen-time-blocks.mjs).';

-- ── §2 THE ROWS ──────────────────────────────────────────────────────────────
delete from public.hr_time_blocks;
insert into public.hr_time_blocks (kind, block_min, per_day, growth_num, growth_den, base, per_level) values
${values};

-- ── §2b THE PRICE'S SQL TWIN (internal) ──────────────────────────────────────
create or replace function public.hr_time_block_price(p_kind text, p_level int, p_n int)
returns bigint language plpgsql stable set search_path = public, pg_catalog as $fn$
declare r public.hr_time_blocks%rowtype; v_l int := greatest(1, coalesce(p_level, 1));
begin
  -- BOUGHT TIME (${OUT_NAME}): time-blocks.js blockPrice, the gold block p_n (1 for the day's first) of p_kind costs a hero of Level p_level.
  select * into r from public.hr_time_blocks where kind = p_kind;
  if not found or p_n is null or p_n < 1 or p_n > r.per_day then return null; end if;
  return ceil(((r.base + r.per_level * v_l)::numeric * power(r.growth_num::numeric, p_n - 1)) / power(r.growth_den::numeric, p_n - 1))::bigint;
end $fn$;
revoke execute on function public.hr_time_block_price(text, int, int) from public, anon, authenticated, service_role;
do $mig$
begin
  if exists (select 1 from pg_roles where rolname = 'hr_engine') then
    revoke execute on function public.hr_time_block_price(text, int, int) from hr_engine; end if;
  if exists (select 1 from pg_roles where rolname = 'hr_tick') then
    revoke execute on function public.hr_time_block_price(text, int, int) from hr_tick; end if;
end $mig$;

-- ── §3 SELF-CHECK (CLAUDE.md §4) ──────────────────────────────────────────────
-- Every row is the data's; no client role reads the table or runs the twin; the twin answers the data's price at the pinned Levels for
-- every block of the day, and null for the first block past the day's cap.
do $mig$
declare v_r record; v_p bigint;
begin
  if (select count(*) from public.hr_time_blocks) <> ${r.rows.length} then
    raise exception 'VERIFY(a): the catalogue holds % kinds, want ${r.rows.length}', (select count(*) from public.hr_time_blocks); end if;
  if exists (select 1 from unnest(array['anon', 'authenticated']) g(r)
              where has_table_privilege(g.r, 'public.hr_time_blocks', 'select')
                 or has_function_privilege(g.r, 'public.hr_time_block_price(text,integer,integer)', 'execute')) then
    raise exception 'VERIFY(b): a client role reads the bought-time catalogue'; end if;
  for v_r in select * from (values
${pinValues}) p(kind, l, n, price) loop
    v_p := public.hr_time_block_price(v_r.kind, v_r.l, v_r.n);
    if v_p is distinct from v_r.price then
      raise exception 'VERIFY(c): % block % at Level % costs % in SQL, % in the data', v_r.kind, v_r.n, v_r.l, v_p, v_r.price; end if;
  end loop;
  raise notice 'gen-time-blocks: % kind(s), the twin pinned at % prices; all green', ${r.rows.length}, ${r.pins.length};
end $mig$;
`;
}

export async function generate(root = ROOT) { return buildSql(rowsOf(await load(root))); }

async function selftest() {
  const base = await load(ROOT);
  const bites = [];
  const plant = (name, patch) => {
    const T = JSON.parse(JSON.stringify(base.TIME_BLOCKS));
    patch(T);
    /* the data module's own validate, read over the planted table */
    const data = { TIME_BLOCKS: T, validate: () => base.validate(T), blockPrice: base.blockPrice };
    try { rowsOf(data); bites.push(name + ': NOT refused'); } catch { /* refused */ }
  };
  plant('a later block cheaper than the one before it', (T) => { T.hunt.growthNum = 1; T.hunt.growthDen = 2; });
  plant('the ruled cap moved', (T) => { T.hunt.perDay = 4; });
  plant('the ruled block length moved', (T) => { T.hunt.blockMin = 240; });
  plant('a free block', (T) => { T.hunt.base = 0; });
  plant('a kind that is no word', (T) => { T['Hunt-2'] = { ...T.hunt }; });
  plant('an empty table', (T) => { delete T.hunt; });
  /* the shipped validate refuses what the planted one does (the plant above reads the same rules) */
  if (base.validate().length) bites.push('the shipped table is refused: ' + base.validate().join('; '));
  const sql = buildSql(rowsOf(base));
  if (!/VERIFY\(c\)/.test(sql) || !/hr_time_block_price/.test(sql)) bites.push('the twin is not pinned');
  if (bites.length) { console.error('gen-time-blocks --selftest FAILED:\n  ' + bites.join('\n  ')); process.exit(1); }
  console.log('gen-time-blocks --selftest: 6 refusals bite, the twin is pinned');
}

if (isMain(import.meta.url)) {
  if (process.argv.includes('--selftest')) await selftest();
  else {
    const sql = await generate();
    if (process.argv.includes('--check')) {
      const have = await readFile(OUT, 'utf8').catch(() => '');
      if (have.replace(/\r/g, '') !== sql) { console.error('gen-time-blocks --check FAILED: ' + OUT_NAME + ' is stale. Run: node tools/gen-time-blocks.mjs'); process.exit(1); }
      console.log('gen-time-blocks --check: catalogue matches src/data');
    } else {
      await writeFile(OUT, sql);
      console.log('wrote ' + OUT);
    }
  }
}

declare v_md5 text;
begin
  if to_regclass('public.hr_town_walk') is null or to_regprocedure('public.hr_town_walk_ok(text,integer,integer,integer,integer)') is null then
    raise exception 'PRECONDITION: the walk mask is absent (2027-04-02-town-walk-mask.generated.sql first)'; end if;
  if to_regprocedure('public.hr_note_rejection(text,integer,jsonb)') is null or to_regprocedure('public.hr_rate_refused(uuid,integer,text,integer,interval)') is null then
    raise exception 'PRECONDITION: hr_note_rejection / hr_rate_refused are absent (2027-04-02-rate-refusals-recorded.sql first)'; end if;
  v_md5 := md5(regexp_replace(pg_get_functiondef('public.hr_town_move(integer,text,integer,integer,integer,integer,text)'::regprocedure), '[[:space:]]+', ' ', 'g'));
  if v_md5 not in ('f17722883f848431992cc8634fcb5ece', '72ee16c7d8bcdbb5ae17640d6202d8ad') then
    raise exception 'PIN: hr_town_move is neither 2027-04-02-rate-refusals-recorded.sql''s image (f17722883f848431992cc8634fcb5ece) nor this file''s: md5 % - another file moved it', v_md5; end if;
end $mig$;

-- ── §1 hr_town_move RESTATED WHOLE (each `-- TOWN-WALK-MASK` line is this file's; nothing else differs) ──

CREATE OR REPLACE FUNCTION public.hr_town_move(p_slot integer, p_map text, p_x integer, p_y integer, p_gx integer, p_gy integer, p_dir text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_catalog'
AS $function$
declare
  -- The floor: a write inside this of the last is answered and not made. The
  -- client publishes at most once a second (src/data/town-presence.js).
  c_floor   constant interval := interval '250 milliseconds';
  c_per_min constant int := 90;
  v_uid  uuid := auth.uid();
  v_slot int := coalesce(p_slot, -1);
  v_map  public.hr_town_maps%rowtype;
  v_last timestamptz;
  v_on   boolean;  -- TOWN-WALK-MASK: may a hero stand on the tile it says, walking to the tile it says
begin
  -- TOWN-STANDS (2027-01-28-town-stands.sql): a body is placed on the first publish; moved_at is a real move only.
  if v_uid is null then return jsonb_build_object('ok', false, 'error', 'not_signed_in'); end if;
  perform public.hr_access_check();
  if not public.hr_flag_on('town_presence') then return jsonb_build_object('ok', true, 'off', true); end if;
  if not public.hr_rate_ok(v_uid, 'town_move', c_per_min, interval '1 minute') then
    perform public.hr_rate_refused(v_uid, p_slot, 'town_move', c_per_min, interval '1 minute');  -- RATE-JOURNAL
    return jsonb_build_object('ok', false, 'error', 'rate_limited'); end if;
  if not exists (select 1 from public.player_state ps where ps.user_id = v_uid and ps.slot = v_slot) then
    return jsonb_build_object('ok', false, 'error', 'no_character'); end if;
  -- LEAVING: this character's body goes (another character of the account keeps its own); a hero working a town
  -- activity stays at its station (the server plays it, viewed or not).
  if p_map is null then
    delete from public.town_positions where user_id = v_uid and slot = v_slot;
    delete from public.town_seen where user_id = v_uid and slot = v_slot;
    if not exists (select 1 from public.player_state ps where ps.user_id = v_uid and ps.slot = v_slot and public.hr_town_work_kind(ps.active_kind)) then
      perform public.hr_town_release(v_uid, v_slot);
    end if;
    return jsonb_build_object('ok', true, 'left', true);
  end if;
  select * into v_map from public.hr_town_maps where map_id = p_map;
  if not found then return jsonb_build_object('ok', false, 'error', 'bad_map'); end if;
  if p_x is null or p_y is null or p_gx is null or p_gy is null
     or p_x < 0 or p_x >= v_map.w or p_y < 0 or p_y >= v_map.h
     or p_gx < 0 or p_gx >= v_map.w or p_gy < 0 or p_gy >= v_map.h
     or p_dir is null or p_dir not in ('n', 's', 'e', 'w') then
    return jsonb_build_object('ok', false, 'error', 'bad_position'); end if;
  v_on := public.hr_town_walk_ok(p_map, p_x, p_y, p_gx, p_gy);  -- TOWN-WALK-MASK (2027-04-02-town-walk-mask.sql): the tile stood on and the tile walked to are tiles a hero can stand on
  if v_on is null then return public.hr_note_rejection('town_move', v_slot, jsonb_build_object('ok', false, 'error', 'catalogue_missing', 'why', 'no walk mask for ' || p_map)); end if;  -- TOWN-WALK-MASK: never taken unchecked
  if not v_on then return public.hr_note_rejection('town_move', v_slot, jsonb_build_object('ok', false, 'error', 'off_mask', 'detail', jsonb_build_array(p_x, p_y, p_gx, p_gy))); end if;  -- TOWN-WALK-MASK: refused and journalled; the stored tile stands
  -- A HUNTER IS NOT IN TOWN: an open hunt session refuses, and takes the body out.
  if exists (select 1 from public.hunt_sessions h where h.user_id = v_uid and h.slot = v_slot and h.ended_at is null) then
    delete from public.town_positions where user_id = v_uid and slot = v_slot;
    return jsonb_build_object('ok', false, 'error', 'hunting'); end if;
  select at into v_last from public.town_positions where user_id = v_uid and slot = v_slot;
  if v_last is not null and now() - v_last < c_floor then
    return jsonb_build_object('ok', true, 'stamped', false); end if;
  insert into public.town_positions as tp (user_id, slot, map_id, x, y, gx, gy, dir, at, moved_at)
    values (v_uid, v_slot, p_map, p_x, p_y, p_gx, p_gy, p_dir, now(), now())
  on conflict (user_id, slot) do update
    set map_id = excluded.map_id, x = excluded.x, y = excluded.y,
        gx = excluded.gx, gy = excluded.gy, dir = excluded.dir, at = excluded.at,
        moved_at = case when (tp.map_id, tp.x, tp.y, tp.gx, tp.gy, tp.dir)
                             is distinct from (excluded.map_id, excluded.x, excluded.y, excluded.gx, excluded.gy, excluded.dir)
                        then excluded.at else tp.moved_at end;
  -- the first publish stands the body on the server's stand (a walk then starts from there)
  if not exists (select 1 from public.town_bodies b where b.user_id = v_uid and b.slot = v_slot and b.map_id = p_map and b.station_id is not null) then
    perform public.hr_town_place_pointer(v_uid, v_slot, p_map);
  end if;
  return jsonb_build_object('ok', true, 'stamped', true);
end $function$;

-- ── §2 SELF-CHECK (CLAUDE.md §4), EXECUTED, every probe row rolled back ──────
do $chk$
declare
  c_u  constant uuid := '000000c0-0000-4000-a000-0000402b0001';
  c_fn constant text := 'public.hr_town_move(integer,text,integer,integer,integer,integer,text)';
  v_def text; v_md5 text; v jsonb; v_map text; v_w int; v_h int;
  v_sx int; v_sy int; v_tx int; v_ty int; v_ox int; v_oy int; v_pos record; v_row public.hr_rejections%rowtype; v_mask bytea;
begin
  -- (a) THE SHAPE: a signed-in client asks, nobody else; still a security definer.
  if not has_function_privilege('authenticated', c_fn, 'execute') or has_function_privilege('anon', c_fn, 'execute')
     or has_function_privilege('service_role', c_fn, 'execute') or has_function_privilege('hr_engine', c_fn, 'execute') then
    raise exception 'town-walk-mask §2(a): the grants of hr_town_move moved'; end if;
  if not exists (select 1 from pg_proc p where p.oid = c_fn::regprocedure and p.prosecdef) then
    raise exception 'town-walk-mask §2(a): hr_town_move is no longer a security definer'; end if;
  perform public.hr_assert_grant_hygiene(true);

  begin
    -- THE TOWN, and three tiles of it: two a hero can stand on (two stands of the server's own) and one it cannot.
    select m.map_id, m.w, m.h into v_map, v_w, v_h from public.hr_town_maps m where m.main;
    if v_map is null then raise exception 'town-walk-mask §2-harness: no main town map'; end if;
    select s.x, s.y into v_sx, v_sy from public.hr_town_stands s where s.map_id = v_map order by s.station_id, s.stand_no limit 1;
    select s.x, s.y into v_tx, v_ty from public.hr_town_stands s where s.map_id = v_map order by s.station_id desc, s.stand_no desc limit 1;
    select m.mask into v_mask from public.hr_town_walk m where m.map_id = v_map;
    for v_i in 0 .. v_w * v_h - 1 loop   -- the first blocked tile in reading order
      if get_bit(v_mask, v_i) = 0 then v_ox := v_i % v_w; v_oy := v_i / v_w; exit; end if;
    end loop;
    if public.hr_town_walk_ok(v_map, v_ox, v_oy, v_ox, v_oy) is not false or public.hr_town_walk_ok(v_map, v_sx, v_sy, v_tx, v_ty) is not true then
      raise exception 'town-walk-mask §2-harness: the reader does not answer the probe tiles as the mask holds them'; end if;
    if v_sx is null or v_tx is null or v_ox is null or (v_sx, v_sy) = (v_tx, v_ty) then
      raise exception 'town-walk-mask §2-harness: the town gives no two stands and one blocked tile'; end if;

    insert into public.hr_flags (key, enabled, note) values ('town_presence', true, 'town-walk-mask §2 probe')
      on conflict (key) do update set enabled = true;
    insert into auth.users (id) values (c_u) on conflict (id) do nothing;
    insert into public.profiles (id, display_name) values (c_u, 'Probe Walk Mask') on conflict (id) do update set display_name = excluded.display_name;
    insert into public.hr_access_allowlist (user_id, note) values (c_u, 'town-walk-mask §2 probe') on conflict (user_id) do nothing;
    perform set_config('request.jwt.claim.sub', c_u::text, true);
    perform set_config('request.jwt.claims', jsonb_build_object('sub', c_u, 'role', 'authenticated')::text, true);
    v := public.hr_create_character(0);
    if coalesce(v->>'ok', '') <> 'true' then raise exception 'town-walk-mask §2-harness: hr_create_character(0) refused: %', v; end if;
    update public.player_state set active_kind = 'idle', active_id = null where user_id = c_u;
    delete from public.hr_rejections where user_id = c_u;

    -- (b) ON THE MASK: an honest publish is taken as it was (a stand to stand on, a stand to walk to).
    v := public.hr_town_move(0, v_map, v_sx, v_sy, v_tx, v_ty, 's');
    if v->>'stamped' is distinct from 'true' then raise exception 'town-walk-mask §2(b): an honest publish answered %', v; end if;
    if not exists (select 1 from public.town_positions p where p.user_id = c_u and p.slot = 0 and (p.x, p.y, p.gx, p.gy) = (v_sx, v_sy, v_tx, v_ty)) then
      raise exception 'town-walk-mask §2(b): the honest tile was not stored'; end if;
    if exists (select 1 from public.hr_rejections where user_id = c_u) then raise exception 'town-walk-mask §2(b): an accepted publish was journalled'; end if;
    update public.town_positions set at = now() - interval '1 second', moved_at = now() - interval '1 second' where user_id = c_u and slot = 0;
    select p.x, p.y, p.gx, p.gy, p.dir, p.at, p.moved_at, p.ctid as tid into v_pos from public.town_positions p where p.user_id = c_u and p.slot = 0;

    -- (c) ★ STANDING IN A WALL: refused off_mask, journalled, and the stored tile is the same row version it was.
    v := public.hr_town_move(0, v_map, v_ox, v_oy, v_ox, v_oy, 'n');
    if v->>'ok' is distinct from 'false' or v->>'error' is distinct from 'off_mask' then
      raise exception 'town-walk-mask §2(c): a publish on the blocked tile (%, %) answered %', v_ox, v_oy, v; end if;
    if (select p.ctid from public.town_positions p where p.user_id = c_u and p.slot = 0) is distinct from v_pos.tid then
      raise exception 'town-walk-mask §2(c): a refused publish wrote the stored tile'; end if;
    select * into v_row from public.hr_rejections where user_id = c_u and code = 'off_mask';
    if not found or v_row.n <> 1 or v_row.slot <> 0 or not (v_row.verbs ? 'town_move') then
      raise exception 'town-walk-mask §2(c): the refusal is not journalled as one town_move row: %', to_jsonb(v_row); end if;
    -- (d) ★ WALKING INTO A WALL: an honest tile to stand on with a blocked tile to walk to is refused the same way.
    perform set_config('hearthrise.rejection_noted', '', true);   -- one transaction here, one request each in play: the once-a-request mark is cleared
    v := public.hr_town_move(0, v_map, v_sx, v_sy, v_ox, v_oy, 's');
    if v->>'error' is distinct from 'off_mask' then raise exception 'town-walk-mask §2(d): a blocked goal answered %', v; end if;
    if (select p.ctid from public.town_positions p where p.user_id = c_u and p.slot = 0) is distinct from v_pos.tid
       or (select n from public.hr_rejections where user_id = c_u and code = 'off_mask') <> 2 then
      raise exception 'town-walk-mask §2(d): a blocked goal wrote the tile, or was not journalled'; end if;
    -- (e) OUTSIDE THE RECTANGLE is still bad_position (the older check answers first), and a leave still leaves.
    v := public.hr_town_move(0, v_map, -1, 0, 0, 0, 's');
    if v->>'error' is distinct from 'bad_position' then raise exception 'town-walk-mask §2(e): a tile off the map answered %', v; end if;
    -- (f) A TOWN WITH NO MASK takes no position at all: catalogue_missing, journalled, nothing written.
    delete from public.hr_town_walk where map_id = v_map;
    perform set_config('hearthrise.rejection_noted', '', true);
    v := public.hr_town_move(0, v_map, v_tx, v_ty, v_tx, v_ty, 's');
    if v->>'ok' is distinct from 'false' or v->>'error' is distinct from 'catalogue_missing' then
      raise exception 'town-walk-mask §2(f): a town with no mask answered % (a position was taken unchecked)', v; end if;
    if (select p.ctid from public.town_positions p where p.user_id = c_u and p.slot = 0) is distinct from v_pos.tid
       or not exists (select 1 from public.hr_rejections where user_id = c_u and code = 'catalogue_missing' and verbs ? 'town_move') then
      raise exception 'town-walk-mask §2(f): the unmasked publish wrote the tile, or was not journalled'; end if;
    v := public.hr_town_move(0, null, null, null, null, null, null);
    if v->>'left' is distinct from 'true' then raise exception 'town-walk-mask §2(e): a leave answered %', v; end if;

    raise exception using errcode = 'HRW42', message = 'town-walk-mask §2 complete - rolling back';
  exception when sqlstate 'HRW42' then null;
  end;
  perform set_config('request.jwt.claim.sub', '', true);
  perform set_config('request.jwt.claims', '', true);
  if exists (select 1 from auth.users where id = c_u) or exists (select 1 from public.player_state where user_id = c_u)
     or exists (select 1 from public.town_positions where user_id = c_u) or exists (select 1 from public.hr_rejections where user_id = c_u)
     or not exists (select 1 from public.hr_town_walk) then
    raise exception 'town-walk-mask §2: LEAKED a probe row, or the mask did not come back'; end if;
  -- (g) ★ THE DIFF IS ONLY THIS FILE'S LINES, judged LAST so a changed rule is refused above by what it breaks: the installed
  --     body is this file's image, and with its marked lines taken back out it is 2027-04-02-rate-refusals-recorded.sql's.
  v_def := replace(pg_get_functiondef(c_fn::regprocedure), E'\r', '');
  v_md5 := md5(regexp_replace(v_def, '[[:space:]]+', ' ', 'g'));
  if v_md5 is distinct from '72ee16c7d8bcdbb5ae17640d6202d8ad' then raise exception 'town-walk-mask §2(g): hr_town_move is not this file''s image (md5 %)', v_md5; end if;
  v_def := regexp_replace(v_def, '\n[^\n]*-- TOWN-WALK-MASK[^\n]*(?=\n)', '', 'g');
  if position('TOWN-WALK-MASK' in v_def) > 0 or position('hr_town_walk_ok' in v_def) > 0 then
    raise exception 'town-walk-mask §2(g): a line of this file stands after the reverse edit'; end if;
  v_md5 := md5(regexp_replace(v_def, '[[:space:]]+', ' ', 'g'));
  if v_md5 is distinct from 'f17722883f848431992cc8634fcb5ece' then
    raise exception 'town-walk-mask §2(g): hr_town_move differs from its pre-image by more than this file''s marked lines (md5 % after the reverse edit, wanted f17722883f848431992cc8634fcb5ece)', v_md5; end if;
  raise notice 'town-walk-mask: an honest publish is stored; a blocked tile to stand on or walk to is refused off_mask, journalled, and the stored tile untouched; a town with no mask takes no position; hr_town_move is its pre-image plus four marked lines; all green';
end $chk$;

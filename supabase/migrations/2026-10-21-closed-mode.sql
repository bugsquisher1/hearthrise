    raise exception 'closed-mode §10 k1: hr_access_allowlist must carry exactly the own-row SELECT policy'; end if;
  if exists (select 1 from information_schema.role_table_grants
              where table_schema = 'public' and table_name = 'hr_access_allowlist'
                and grantee in ('anon', 'authenticated', 'service_role', 'hr_engine', 'hr_tick', 'PUBLIC')
                and not (grantee = 'authenticated' and privilege_type = 'SELECT')) then
    raise exception 'closed-mode §10 k1: a client or engine role can write hr_access_allowlist'; end if;

  -- k2 the switch exists (a fresh apply lands it CLOSED; a re-apply never moves it).
  if not exists (select 1 from public.hr_flags where key = 'closed_mode') then
    raise exception 'closed-mode §10 k2: the closed_mode flag row is absent'; end if;
  select enabled into v_flag from public.hr_flags where key = 'closed_mode';

  -- k3 the grants are exact.
  if has_function_privilege('anon', 'public.hr_admitted(uuid)', 'execute')
     or not has_function_privilege('authenticated', 'public.hr_admitted(uuid)', 'execute')
     or not has_function_privilege('anon', 'public.hr_access_check()', 'execute')
     or not has_function_privilege('authenticated', 'public.hr_access_check()', 'execute')
     or not has_function_privilege('service_role', 'public.hr_access_check()', 'execute') then
    raise exception 'closed-mode §10 k3: hr_admitted / hr_access_check grants are not exact'; end if;
  if exists (select 1 from pg_proc where oid in ('public.hr_admitted(uuid)'::regprocedure,
                                                  'public.hr_access_check()'::regprocedure)
                                     and (prosecdef or provolatile <> 'v' or proacl is null
                                          or proacl::text ~ '(\{|,)=[a-zA-Z*]*X')) then
    raise exception 'closed-mode §10 k3: hr_admitted / hr_access_check is SECURITY DEFINER, not VOLATILE, or PUBLIC-executable'; end if;
  if has_function_privilege('authenticated', 'public.hr_rpc_gate(text)', 'execute')
     or has_function_privilege('authenticated', 'public.hr_rate_gate(uuid,integer,text)', 'execute') then
    raise exception 'closed-mode §10 k3: a gate became client-executable'; end if;

  -- k4 the gates carry their line.
  select replace(pg_get_functiondef('public.hr_rpc_gate(text)'::regprocedure), chr(13), '') into v_def;
  if position('perform public.hr_access_check();' || chr(10) || '  case p_bucket' in v_def) = 0 then
    raise exception 'closed-mode §10 k4: hr_rpc_gate does not call hr_access_check before its buckets'; end if;
  select replace(pg_get_functiondef('public.hr_rate_gate(uuid,integer,text)'::regprocedure), chr(13), '') into v_def;
  if position('if not public.hr_admitted(p_user) then return false; end if;' in v_def) = 0 then
    raise exception 'closed-mode §10 k4: hr_rate_gate does not refuse a non-admitted user'; end if;

  -- k5 the six restrictive policies.
  foreach t in array array['bug_reports', 'chat_blocks', 'chat_messages', 'clan_members',
                           'game_events', 'session_claims'] loop
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t
                    and policyname = 'hr_closed_admit' and permissive = 'RESTRICTIVE'
                    and cmd = 'ALL' and roles = '{authenticated}') then
      raise exception 'closed-mode §10 k5: % lacks the restrictive hr_closed_admit policy', t; end if;
  end loop;

  foreach t in array array['chat_messages', 'display_names', 'market_listings', 'market_buy_offers',
                           'clans', 'clan_board', 'clan_ledger', 'clan_members', 'clan_raids',
                           'clan_stores', 'clan_tavern', 'clan_withdrawals', 'clan_work_labour',
                           'clan_work_orders', 'raid_claims', 'raid_contributions',
                           'world_event_pledges', 'world_event_totals'] loop
    if to_regclass('public.' || t) is not null
       and not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t
                        and policyname = 'hr_closed_anon' and permissive = 'RESTRICTIVE'
                        and cmd = 'SELECT' and roles = '{anon}') then
      raise exception 'closed-mode §10 k5: % lacks the restrictive anon hr_closed_anon read policy', t; end if;
  end loop;
  -- (nested, not `is not null AND …::regclass`: the cast would be evaluated
  --  on a database without storage and raise there)
  if to_regclass('storage.objects') is not null then
    if (select count(*) from pg_policy
         where polrelid = to_regclass('storage.objects') and not polpermissive
           and polname in ('hr_closed_admit_insert', 'hr_closed_admit_update')) <> 2 then
      raise exception 'closed-mode §10 k5: storage.objects lacks the restrictive closed-mode write policies'; end if;
  end if;

  -- k6 L1 is configured wherever PostgREST exists.
  if exists (select 1 from pg_roles where rolname = 'authenticator')
     and not exists (select 1 from pg_db_role_setting s, unnest(s.setconfig) c
                      where s.setrole = 'authenticator'::regrole and s.setdatabase = 0
                        and c = 'pgrst.db_pre_request=public.hr_access_check') then
    raise exception 'closed-mode §10 k6: authenticator does not run public.hr_access_check as its pre-request'; end if;

  -- k7 BEHAVIOUR, executed as the roles PostgREST uses, every row rolled back.
  begin
    insert into auth.users (id) values (v_in), (v_out) on conflict (id) do nothing;
    insert into public.hr_access_allowlist (user_id, note) values (v_in, 'closed-mode self-check')
      on conflict (user_id) do nothing;
    update public.hr_flags set enabled = true where key = 'closed_mode';

    -- the truth table, as owner
    if not public.hr_admitted(v_in) or public.hr_admitted(v_out) or public.hr_admitted(null) then
      raise exception 'closed-mode §10 k7a: closed: admitted(in/out/null) is wrong'; end if;
    update public.hr_flags set enabled = false where key = 'closed_mode';
    if not public.hr_admitted(v_in) or not public.hr_admitted(v_out) or public.hr_admitted(null) then
      raise exception 'closed-mode §10 k7a: open: admitted(in/out/null) is wrong'; end if;
    delete from public.hr_flags where key = 'closed_mode';
    if not public.hr_admitted(v_in) or public.hr_admitted(v_out) then
      raise exception 'closed-mode §10 k7a: a missing flag row does not read as CLOSED'; end if;
    insert into public.hr_flags (key, enabled, note) values ('closed_mode', true, 'self-check');

    -- L3 the engine's gate
    if public.hr_rate_gate(v_out, 0, 'accrue') then
      raise exception 'closed-mode §10 k7b: hr_rate_gate admitted a non-allowlisted user'; end if;
    if not public.hr_rate_gate(v_in, 0, 'accrue') then
      raise exception 'closed-mode §10 k7b: hr_rate_gate refused an allowlisted user'; end if;

    -- L1 the hook, as the request roles: anon passes, allowlisted passes, the rest 403 hr_closed
    perform set_config('request.jwt.claim.sub', '', true);
    perform set_config('request.jwt.claims', '{"role":"anon"}', true);
    set local role anon;
    perform public.hr_access_check();
    reset role;

    -- L4 anon reads (R1): a player's global chat line is invisible to anon while
    -- closed, and visible once open (the control: the policy, not an empty table).
    insert into public.chat_messages (channel, from_id, from_name, body)
    values ('global', v_in, 'selfcheck', 'closed-mode self-check');
    set local role anon;
    select count(*) into v_n from public.chat_messages where from_id = v_in;
    reset role;
    if v_n <> 0 then raise exception 'closed-mode §10 k7f: anon read % chat row(s) while closed', v_n; end if;
    update public.hr_flags set enabled = false where key = 'closed_mode';
    set local role anon;
    select count(*) into v_n from public.chat_messages where from_id = v_in;
    reset role;
    update public.hr_flags set enabled = true where key = 'closed_mode';
    if v_n <> 1 then raise exception 'closed-mode §10 k7f: anon read % chat row(s) while OPEN, expected 1 (control)', v_n; end if;

    perform set_config('request.jwt.claim.sub', v_in::text, true);
    perform set_config('request.jwt.claims', json_build_object('sub', v_in, 'role', 'authenticated')::text, true);
    set local role authenticated;
    perform public.hr_access_check();
    -- the client sees its own allowlist row and no one else's
    select count(*) into v_n from public.hr_access_allowlist;
    reset role;
    if v_n <> 1 then raise exception 'closed-mode §10 k7c: an allowlisted client read % allowlist rows, expected 1', v_n; end if;
    -- L2 the RPC gate passes the allowlisted caller
    if not public.hr_rpc_gate('hr_server_now') then
      raise exception 'closed-mode §10 k7c: hr_rpc_gate refused an allowlisted caller'; end if;

    perform set_config('request.jwt.claim.sub', v_out::text, true);
    perform set_config('request.jwt.claims', json_build_object('sub', v_out, 'role', 'authenticated')::text, true);
    v_err := null;
    begin
      set local role authenticated;
      perform public.hr_access_check();
    exception when sqlstate 'PGRST' then
      v_err := sqlerrm;
    end;
    reset role;
    if v_err is null or position('"code":"hr_closed"' in v_err) = 0 then
      raise exception 'closed-mode §10 k7d: a non-allowlisted caller passed the pre-request hook (%)', v_err; end if;
    select count(*) into v_n from public.hr_access_allowlist;   -- as owner: unaffected
    v_err := null;
    begin
      perform public.hr_rpc_gate('hr_server_now');
    exception when sqlstate 'PGRST' then
      v_err := sqlerrm;
    end;
    if v_err is null or position('"code":"hr_closed"' in v_err) = 0 then
      raise exception 'closed-mode §10 k7d: hr_rpc_gate admitted a non-allowlisted caller'; end if;

    -- L4 a client write by a non-admitted caller is refused by RLS; the admitted one lands
    v_ok := false;
    begin
      set local role authenticated;
      insert into public.game_events (user_id, event_type) values (v_out, 'closed_mode_selfcheck');
    exception when insufficient_privilege or check_violation then
      v_ok := true;
    end;
    reset role;
    if not v_ok then raise exception 'closed-mode §10 k7e: RLS let a non-admitted caller write game_events'; end if;
    perform set_config('request.jwt.claim.sub', v_in::text, true);
    perform set_config('request.jwt.claims', json_build_object('sub', v_in, 'role', 'authenticated')::text, true);
    set local role authenticated;
    insert into public.game_events (user_id, event_type) values (v_in, 'closed_mode_selfcheck');
    reset role;

    raise exception using errcode = 'HRC10', message = 'closed-mode §10 complete — rolling back';
  exception when sqlstate 'HRC10' then
    null;
  end;
  reset role;
  perform set_config('request.jwt.claim.sub', '', true);
  perform set_config('request.jwt.claims', '', true);

  -- k8 the fixtures are gone and the flag is what it was.
  if exists (select 1 from auth.users where id in (v_in, v_out))
     or exists (select 1 from public.hr_access_allowlist where user_id in (v_in, v_out))
     or (select enabled from public.hr_flags where key = 'closed_mode') is distinct from v_flag then
    raise exception 'closed-mode §10 k8: the self-check left a fixture or moved the flag'; end if;

  -- k9 grant hygiene still holds with the two new client functions baselined.
  perform public.hr_assert_grant_hygiene(true);
end $mig$;

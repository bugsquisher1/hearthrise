// src/data/store-kit.js — THE STORE'S BASICS, PRICED IN HOURS OF WAGE (lane/econ-levers, game designer, 2026-11-22;
//   docs/design/redesign/04-math-strategy.md section 11 `supplyShare`, 09-crafting.md sections 2.5, 4.3 and 4.6).
//
// No store price is typed. Every row of src/data/supply-basics.js is priced here from the wage at a step (src/data/wage.js): a USE at the
// buyer's store step (below), the row's LIST price at its own step:
//
//   a meal or a drink   round(storeShare x lineShare.meal   x wage(step) x amount / refRestore)     gold a use
//   a charge            round(storeShare x lineShare.charge x wage(step) / refCharges)              gold a shot or a cast
//   storeShare          kitWork x townWageShare x storeCeiling (09: 0.8 x 0.25 x 1.5 = 0.3 of an hour's wage for a store-fed kit-hour)
//
// So a reference hero (the mixed MID four at Level 60 on Steady, the scale's one reference ground) spends lineShare of a store kit-hour
// on each line the store sells: meals (food and drink, 0.35) and charges (arrows and runes, 0.35). The two lines 09 keeps crafted-only
// (draught 0.2, imbuement 0.1) have no store row, so a store-only hero's bill is 0.3 x 0.7 = 0.21 of its wage before rounding.
// A row's own step is the Level its crafted partner is made at (the band its strength belongs to), so a deeper row LISTS higher a point.
//
// THE FLOORS, ALL FROM THE CRAFTED PARTNER, NEVER TYPED (09 2.5: "a crafted kit wins twice, on price and on strength"; the shop's bid for
// a crafted partner is capped at `buyback` of the store's list, so no floor below can print gold):
//   a meal or a drink   enough that the cap never cuts the crafted partner's bid under its book: book a point / buyback (tests/craft-wages
//                       W-STEP, a cook still refines for the shop; 2x the book a point, so B1's "more than the book a point" holds too)
//   a charge            at least BASIC_AMMO_PREMIUM x its partner's book a shot, and a rune with any book at least 2 so the shop's bid for
//                       the crafted rune (whole gold, never under 1) stays under the store (tests/craft-wages.mjs W-RUNE)
// At the reference the floors, not the wage, set the charge and the drink a Level 60 four buys (a mithril arrow 2, an Etched rune 2, a
// Thin Carrot Juice 16): today's crafted book values sit above 09's share of the wage. They fall to the wage when wave 4 prices crafted
// goods as V = work-hours x townWageShare x wage(band step) (13-market 3.2); the formula is already the price wherever it is higher.
// And the whole-gold floor of 1: a store use is whole gold (the purse and hr_hunt_apply_member re-price in gold), so a charge whose share
// of the wage is under a gold costs 1 (the measured bill reads the floor, tools/balance-program/redesign/econ/).
//
// THE REFERENCE RATES are the four's mean per hunted hero-hour at Level 60 on Steady, MEASURED (v1-climb.mjs base:steady from a held start,
// 6 seeds x 8 h, lane/econ-levers): HP and mana restored from store meals and drinks, and store shots and casts. They are how much of a
// line one reference hour burns, the "hours of effect" 09 section 4.3 writes on a recipe; nothing else in the price is measured.
//
// A USE IS PRICED AT THE BUYER'S STEP (lane/econ-followups, backend-architect, 2026-11-22; 04 section 3: "every repeating price is stored
// as hours of the wage at the buyer's step ... the supply rows"; Tyler 2026-11-22: goods are priced by DEPTH). The server charges every
// store use storePriceOf(storeTerms(row), the buyer's store step) (hr_store_price, its float8 twin, generated by tools/gen-store-prices.mjs
// into 1061-store-step-catalogue.generated.sql and pinned at every row and step; the step is 1062-store-step.sql hr_store_step), so the
// bill a hunted hour burns follows what that hour pays:
//   on the Danger scale   the step the hunt stands at as each settle window opens, in the wage's unit (src/core/wage.js depthStep);
//   off it                the hero's Level (wage.js levelStep: a tier ground, the Tower, a hall, a call, town).
// A row's `price` (supply-basics.js) is the same rule at the row's OWN step: its list price, the one the shop's buy-back cap reads
// (SUPPLY_SHOP_OFFERS). It is never what a use costs. The floors below never read a step, so no step prices a use under them.
// `storeLag` (09 4.6: the store's good one tier behind the hero's band) is NOT applied: today a store row's strength is fixed
// (BASIC_EFFECT_SHARE of its crafted partner), so a price lag would be a second discount for the same gap. It lands with the store good
// whose strength follows the hero (wave 4), strength and price together.
//
// PURE ESM. Data and pure arithmetic only.
// ════════════════════════════════════════════════════════════════════════
import { wage } from './wage.js';

export const STORE_KIT = Object.freeze({
  /* LEVER (econ.kit-work; 09 4.7, search 0.5 to 1.2): work-hours behind one kit-hour */
  kitWork: 0.8,
  /* LEVER (econ.town-wage-share; 09 4.3, search 0.15 to 0.35): a work-hour's worth beside a hunted hour */
  townWageShare: 0.25,
  /* LEVER (econ.store-ceiling; 09 4.7, search 1.25 to 2.0): how much dearer the store is than the crafted good */
  storeCeiling: 1.5,
  /* LEVER (econ.store-lines; 09 4.3's line shares): the share of a kit-hour each line the store sells takes */
  lineShare: Object.freeze({ meal: 0.35, charge: 0.35 }),
  /* LEVER (econ.store-rates): the reference four's store use a hunted hero-hour, MEASURED at Level 60 on Steady (see the header) */
  refRestore: 12660,
  refCharges: 1390,
  /* NOT A LEVER: supabase/functions/hr-accrue/catalogue.js SHOP_BUYBACK_RATE, the share of the store's list the shop bids for a crafted
     partner (tests/econ-levers.mjs holds the two equal; the edge module is not importable from data) */
  buyback: 0.5,
});

/** A store-fed kit-hour's share of an hour's wage (09 2.5: 0.3 at the starting values). */
export function storeShare(k = STORE_KIT) {
  return k.kitWork * k.townWageShare * k.storeCeiling;
}

/**
 * A ROW'S PRICE TERMS, everything but the step (the server's catalogue row, tools/gen-store-prices.mjs): `line` 'meal' (a food or a
 * drink: `amount` HP or mana, `partnerAmount` the crafted partner's) or 'charge' (a shot or a cast; `rune` true for a rune); `book` the
 * crafted partner's book value; `ammoPremium` supply-basics.js BASIC_AMMO_PREMIUM. Answers { line, coef, amount, per, floor }:
 *   coef   storeShare x the line's share, ONE double (the server stores its shortest round-trip text, which parses to the same bits)
 *   amount the use's HP or mana (a meal), 0 for a charge
 *   per    what one reference hour burns of the line (refRestore for a meal, refCharges for a charge)
 *   floor  the step-free floor in whole gold: the crafted partner's (a meal's book a point / buyback; a charge's ammoPremium x book, and
 *          2 for a rune with any book), and never under 1
 */
export function storeTerms({ line, amount = 0, partnerAmount = 0, book = 0, rune = false, ammoPremium = 1 }, k = STORE_KIT) {
  if (line !== 'meal' && line !== 'charge') throw new Error('store-kit: no line ' + line);
  const coef = storeShare(k) * k.lineShare[line];
  if (line === 'meal') {
    const crafted = partnerAmount > 0 ? Math.ceil((book * amount) / (partnerAmount * k.buyback)) : 1;
    return Object.freeze({ line, coef, amount, per: k.refRestore, floor: Math.max(1, crafted) });
  }
  return Object.freeze({ line, coef, amount: 0, per: k.refCharges, floor: Math.max(1, Math.ceil(ammoPremium * book), rune && book > 0 ? 2 : 1) });
}

/**
 * ONE USE OF A ROW AT A STEP, whole gold: the formula's share of the wage at `step` (wage.js wageStep holds it to 1..stepMax), never
 * under the row's floor. The multiplications run in the order the server's float8 twin runs them (hr_store_price), and Math.round on a
 * positive number is floor plus one at a fraction of a half or more, which the twin spells out, so both reach the same whole gold.
 */
export function storePriceOf(t, step) {
  const share = t.coef * wage(step);
  const formula = Math.round(t.line === 'meal' ? (share * t.amount) / t.per : share / t.per);
  return Math.max(t.floor, formula);
}

/**
 * THE PRICE OF ONE STORE USE, whole gold: storeTerms of the row at `step` (the row's own made-at Level for its list price, the buyer's
 * store step for a use). The same arithmetic as before the split, so every list price is unchanged.
 */
/** @param {{ step: number, line: any, amount?: number, partnerAmount?: number, book?: number, rune?: boolean, ammoPremium?: number }} p */
export function storePrice({ step, ...row }, k = STORE_KIT) {
  return storePriceOf(storeTerms(row, k), step);
}

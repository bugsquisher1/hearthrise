#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-raid-boss-rewards.mjs — GENERATE THE SERVER RAID-CHEST CATALOGUE.
//
// The raid claim RPC (raid_claim, 2026-08-11-raid-claim-authority.sql, gold/gems
// credit added b412) must mint the Hunt chest MATERIALS + signature into
// player_inventory server-side — otherwise those OWNABLE ids are an un-backed
// CLIENT mint (raids.js grantReward → window.addItem) the inventory absolute
// envelope would DELETE. To mint them it needs a SERVER-KNOWN reward catalogue:
// which materials each boss chest grants (and in which order), each boss's
// signature spoil, and the boss's rotation ordinal for the solo pick.
//
// hr_hunt_bosses already holds sig_item; hr_hunt_tiers already holds chest_mats
// (a COUNT). What was missing — and what this file supplies — is the per-boss
// MATERIAL ID LIST (the keys of RAID_BOSSES[*].reward.items). Source of truth is
// src/data/raid-bosses.js (the same records the client card reads via
// window.RAID_BOSSES). Copying game DATA into SQL by hand is the failure
// src/main.js `unifyObject` was written about; this file is machine-written from
// that single source and drift-guarded (`--check`, a preflight in
// tests/run-smoke.mjs), so the copy cannot rot.
//
//   Regenerate:  node tools/gen-raid-boss-rewards.mjs
//   Verify:      node tools/gen-raid-boss-rewards.mjs --check   (run in run-smoke)
//
// ⚠ ORDER IS LOAD-BEARING. `ordinal` is the RAID_BOSSES array index — the solo
// bossOfWeek pick is BOSSES[fnv1a('hr-raid-'+week) % n]. `material_ids` preserves
// reward.items key order — the solo chest slices its FIRST TWO materials from it.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { RAID_BOSSES, LONE_HUNT_CHEST } from '../src/data/raid-bosses.js';
import { emitGenerated } from './generated-freeze.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'supabase', 'migrations', '2026-08-22-raid-boss-rewards.generated.sql');

const ID_RE = /^[a-z0-9_]+$/;

function rows() {
  const out = [];
  RAID_BOSSES.forEach((b, i) => {
    if (!b || !ID_RE.test(b.id)) throw new Error(`raid boss id ${b && b.id} is not [a-z0-9_]`);
    if (!b.sig || !ID_RE.test(b.sig)) throw new Error(`raid boss ${b.id} has no valid sig id (${b.sig})`);
    const items = (b.reward && b.reward.items) || {};
    const mats = Object.keys(items);
    if (mats.length === 0) throw new Error(`raid boss ${b.id} has no reward materials`);
    for (const m of mats) if (!ID_RE.test(m)) throw new Error(`raid boss ${b.id} material id ${m} is not [a-z0-9_]`);
    out.push({ id: b.id, ordinal: i, sig: b.sig, mats });
  });
  // ordinal must be a dense 0..n-1 sequence (it indexes the solo rotation modulo).
  out.forEach((r, i) => { if (r.ordinal !== i) throw new Error(`ordinal gap at ${r.id}`); });
  return out;
}

export function render() {
  const rs = rows();
  const n = rs.length;
  const digest = createHash('sha256').update(JSON.stringify(rs)).digest('hex');
  const values = rs.map((r) =>
    `  ('${r.id}', ${r.ordinal}, '${r.sig}', array[${r.mats.map((m) => `'${m}'`).join(', ')}]::text[])`
  ).join(',\n');
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE SERVER RAID-CHEST REWARD CATALOGUE  (GENERATED — DO NOT EDIT)
--
--   Generated by tools/gen-raid-boss-rewards.mjs from src/data/raid-bosses.js.
--   Any hand edit is reverted by the next generation and FAILS
--   \`node tools/gen-raid-boss-rewards.mjs --check\` (a preflight in
--   tests/run-smoke.mjs).
--
--   raid-boss-reward digest: ${digest}
--   ${n} raid bosses · ordinal = RAID_BOSSES array index (solo rotation) ·
--   material_ids in reward.items key order (solo slices the first two)
--
-- Read by raid_claim (2026-08-22-raid-chest-items.sql) to mint chest materials +
-- signature into player_inventory. Numbers/ids only; no client value crosses.
-- Idempotent: truncate+insert inside the migration transaction. Apply BEFORE the
-- raid_claim body migration (which asserts every boss row exists + sig parity).
-- ════════════════════════════════════════════════════════════════════════

do $$
begin
  if to_regclass('public.hr_hunt_boss_reward') is null then
    create table public.hr_hunt_boss_reward (
      boss_id      text primary key,
      ordinal      int  not null,
      sig_item     text not null,
      material_ids text[] not null check (array_length(material_ids, 1) >= 1)
    );
    alter table public.hr_hunt_boss_reward enable row level security;
  end if;
end $$;

-- Read-only catalogue: readable by everyone signed in, written by NO client.
do $$
begin
  revoke all on public.hr_hunt_boss_reward from public, anon, authenticated, service_role;
  grant select on public.hr_hunt_boss_reward to anon, authenticated, service_role;
  drop policy if exists hr_hunt_boss_reward_sel on public.hr_hunt_boss_reward;
  create policy hr_hunt_boss_reward_sel on public.hr_hunt_boss_reward for select using (true);
end $$;

truncate table public.hr_hunt_boss_reward;
insert into public.hr_hunt_boss_reward (boss_id, ordinal, sig_item, material_ids) values
${values};

-- ── Self-verification ────────────────────────────────────────────────────
do $$
declare v_n int; v_bad int;
begin
  select count(*) into v_n from public.hr_hunt_boss_reward;
  if v_n <> ${n} then raise exception 'hr_hunt_boss_reward has % rows, expected ${n}', v_n; end if;

  -- Dense 0..n-1 ordinals (the solo rotation indexes modulo the row count).
  select count(*) into v_bad from public.hr_hunt_boss_reward
    where ordinal not between 0 and ${n - 1};
  if v_bad > 0 then raise exception '% boss reward rows have an out-of-range ordinal', v_bad; end if;
  if (select count(distinct ordinal) from public.hr_hunt_boss_reward) <> ${n} then
    raise exception 'boss reward ordinals are not distinct 0..${n - 1}';
  end if;

  -- No write policy may exist on the catalogue.
  select count(*) into v_bad from pg_policies
    where schemaname = 'public' and tablename = 'hr_hunt_boss_reward'
      and cmd in ('INSERT','UPDATE','DELETE','ALL');
  if v_bad > 0 then raise exception '% write policies on hr_hunt_boss_reward', v_bad; end if;

  -- SIG PARITY: every boss's signature here must equal hr_hunt_bosses.sig_item
  -- (the catalogue already used by the claim payout), so the two never diverge.
  if to_regclass('public.hr_hunt_bosses') is not null then
    select count(*) into v_bad from public.hr_hunt_boss_reward r
      join public.hr_hunt_bosses b on b.boss_id = r.boss_id
     where b.sig_item is distinct from r.sig_item;
    if v_bad > 0 then raise exception '% boss reward rows disagree with hr_hunt_bosses.sig_item', v_bad; end if;
  end if;
end $$;
`;
}

/** Every Lone Hunt literal in the two SQL files vs LONE_HUNT_CHEST. Pure. */
function lonelyDrift(gateSql, chestSql) {
  const out = [];
  const num = (sql, re) => { const m = sql.match(re); return m ? Number(m[1]) : NaN; };
  const pairs = [
    [num(gateSql, /c_lone_kills constant bigint := (\d+);/), LONE_HUNT_CHEST.killsNeeded, 'gate c_lone_kills'],
    [num(chestSql, /c_solo_gold constant bigint := (\d+);/), LONE_HUNT_CHEST.gold, 'c_solo_gold'],
    [num(chestSql, /c_solo_gems constant int\s+:= (\d+);/), LONE_HUNT_CHEST.gems, 'c_solo_gems'],
    [num(chestSql, /c_solo_scale constant numeric := ([0-9.]+);/), LONE_HUNT_CHEST.scale, 'c_solo_scale'],
    [num(chestSql, /c_solo_mats\s+constant int := (\d+);/), LONE_HUNT_CHEST.mats, 'c_solo_mats'],
  ];
  for (const [have, want, what] of pairs) {
    if (have !== want) out.push(`${what} is ${have} in SQL, LONE_HUNT_CHEST says ${want}`);
  }
  return out;
}

if (process.argv.includes('--selftest-lone')) {
  const mig = (n) => readFile(join(ROOT, 'supabase', 'migrations', n), 'utf8');
  const g = await mig('2026-10-10-lone-hunt-weekly-chest.sql'), c = await mig('2026-08-22-raid-chest-items.sql');
  const arms = [
    ['clean', g, c, 0],
    ['gate lowered to 30', g.replace('c_lone_kills constant bigint := 300;', 'c_lone_kills constant bigint := 30;'), c, 1],
    ['solo gold raised', g, c.replace('c_solo_gold constant bigint := 2800;', 'c_solo_gold constant bigint := 9800;'), 1],
  ];
  let bad = 0;
  for (const [name, gs, cs, want] of arms) {
    const n = lonelyDrift(gs, cs).length;
    const okArm = want ? n > 0 : n === 0;
    console.log(`${okArm ? 'ok  ' : 'FAIL'} ${name} (${n} drift)`);
    if (!okArm) bad++;
  }
  process.exit(bad ? 1 : 0);
}

const wanted = render();
/* Applied generated files are FROZEN (tools/generated-freeze.mjs): a data change
   lands as an append-only delta migration, never as new bytes in history. */
const CHECK_MODE = process.argv.includes('--check');
const emitted = emitGenerated(OUT, wanted, CHECK_MODE);
if (!emitted.ok) {
  console.error('gen-raid-boss-rewards --check FAILED: ' + emitted.msg + '. Run: node tools/gen-raid-boss-rewards.mjs');
  process.exit(1);
}
if (CHECK_MODE) {
  /* THE LONE HUNT LITERALS (2026-10-10). The solo chest's gate and payout are
     typed into raid_claim__ungated (the static 2026-08-22 body + the 2026-10-10
     gate); each must equal LONE_HUNT_CHEST, or the card promises one chest and
     the server pays another. `--check-lone=<sql>` lets a selftest feed text. */
  const mig = (n) => readFile(join(ROOT, 'supabase', 'migrations', n), 'utf8').catch(() => '');
  const lone = await lonelyDrift(await mig('2026-10-10-lone-hunt-weekly-chest.sql'),
                                 await mig('2026-08-22-raid-chest-items.sql'));
  if (lone.length) {
    console.error('gen-raid-boss-rewards --check FAILED (Lone Hunt):\n  ' + lone.join('\n  '));
    process.exit(1);
  }
}
if (CHECK_MODE) console.log('gen-raid-boss-rewards --check: catalogue + Lone Hunt literals match src/data/raid-bosses.js — ' + emitted.msg);
else console.log(emitted.msg);

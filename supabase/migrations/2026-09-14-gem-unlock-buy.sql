-- ── 6. hr_state_of — PROJECT the owned set (programmatic, additive) ────────
-- WHY THE ENVELOPE AND NOT A SECOND RPC: ownership must survive a device change
-- and a cloud restore, and the client's only load path for it today is the
-- RESIDUE — the store a restore can rewind while the entitlement it paid for
-- stays granted, which is the b371 dupe. One additive top-level `gem_unlocks`
-- array means the boot envelope already carries it, with no extra round trip and
-- nothing second to keep in step.
--
-- ⚠ ACCOUNT-SCOPED, like `hero_slots` beside it (game-designer ruling
--   2026-09-14). `v_st.slot` is passed as CONTEXT only — hr_gem_unlocks_of does
--   not filter on it — so every character of an account projects the same owned
--   set, which is what makes a theme bought on Hero 1 appear on Hero 2 with no
--   backfill. The EQUIPPED selection stays per character and is not in this
--   lane.
--
-- ⚠ READ UNFILTERED, exactly as `traits` and `hero_slots` are, and for the same
--   stated reason: the generic `progress` array is LIMIT 1000, and a projection
--   that truncates is a projection that can silently answer "you own nothing"
--   about something a player paid gems for.
--
-- Patched at the `total_level` anchor — the anchor
-- 2026-08-22-companion-record.sql, 2026-08-23-trait-buy.sql,
-- 2026-09-08-hero-slot-buy.sql and 2026-09-12-renown-high-projection.sql all
-- use, which survives insertion because each appends AFTER the anchor text.
-- NO-OP on re-apply.

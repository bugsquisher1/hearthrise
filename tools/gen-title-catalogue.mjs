#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-title-catalogue.mjs — GENERATE THE TITLES' SERVER CATALOGUE.
//
// src/data/titles.js is the single source of what a title costs and what it takes; Postgres must know it to do what only it may: count
// the hero's kills and re-quote the price under the lock, on its own clock. Emitted as hr_titles, one row per title, a full delete +
// insert replace. A hero's held titles (player_titles) are not touched: a title dropped from the data reads as nothing worn (hr_title_of joins).
//
//   Regenerate:  node tools/gen-title-catalogue.mjs
//   Verify:      node tools/gen-title-catalogue.mjs --check     (exit 1 on drift)
//   Selftest:    node tools/gen-title-catalogue.mjs --selftest  (every refusal bites)
//
// REFUSES (throws, nothing written): an id that is not one; words the client would drop (src/data/titles.js TITLE_WORDS); a filler name
// (CLAUDE.md §10); two titles with one set of words; a price that is not whole; kills that aren't; no monster, an unknown monster, one
// monster counted twice in a row; a row with no label or noun.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';
import { TITLES, TITLE_WORDS } from '../src/data/titles.js';
import { MONSTERS } from '../src/data/monsters.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
/* Once this file is APPLIED it is history: a new row moves OUT_FILE to a forward file, like every generated catalogue. */
/* 2027-03-25: Tyler 11-09 renamed five titles (Wolfslayer, Warden, Crownbreaker, Sewerlord, Slagbreaker); ids unchanged, so holders keep them. */
/* 2027-02-28 carries the sample of five. The two prizes of Call out (lane/c-boss-call) land in this forward file, the same full replace, whichever order the two lanes apply in. */
export const OUT_FILE = '2027-03-25-title-names-catalogue.generated.sql';
const OUT = join(ROOT, 'supabase', 'migrations', OUT_FILE);

const PRICE_MAX = 1000000000;
const FILLER = /\b(shadow|void|ancient|eternal|dark|forgotten)\b/i;
const whole = (v, min, max) => Number.isInteger(v) && v >= min && v <= max;

/** What is wrong with the rows, as sentences. Pure. */
export function problemsOf(titles, ctx = {}) {
  const monsters = ctx.monsters || MONSTERS;
  const out = [];
  const seen = new Set();
  if (!Object.keys(titles).length) out.push('there are no titles');
  for (const [id, t] of Object.entries(titles)) {
    if (!/^[a-z0-9_]{1,32}$/.test(id)) out.push(`${id} is not a title id`);
    if (typeof t.words !== 'string' || !TITLE_WORDS.test(t.words)) out.push(`${id}: the words ${t.words} would be dropped by the client`);
    else {
      if (seen.has(t.words)) out.push(`${id}: the words "${t.words}" are on two titles`);
      seen.add(t.words);
    }
    if (typeof t.name !== 'string' || !t.name.trim()) out.push(`${id}: it has no name`);
    for (const said of [t.name, t.words]) if (typeof said === 'string' && FILLER.test(said)) out.push(`${id}: "${said}" is a filler name (CLAUDE.md §10)`);
    /* 0 is legal: a title that is itself a prize, the same row with no charge. */
    if (!whole(t.price, 0, PRICE_MAX)) out.push(`${id}: ${t.price} is not a whole price`);
    if (!whole(t.kills, 1, PRICE_MAX)) out.push(`${id}: kills ${t.kills} is not a whole count of at least 1`);
    const counted = t.monsters || [];
    if (!counted.length) out.push(`${id}: it counts no monster`);
    if (new Set(counted).size !== counted.length) out.push(`${id}: a monster is counted twice`);
    for (const m of counted) if (!monsters[m]) out.push(`${id}: ${m} is not a monster`);
    if (typeof t.label !== 'string' || !t.label.trim() || typeof t.noun !== 'string' || !t.noun.trim()) out.push(`${id}: it has no label or noun for its count`);
  }
  return out;
}

const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const texts = (a) => `array[${a.map(lit).join(', ')}]::text[]`;

export function build(titles = TITLES) {
  const problems = problemsOf(titles);
  if (problems.length) throw new Error('gen-title-catalogue: ' + problems.join('; '));
  const rows = Object.entries(titles).map(([id, t], i) => `  (${lit(id)}, ${lit(t.words)}, ${t.price}, ${t.kills}, ${texts(t.monsters)}, ${i})`);
  return `-- ════════════════════════════════════════════════════════════════════════
-- ${OUT_FILE} — WHAT A HERO CAN BE CALLED, AND WHAT IT TAKES.
-- Generated by tools/gen-title-catalogue.mjs from src/data/titles.js.
--   Any hand edit FAILS \`node tools/gen-title-catalogue.mjs --check\`.
-- A row moves no value: hr_title_buy counts the hero's kills and re-quotes from it under its lock, and answers quote_changed if the price moved.
-- RLS on, no policy, no client grant: a client reads a title through the \`titles\` section. No begin/commit.
-- REVERSIBLE: drop the table with the verbs that read it (2027-02-28-titles.sql). ON THE EA SECURITY LIST.
-- ════════════════════════════════════════════════════════════════════════
create table if not exists public.hr_titles (
  title_id text primary key check (title_id ~ '^[a-z0-9_]{1,32}$'),
  words    text not null unique check (words ~ '^[A-Za-z][A-Za-z'' -]{0,39}$'),
  price    bigint not null check (price between 0 and ${PRICE_MAX}),
  kills    bigint not null check (kills >= 1),
  monsters text[] not null check (cardinality(monsters) >= 1),
  ord      int not null
);
alter table public.hr_titles enable row level security;
revoke all on table public.hr_titles from public, anon, authenticated, service_role;
comment on table public.hr_titles is
  '${OUT_FILE}: one row per title (src/data/titles.js): the words beside a hero''s name, the gold to claim it, the kills it takes and the monsters they count. Read only by SECURITY DEFINER functions.';

delete from public.hr_titles;
insert into public.hr_titles (title_id, words, price, kills, monsters, ord) values
${rows.join(',\n')};

-- §4 SELF-CHECK: there is a catalogue, every word fits the seam's 40 letters, and no client can read or write the table.
do $$
begin
  if not exists (select 1 from public.hr_titles) then raise exception 'titles-catalogue §4: no titles'; end if;
  if exists (select 1 from public.hr_titles where char_length(words) > 40) then raise exception 'titles-catalogue §4: a title is longer than the seam takes'; end if;
  if exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'hr_titles') then
    raise exception 'titles-catalogue §4: a policy opens the table to a client'; end if;
  if has_table_privilege('authenticated', 'public.hr_titles', 'select') or has_table_privilege('anon', 'public.hr_titles', 'select')
     or has_table_privilege('authenticated', 'public.hr_titles', 'insert,update,delete') or has_table_privilege('anon', 'public.hr_titles', 'insert,update,delete') then
    raise exception 'titles-catalogue §4: a client role holds a grant'; end if;
end $$;
`;
}

function selftest() {
  let bad = 0;
  const clean = problemsOf(TITLES);
  if (clean.length) { console.error('gen-title-catalogue --selftest: the tree is not clean: ' + clean.join('; ')); process.exit(2); }
  const bites = (name, want, titles) => {
    const hit = problemsOf(titles).some((p) => p.includes(want));
    console.log(`  ${hit ? 'CAUGHT' : 'MISSED'} ${name}`);
    if (!hit) bad++;
  };
  const T = TITLES;
  const w = T.wolfer;
  bites('no titles at all', 'no titles', {});
  bites('an id that is not one', 'not a title id', { ...T, 'Bad-Id': w });
  bites('markup in the words', 'would be dropped', { ...T, wolfer: { ...w, words: '<b>the Wolfer</b>' } });
  bites('words longer than the seam takes', 'would be dropped', { ...T, wolfer: { ...w, words: 'the ' + 'W'.repeat(40) } });
  bites('a filler name', 'filler name', { ...T, wolfer: { ...w, name: 'Shadow Wolfer', words: 'the Shadow Wolfer' } });
  bites('two titles with one set of words', 'on two titles', { ...T, gamekeeper: { ...T.gamekeeper, words: w.words } });
  bites('a fractional price', 'not a whole price', { ...T, wolfer: { ...w, price: 2.5 } });
  bites('a negative price', 'not a whole price', { ...T, wolfer: { ...w, price: -1 } });
  bites('no kills', 'whole count of at least 1', { ...T, wolfer: { ...w, kills: 0 } });
  bites('a title that counts nothing', 'counts no monster', { ...T, wolfer: { ...w, monsters: [] } });
  bites('a monster that does not exist', 'zzz_wolf is not a monster', { ...T, wolfer: { ...w, monsters: ['zzz_wolf'] } });
  bites('one monster counted twice', 'counted twice', { ...T, wolfer: { ...w, monsters: ['gray_wolf', 'gray_wolf'] } });
  bites('no words for its count', 'no label or noun', { ...T, wolfer: { ...w, label: '' } });
  /* The next lane's prize titles: price 0 stays one legal row. */
  const free = problemsOf({ ...T, wolfer: { ...w, price: 0 } });
  console.log(`  ${free.length ? 'MISSED' : 'CAUGHT'} a title with price 0 is one legal row`);
  if (free.length) bad++;
  if (bad) { console.error(`gen-title-catalogue --selftest: ${bad} refusal(s) did not bite`); process.exit(1); }
  console.log('gen-title-catalogue --selftest: every refusal bites');
}

if (isMain(import.meta.url)) {
  if (process.argv.includes('--selftest')) selftest();
  else if (process.argv.includes('--check')) {
    const was = await readFile(OUT, 'utf8').catch(() => '');
    if (was.replace(/\r/g, '') !== build()) { console.error(`gen-title-catalogue --check: ${OUT_FILE} is stale; run node tools/gen-title-catalogue.mjs`); process.exit(1); }
    console.log('gen-title-catalogue --check: OK');
  } else {
    await writeFile(OUT, build());
    console.log('gen-title-catalogue: wrote ' + OUT_FILE);
  }
}

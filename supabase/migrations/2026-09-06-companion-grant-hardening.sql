                      'row (% / %). The translation must sit ON TOP of the guard, never instead of it.',
                      v_state, v_msg;
    end if;

    raise exception using errcode = 'HRG28', message = '§4 complete — rolling back';
  exception when sqlstate 'HRG28' then
    null;
  end;


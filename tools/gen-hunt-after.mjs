#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-hunt-after.mjs — GENERATE THE SERVER'S COPY OF "WHEN THE HUNT ENDS" (lane/c-hunt-itinerary; Tyler 2026-11-15).
//
// src/data/hunt-after.js is the single source of what a hero may do after a hunt, which choice a hero who never picked
// gets, and how long a stopped bench still counts as the job it set off from. Postgres must know them to do what only it
// may: refuse a choice that is no row, freeze the choice on the hunt at Enter, and run it at the hunt's end. Emitted as
// hr_hunt_after_choices and hr_hunt_after_rule. Read by supabase/migrations/2027-04-25-hunt-itinerary.sql.
//
//   Regenerate:  node tools/gen-hunt-after.mjs
//   Verify:      node tools/gen-hunt-after.mjs --check     (exit 1 on drift)
//   Selftest:    node tools/gen-hunt-after.mjs --selftest  (every refusal bites)
//
// mutant-anchors: none — the selftest plants into rows it builds itself
//
// REFUSES (throws, nothing written): hunt-after.js validateAfter's problems (an unknown `runs`, a training choice with no
// place or a place nobody trains at, a default that is no row or costs gold, no way to wait in town), and validateJobNexts'
// (the job THEN rows the server's active_next CHECK lists, 1026-job-counts.sql).
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';
import { AFTER_CHOICES, AFTER_DEFAULT, JOB_GRACE_S, validateAfter, validateJobNexts } from '../src/data/hunt-after.js';
import { TRAINING_PLACES } from '../src/data/training.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
/* Once this file is APPLIED it is history: a changed row moves OUT_NAME to a forward file, like every generated catalogue. */
export const OUT_NAME = '2027-04-25-hunt-after-catalogue.generated.sql';
const OUT = join(ROOT, 'supabase', 'migrations', OUT_NAME);

/** The catalogue's rows, or a throw naming every problem. Pure. */
export function catalogueRows({ choices = AFTER_CHOICES, def = AFTER_DEFAULT, graceS = JOB_GRACE_S, places = Object.keys(TRAINING_PLACES) } = {}) {
  /* the same module's job THEN rows too: 1026-job-counts.sql's CHECK on player_state.active_next mirrors them (tests/job-counts J-DATA) */
  const problems = [...validateAfter(choices, def, graceS, places), ...validateJobNexts()];
  if (problems.length) throw new Error('gen-hunt-after: ' + problems.join('; '));
  return { choices: choices.map((c, ord) => ({ id: c.id, ord, runs: c.runs, place: c.place })), def, graceS };
}

const lit = (s) => (s === null || s === undefined ? 'null' : "'" + String(s).replace(/'/g, "''") + "'");

export function build(input) {
  const r = catalogueRows(input);
  const ids = r.choices.map((c) => lit(c.id)).join(', ');
  const rows = r.choices.map((c) => `  (${lit(c.id)}, ${c.ord}, ${lit(c.runs)}, ${lit(c.place)})`).join(',\n');
  return `-- ════════════════════════════════════════════════════════════════════════
-- ${OUT_NAME} — WHEN THE HUNT ENDS: THE CHOICES, THE DEFAULT, THE GRACE.
-- Generated by tools/gen-hunt-after.mjs from src/data/hunt-after.js. Any hand edit FAILS \`node tools/gen-hunt-after.mjs --check\`.
-- STAGED: tools/apply-migration.mjs, one file, never inside begin/commit. No function, no player row, no client grant.
-- ORDER: right before 2027-04-25-hunt-itinerary.sql, which reads these rows (its §0 refuses without them).
-- hr_hunt_after_choices is UPSERTED, never deleted and re-inserted: a hero's remembered choice and a hunt's frozen one point at it.
-- ════════════════════════════════════════════════════════════════════════
create table if not exists public.hr_hunt_after_choices (
  choice text primary key check (choice ~ '^[a-z_]{1,24}$'),
  ord    int  not null,
  runs   text not null check (runs in ('job', 'nothing', 'training')),
  place  text check ((runs = 'training') = (place is not null))
);
create table if not exists public.hr_hunt_after_rule (
  id             boolean primary key default true check (id),
  default_choice text not null references public.hr_hunt_after_choices (choice),
  job_grace_s    int  not null check (job_grace_s between 0 and 3600)
);
do $$
declare t text;
begin
  foreach t in array array['hr_hunt_after_choices', 'hr_hunt_after_rule'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from public, anon, authenticated, service_role', t);
  end loop;
end $$;
comment on table public.hr_hunt_after_choices is '${OUT_NAME}: what a hero may do when a hunt ends on its own (src/data/hunt-after.js AFTER_CHOICES): runs job | nothing | training, and where a training choice trains.';
comment on table public.hr_hunt_after_rule is '${OUT_NAME}: the choice of a hero who never picked, and how many seconds a bench the player stopped still counts as the job the hero set off from (src/data/hunt-after.js).';

insert into public.hr_hunt_after_choices (choice, ord, runs, place) values
${rows}
on conflict (choice) do update set ord = excluded.ord, runs = excluded.runs, place = excluded.place;

insert into public.hr_hunt_after_rule (id, default_choice, job_grace_s) values
  (true, ${lit(r.def)}, ${r.graceS})
on conflict (id) do update set default_choice = excluded.default_choice, job_grace_s = excluded.job_grace_s;

delete from public.hr_hunt_after_choices where choice <> all (array[${ids}]::text[]);

do $$
declare t text; v_role text;
begin
  if (select count(*) from public.hr_hunt_after_choices) <> ${r.choices.length} then raise exception 'hunt-after-catalogue: hr_hunt_after_choices does not hold the ${r.choices.length} choices'; end if;
  if (select c.runs from public.hr_hunt_after_rule r join public.hr_hunt_after_choices c on c.choice = r.default_choice where r.id) is distinct from ${lit(r.choices.find((c) => c.id === r.def).runs)} then
    raise exception 'hunt-after-catalogue: the default is not the data''s'; end if;
  if not exists (select 1 from public.hr_hunt_after_choices where runs = 'nothing') then raise exception 'hunt-after-catalogue: no choice waits in town'; end if;
  foreach t in array array['hr_hunt_after_choices', 'hr_hunt_after_rule'] loop
    if exists (select 1 from pg_policies where schemaname = 'public' and tablename = t) then
      raise exception 'hunt-after-catalogue: a policy opens % to a client', t; end if;
    foreach v_role in array array['anon', 'authenticated'] loop
      if has_table_privilege(v_role, 'public.' || t, 'select') or has_table_privilege(v_role, 'public.' || t, 'insert,update,delete') then
        raise exception 'hunt-after-catalogue: % holds a grant on %', v_role, t; end if;
    end loop;
  end loop;
end $$;
`;
}

function selftest() {
  try { catalogueRows(); } catch (e) { console.error('gen-hunt-after --selftest: the tree is not clean: ' + e.message); process.exit(2); }
  const base = AFTER_CHOICES.map((c) => ({ ...c }));
  const cases = [
    ['an unknown runs', { choices: [...base, { id: 'nap', runs: 'sleep', place: null }] }, /no entry of AFTER_RUNS/],
    ['a training choice with no place', { choices: base.map((c) => (c.runs === 'training' ? { ...c, place: null } : c)) }, /a place belongs/],
    ['a place nobody trains at', { choices: base.map((c) => (c.runs === 'training' ? { ...c, place: 'moon' } : c)) }, /no place a hero trains/],
    ['a choice listed twice', { choices: [...base, { ...base[0] }] }, /listed twice/],
    ['a default that is no row', { def: 'nap' }, /is no choice/],
    ['a default that costs gold', { def: 'train' }, /may not cost gold/],
    ['no way to wait', { choices: base.filter((c) => c.runs !== 'nothing') }, /waits in town/],
    ['a grace of a day', { graceS: 86400 }, /grace/],
  ];
  let bad = 0;
  for (const [name, input, want] of cases) {
    let said = null;
    try { build(input); } catch (e) { said = String(e.message); }
    if (said && want.test(said)) console.log('ok  refuses: ' + name);
    else { console.error('MISS  ' + name + ': ' + (said || 'built')); bad += 1; }
  }
  if (bad) { console.error(`gen-hunt-after --selftest: ${bad} refusal(s) did not bite`); process.exit(1); }
  console.log('gen-hunt-after --selftest: every refusal bites');
}

async function main() {
  if (process.argv.includes('--selftest')) return selftest();
  if (process.argv.includes('--check')) {
    const was = await readFile(OUT, 'utf8').catch(() => '');
    if (was.replace(/\r/g, '') !== build()) { console.error(`gen-hunt-after --check: ${OUT_NAME} is stale; run node tools/gen-hunt-after.mjs`); process.exit(1); }
    console.log('gen-hunt-after --check: OK');
    return;
  }
  await writeFile(OUT, build());
  console.log('wrote ' + OUT_NAME);
}

if (isMain(import.meta.url)) main().catch((e) => { console.error(e && e.stack ? e.stack : e); process.exit(1); });

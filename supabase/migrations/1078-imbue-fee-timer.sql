-- ── §3 THE TIMER, RESTATED WHOLE (1074's §7 image; this file's lines: IMBUE-FEE-TIMER, only while worn) ──
create or replace function public.hr_flame_temper_settle()
returns trigger language plpgsql security definer set search_path = public, pg_catalog as $fn$
declare v_ms bigint;
begin
  -- 1063-flame-temper.sql: a hero's settled window moved forward by v_ms hunted milliseconds. Only hunted time moves an imbuement's clock.
  -- INNER-FLAME (1074-inner-flame-luck.sql): the fire left this trigger for the settle's walk (hr_flame_settle), on the window's own clock.
  v_ms := floor(extract(epoch from (new.settled_to - old.settled_to)) * 1000)::bigint;
  if v_ms <= 0 then return null; end if;
  if public.hr_flag_on('imbuements') then
    -- IMBUE-FEE-TIMER (1078-imbue-fee-timer.sql): ONLY WHILE WORN (21 D-20). A row runs only where hr_worn_imbues_of hands it to the fight:
    -- in its own kind's slot (the catalogue's) with a piece worn there. An imbuement on a bare slot keeps its hours. Gear never changes in
    -- a hunt (equip and hr_piece_wear answer hunt_open), so the rows that run are fixed for the hunt and every cut of its windows charges
    -- the same. One statement: the spent rows go (their last hunted ms ran out in this window), the rest count down, never one twice.
    with live as (
      select w.equip_slot from public.hero_worn_imbue w
        join public.hr_imbue_rules r on r.imbue_id = w.imbue_id and r.equip_slot = w.equip_slot
        join public.player_equipment e on e.user_id = w.user_id and e.slot = w.slot and e.equip_slot = w.equip_slot
       where w.user_id = new.user_id and w.slot = new.slot),
    spent as (
      delete from public.hero_worn_imbue w using live l
       where w.user_id = new.user_id and w.slot = new.slot and w.equip_slot = l.equip_slot and w.ms_left <= v_ms)
    update public.hero_worn_imbue w set ms_left = w.ms_left - v_ms, updated_at = now()
      from live l where w.user_id = new.user_id and w.slot = new.slot and w.equip_slot = l.equip_slot and w.ms_left > v_ms;
  end if;
  return null;
end $fn$;

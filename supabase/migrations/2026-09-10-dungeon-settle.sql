      v_out := jsonb_build_object('ok', false, 'error', 'bad_dungeon_write',
                                  'sqlstate', v_sqlstate, 'detail', v_msg);
  end;

  -- ── (5) CACHE THE DECISION — SUCCESS ONLY. A refusal (on_cooldown, daily_cap,
  --        level_locked, insufficient_item) stays retryable; a version_conflict
  --        is not cached either, so a re-read retry can succeed — no key-release
  --        dance is needed because nothing failing is ever stored. The cached
  --        value is the {ok, settled} receipt; the replay branch §(4) reunites it
  --        with FRESH state.
  if coalesce(v_out->>'ok', 'false') = 'true' then
    insert into public.player_intents (user_id, intent_id, slot, intent, result, at)
      values (v_uid, p_intent_id, v_slot, v_intent,
              jsonb_build_object('ok', true, 'settled', v_out->'settled'), now())
      on conflict (user_id, intent_id) do nothing;
  else
    perform public.hr_record_rejection(v_uid, v_slot, v_intent, v_out->>'error',
                                       v_out - 'ok' - 'error');
  end if;

  return v_out;
end $$;


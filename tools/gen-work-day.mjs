#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-work-day.mjs — GENERATE THE SERVER'S WORK-DAY CATALOGUE (lane/r12-company-trades, FB-10 slice 1; Tyler 2026-11-22 CR-Q1 a, CR-Q3 b).
//
// src/data/work-day.js is the one source of the work day (WORK_DAY: the free day and Premium's extra, in minutes) and of what a
// company trade and a town job are (TRADE_CATS, WORK_KINDS). The server reads this one-row table when it caps a hero's town work and
// when it keeps the company's trade XP (1059-company-trades.sql hr_work_cap_ms, hr_trade_is). This writes it whole, with a self-check
// that every skill category it names exists and that the cap it derives is the data's:
//   hr_work_day   id true; free_min, premium_extra_min, trade_cats text[], work_kinds text[]
//
// THE FORWARD-FILE RULE: an applied file is history and is never regenerated in place; new rows are a new sequence file (OUT_NAME).
//
//   node tools/gen-work-day.mjs            write OUT_NAME
//   node tools/gen-work-day.mjs --check    exit 1 if OUT_NAME is not what it would write
//   node tools/gen-work-day.mjs --selftest every refusal bites
//
// mutant-anchors: none — --selftest plants defects in an in-memory copy of the data; no tracked file is patched
//
// REFUSES (throws, nothing written): a table work-day.js validate() refuses (a day under an hour, Premium's extra past a quarter of
// the day, a longest day of 24 h or more, a combat category named a trade, a hunt named town work).
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';
import { sourceQuery } from './lib/version-stamp.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_NAME = '1059-company-trades-catalogue.generated.sql';
const OUT = join(ROOT, 'supabase', 'migrations', OUT_NAME);

async function load(root) {
  return import(pathToFileURL(join(root, 'src/data/work-day.js')).href + sourceQuery(root));
}

/** The resolved row of the data, refused on a defect. */
export function rowOf(data) {
  const problems = data.validate(data.WORK_DAY, data.TRADE_CATS, data.WORK_KINDS);
  if (problems.length) throw new Error('gen-work-day: ' + problems.join('; '));
  return {
    freeMin: data.WORK_DAY.freeMin, premiumExtraMin: data.WORK_DAY.premiumExtraMin,
    tradeCats: [...data.TRADE_CATS].sort(), workKinds: [...data.WORK_KINDS].sort(),
  };
}

const arr = (a) => `array[${a.map((x) => `'${x}'`).join(', ')}]::text[]`;

export function buildSql(r) {
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE WORK-DAY CATALOGUE  (GENERATED — DO NOT EDIT)
--
--   Generated by tools/gen-work-day.mjs from src/data/work-day.js (WORK_DAY, TRADE_CATS, WORK_KINDS).
--   Any hand edit FAILS \`node tools/gen-work-day.mjs --check\`.
--
-- WHAT (lane/r12-company-trades, backend-architect, 2026-11-22; FB-10 slice 1, Tyler's rulings CR-Q1 a and CR-Q3 b): the work day and
-- the company's trades as the server reads them, so no number is typed twice. hr_work_day (one row), rewritten whole: a hero's free
-- town-work day (${r.freeMin} min), Premium's extra (${r.premiumExtraMin} min), the skill categories that are company trades
-- (${r.tradeCats.join(', ')}) and the pointer kinds that are town work (${r.workKinds.join(', ')}).
-- READERS: 1059-company-trades.sql (hr_work_cap_ms, hr_trade_is, the \`work_day\` section). The minutes are LEVERS (econ.work-day,
-- econ.work-premium).
-- ORDER: 1059 in its name, before 1059-company-trades.sql (which reads this table). Idempotent: the table is made if missing and its
-- row rewritten whole, so a second apply is byte-identical. No begin/commit (CLAUDE.md §2).
-- EXPLOIT SURFACE: none added. A catalogue table, RLS on, no policy, no grant to any client role. No value moves here.
-- REVERSIBLE: drop the table (after 1059-company-trades.sql's readers are gone).
-- ════════════════════════════════════════════════════════════════════════

-- ── §0 PRECONDITIONS ─────────────────────────────────────────────────────────
do $mig$
begin
  if to_regclass('public.hr_skills') is null then
    raise exception 'PRECONDITION: the skill catalogue first (hr_skills)'; end if;
end $mig$;

-- ── §1 THE TABLE ─────────────────────────────────────────────────────────────
create table if not exists public.hr_work_day (
  id                boolean primary key default true check (id),
  free_min          int     not null check (free_min between 60 and 1439),
  premium_extra_min int     not null check (premium_extra_min between 0 and 1439),
  trade_cats        text[]  not null check (cardinality(trade_cats) >= 1),
  work_kinds        text[]  not null check (cardinality(work_kinds) >= 1),
  check (premium_extra_min * 4 <= free_min),
  check (not ('combat' = any (trade_cats)) and not ('combat' = any (work_kinds)))
);
alter table public.hr_work_day enable row level security;
revoke all on public.hr_work_day from public, anon, authenticated, service_role;
comment on table public.hr_work_day is '${OUT_NAME}: the work day and the company trades (src/data/work-day.js through tools/gen-work-day.mjs).';

-- ── §2 THE ROW ───────────────────────────────────────────────────────────────
delete from public.hr_work_day;
insert into public.hr_work_day (id, free_min, premium_extra_min, trade_cats, work_kinds) values
  (true, ${r.freeMin}, ${r.premiumExtraMin}, ${arr(r.tradeCats)}, ${arr(r.workKinds)});

-- ── §3 SELF-CHECK (CLAUDE.md §4) ──────────────────────────────────────────────
-- The row is the data's; no client role reads it; every trade category names skills in the catalogue, and none is combat.
do $mig$
declare v_r public.hr_work_day%rowtype;
begin
  select * into v_r from public.hr_work_day;
  if v_r.free_min is distinct from ${r.freeMin} or v_r.premium_extra_min is distinct from ${r.premiumExtraMin}
     or v_r.trade_cats is distinct from ${arr(r.tradeCats)} or v_r.work_kinds is distinct from ${arr(r.workKinds)} then
    raise exception 'VERIFY(a): hr_work_day holds %, not the data''s row', row_to_json(v_r); end if;
  if exists (select 1 from unnest(array['anon', 'authenticated']) g(r) where has_table_privilege(g.r, 'public.hr_work_day', 'select')) then
    raise exception 'VERIFY(b): a client role reads the work-day catalogue'; end if;
  if exists (select 1 from unnest(v_r.trade_cats) c where not exists (select 1 from public.hr_skills k where k.cat = c)) then
    raise exception 'VERIFY(c): a trade category names no skill in hr_skills'; end if;
  raise notice 'gen-work-day: a % min day (+% with Premium), % trade(s); all green', ${r.freeMin}, ${r.premiumExtraMin},
    (select count(*) from public.hr_skills k where k.cat = any (v_r.trade_cats));
end $mig$;
`;
}

export async function generate(root = ROOT) { return buildSql(rowOf(await load(root))); }

async function selftest() {
  const base = await load(ROOT);
  const bites = [];
  const plant = (name, patch) => {
    const T = { WORK_DAY: { ...base.WORK_DAY }, TRADE_CATS: [...base.TRADE_CATS], WORK_KINDS: [...base.WORK_KINDS] };
    patch(T);
    const data = { ...T, validate: base.validate };
    try { rowOf(data); bites.push(name + ': NOT refused'); } catch { /* refused */ }
  };
  plant('a day under an hour', (T) => { T.WORK_DAY.freeMin = 30; });
  plant('Premium past a quarter of the day', (T) => { T.WORK_DAY.premiumExtraMin = T.WORK_DAY.freeMin; });
  plant('a longest day of 24 h', (T) => { T.WORK_DAY.freeMin = 1400; T.WORK_DAY.premiumExtraMin = 0; });
  plant('combat skills as a company trade', (T) => { T.TRADE_CATS.push('combat'); });
  plant('a hunt as town work', (T) => { T.WORK_KINDS.push('combat'); });
  plant('a fractional minute', (T) => { T.WORK_DAY.freeMin = 480.5; });
  if (base.validate().length) bites.push('the shipped table is refused: ' + base.validate().join('; '));
  const sql = buildSql(rowOf(base));
  if (!/VERIFY\(a\)/.test(sql) || !/hr_work_day/.test(sql)) bites.push('the row is not self-checked');
  if (bites.length) { console.error('gen-work-day --selftest FAILED:\n  ' + bites.join('\n  ')); process.exit(1); }
  console.log('gen-work-day --selftest: 6 refusals bite, the row is self-checked');
}

if (isMain(import.meta.url)) {
  if (process.argv.includes('--selftest')) await selftest();
  else {
    const sql = await generate();
    if (process.argv.includes('--check')) {
      const have = await readFile(OUT, 'utf8').catch(() => '');
      if (have.replace(/\r/g, '') !== sql) { console.error('gen-work-day --check FAILED: ' + OUT_NAME + ' is stale. Run: node tools/gen-work-day.mjs'); process.exit(1); }
      console.log('gen-work-day --check: catalogue matches src/data');
    } else {
      await writeFile(OUT, sql);
      console.log('wrote ' + OUT);
    }
  }
}

#!/usr/bin/env node
// tools/access-allow.mjs — ADD (OR REMOVE) ONE ACCOUNT ON THE CLOSED-MODE
//                          ALLOWLIST, AS A GENERATED MIGRATION.
//
//   node tools/access-allow.mjs add <user-uuid> --note "<who, no email>"
//   node tools/access-allow.mjs remove <user-uuid>
//   options: --date YYYY-MM-DD (file date; default today UTC)
//            --offline         skip the read-only production lookup
//            --dry-run         print the SQL, write nothing
//
// While Hearthrise is closed (supabase/migrations/2026-10-21-closed-mode.sql)
// only accounts in public.hr_access_allowlist get past the server. No client can
// write that table; it changes only through a migration, so a change is
// reviewable, journalled in git, and replays. This tool writes that migration —
// supabase/migrations/<date>-access-<add|remove>-<uuid8>.sql — and registers it
// at the end of tests/schema-apply-order.json as STAGED. The Coordinator applies
// it with tools/apply-migration.mjs like any other file.
//
// Before writing, it asks production ONE read-only question (unless --offline):
// does this auth user exist, and is it already listed? A typo'd id is refused
// here rather than becoming a migration that admits nobody. The management-API
// token is read as file bytes from ~/.supabase-token and never printed.
//
// The repository is PUBLIC: the note names a person the way the team does
// ("Tyler", "QA account", "Sam (friend)") — never an email address.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const URL_Q = 'https://api.supabase.com/v1/projects/nezapsylztqbbwuwembx/database/query';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const NOTE = /^[A-Za-z0-9 ().,:'+-]{1,120}$/;

/** Validate the inputs. Returns an error string or null. Pure. */
export function checkInputs(verb, uuid, note) {
  if (verb !== 'add' && verb !== 'remove') return 'the verb is add or remove';
  if (!UUID.test(String(uuid || ''))) return 'the user id is not a lower-case uuid';
  if (verb === 'add') {
    if (!NOTE.test(String(note || ''))) return 'the note must be 1-120 letters, digits, spaces or ().,:\'+- (no email)';
  }
  return null;
}

/** The migration text for one change. Pure; inputs must already pass checkInputs. */
export function allowSql(verb, uuid, note, file) {
  const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
  const head = [
    '-- ════════════════════════════════════════════════════════════════════════',
    `-- ${file} — GENERATED by tools/access-allow.mjs. Do not edit; generate a new file.`,
    `--   ${verb === 'add' ? 'ADMITS' : 'REMOVES'} one account ${verb === 'add' ? 'to' : 'from'} the closed-mode allowlist`,
    '--   (supabase/migrations/2026-10-21-closed-mode.sql). STAGED: the Coordinator',
    '--   applies it with tools/apply-migration.mjs. Idempotent; a database without',
    '--   this auth user (the repo replay) changes nothing and says so.',
    '-- ════════════════════════════════════════════════════════════════════════',
    'do $mig$',
    'begin',
    "  if to_regclass('public.hr_access_allowlist') is null then",
    "    raise exception 'PRECONDITION: apply 2026-10-21-closed-mode.sql before this file';",
    '  end if;',
    'end $mig$;',
    '',
  ];
  const body = verb === 'add' ? [
    'insert into public.hr_access_allowlist (user_id, note)',
    `select ${q(uuid)}::uuid, ${q(note)}`,
    ` where exists (select 1 from auth.users where id = ${q(uuid)}::uuid)`,
    'on conflict (user_id) do update set note = excluded.note;',
  ] : [
    `delete from public.hr_access_allowlist where user_id = ${q(uuid)}::uuid;`,
  ];
  const check = [
    '',
    '-- §4 self-check, executed',
    'do $mig$',
    'begin',
    `  if not exists (select 1 from auth.users where id = ${q(uuid)}::uuid) then`,
    `    raise notice 'account ${uuid} is not on this database — nothing ${verb === 'add' ? 'admitted' : 'removed'}';`,
    '    return;',
    '  end if;',
    `  if ${verb === 'add' ? 'not ' : ''}exists (select 1 from public.hr_access_allowlist where user_id = ${q(uuid)}::uuid) then`,
    `    raise exception '${file}: the account is ${verb === 'add' ? 'not on' : 'still on'} the allowlist';`,
    '  end if;',
    'end $mig$;',
    '',
  ];
  return [...head, ...body, ...check].join('\n');
}

/* Read-only: does the account exist, and (once closed mode is applied) is it
   already listed? `uuid` has passed checkInputs, so it is a bare uuid. */
async function lookup(uuid) {
  const token = readFileSync(join(homedir(), '.supabase-token'), 'utf8').trim();
  const ask = async (sql) => {
    if (/\b(insert|update|delete|create|alter|drop|grant|revoke|truncate|call|do)\b/i.test(sql)) throw new Error('not select-only');
    const res = await fetch(URL_Q, {
      method: 'POST',
      headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ query: sql }),
    });
    const text = await res.text();
    if (!res.ok) throw new Error(`HTTP ${res.status}: ${text.slice(0, 300)}`);
    return JSON.parse(text)[0];
  };
  const a = await ask(`select exists (select 1 from auth.users where id = '${uuid}'::uuid) as present, `
                    + `to_regclass('public.hr_access_allowlist') is not null as has_table`);
  if (!a.has_table) return { present: a.present, listed: false, noTable: true };
  const b = await ask(`select exists (select 1 from public.hr_access_allowlist where user_id = '${uuid}'::uuid) as listed`);
  return { present: a.present, listed: b.listed, noTable: false };
}

async function main(argv) {
  const verb = argv[0];
  const uuid = String(argv[1] || '').toLowerCase();
  const opt = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : null; };
  const note = opt('--note');
  const date = opt('--date') || new Date().toISOString().slice(0, 10);
  const bad = checkInputs(verb, uuid, note) || (/^\d{4}-\d{2}-\d{2}$/.test(date) ? null : '--date is YYYY-MM-DD');
  if (bad) { console.error(`access-allow: ${bad}`); return 2; }

  if (!argv.includes('--offline')) {
    let r;
    try { r = await lookup(uuid); } catch (e) { console.error(`access-allow: production lookup failed (${e.message}); use --offline to skip`); return 1; }
    if (r.present !== true) { console.error(`access-allow: no auth user ${uuid} on production — check the id`); return 1; }
    if (r.noTable) console.error('access-allow: note — closed mode is not applied yet; this file must apply after it');
    if (verb === 'add' && r.listed) { console.error('access-allow: already on the allowlist — nothing to do'); return 0; }
    if (verb === 'remove' && !r.listed && !r.noTable) { console.error('access-allow: not on the allowlist — nothing to do'); return 0; }
  }

  const file = `${date}-access-${verb}-${uuid.slice(0, 8)}.sql`;
  const path = join(ROOT, 'supabase', 'migrations', file);
  const sql = allowSql(verb, uuid, note, file);
  if (argv.includes('--dry-run')) { process.stdout.write(sql); return 0; }
  if (existsSync(path)) { console.error(`access-allow: ${file} already exists`); return 1; }
  writeFileSync(path, sql);
  const mp = join(ROOT, 'tests', 'schema-apply-order.json');
  const m = JSON.parse(readFileSync(mp, 'utf8'));
  m.order.push(file);
  m._order_notes[file] = `STAGED, NOT APPLIED - generated by tools/access-allow.mjs: ${verb} ${uuid} `
    + `${verb === 'add' ? `(${note}) to` : 'from'} the closed-mode allowlist. Apply with tools/apply-migration.mjs; idempotent.`;
  writeFileSync(mp, JSON.stringify(m, null, 2) + '\n');
  console.log(`wrote supabase/migrations/${file} and registered it in tests/schema-apply-order.json (STAGED).`);
  console.log('Next: commit it on a lane branch; the Coordinator applies it with tools/apply-migration.mjs.');
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = await main(process.argv.slice(2));
}

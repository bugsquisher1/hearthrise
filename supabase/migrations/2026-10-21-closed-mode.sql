-- ── §3 hr_admitted ──────────────────────────────────────────────────────────
create or replace function public.hr_admitted(p_user uuid)
 returns boolean
 language sql
 volatile
 security invoker
 set search_path to 'public', 'pg_catalog'
as $fn$
  select p_user is not null
     and (coalesce((select not f.enabled from public.hr_flags f where f.key = 'closed_mode'), false)
          or exists (select 1 from public.hr_access_allowlist a where a.user_id = p_user));
$fn$;

-- ── §4 hr_access_check — THE PRE-REQUEST HOOK AND L2's FIRST LINE ──────────
create or replace function public.hr_access_check()
 returns void
 language plpgsql
 volatile
 security invoker
 set search_path to 'public', 'pg_catalog'
as $fn$
declare
  v_uid uuid := auth.uid();
begin
  -- Two statements, not `is null OR hr_admitted(…)`: SQL does not promise to
  -- short-circuit, and anon / service_role hold no EXECUTE on hr_admitted.
  if v_uid is null then return; end if;
  if public.hr_admitted(v_uid) then return; end if;
  raise sqlstate 'PGRST' using
    message = '{"code":"hr_closed","message":"Hearthrise is closed while we rebuild it.","details":null,"hint":null}',
    detail  = '{"status":403,"headers":{}}';
end $fn$;

-- ── §5 L2: hr_rpc_gate CALLS hr_access_check FIRST (ANCHORED SPLICE) ────────
do $mig$
declare
  v_src text; v_new text;
  c_anchor constant text := 'begin' || chr(10) || '  case p_bucket';
  c_line   constant text := 'perform public.hr_access_check();';
begin
  select pg_get_functiondef('public.hr_rpc_gate(text)'::regprocedure) into v_src;
  v_src := replace(v_src, chr(13), '');
  if position(c_line in v_src) > 0 then
    raise notice 'hr_rpc_gate already calls hr_access_check — splice skipped'; return;
  end if;
  if (length(v_src) - length(replace(v_src, c_anchor, ''))) <> length(c_anchor) then
    raise exception 'hr_rpc_gate: anchor ''begin / case p_bucket'' did not match exactly once — refusing to patch blind';
  end if;
  v_new := replace(v_src, c_anchor,
    'begin' || chr(10) ||
    '  -- CLOSED MODE (2026-10-21-closed-mode.sql): a signed-in caller who is not' || chr(10) ||
    '  -- admitted is refused hr_closed (HTTP 403) before any bucket is spent.' || chr(10) ||
    '  ' || c_line || chr(10) ||
    '  case p_bucket');
  execute v_new;
end $mig$;

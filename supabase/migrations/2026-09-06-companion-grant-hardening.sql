  if v_before is null or v_before = '' then
    raise exception '§3(b): the pre-state ACL recorded by §0 is unreadable. Apply this file in ONE '
                    'transaction (begin; ... commit;) — §0 hands it over through a transaction-local '
                    'GUC, and an unverifiable ACL on a SECURITY DEFINER function is not an assertion.';
  end if;
  v_r := coalesce((select proacl::text from pg_proc where oid = v_p), 'NULL');
  if v_r is distinct from v_before then
    raise exception '§3(b): the ACL MOVED across the replace: % -> %. A SECURITY DEFINER grant is '
                    'the whole game; this file is not permitted to change one.', v_before, v_r;
  end if;
  v_owner := current_setting('hearthrise.cgh_owner_before', true);
  if v_owner is distinct from (select proowner::regrole::text from pg_proc where oid = v_p) then
    raise exception '§3(b): the function OWNER moved (% -> %). On a SECURITY DEFINER function the '
                    'owner IS the authority it runs as.',
                    v_owner, (select proowner::regrole::text from pg_proc where oid = v_p);
  end if;

  -- (c) …and the ACL is the RIGHT one, stated independently of (b) so that
  --     "unchanged" can never mean "unchanged and wrong".
  if not has_function_privilege('authenticated', v_p, 'execute') then
    raise exception '§3(c): hr_companion_grant is not executable by authenticated — the client '
                    'cannot grant a companion it legitimately acquired.';
  end if;
  foreach v_r in array array['public','anon','service_role','hr_engine'] loop
    if has_function_privilege(v_r, v_p, 'execute') then
      raise exception '§3(c): hr_companion_grant is executable by % — it must be authenticated-only. '
                      'hr_engine especially: the accrual engine proposes deltas an RPC re-validates; '
                      'it must never grant a companion for somebody.', v_r;
    end if;
  end loop;

  -- (d) SECURITY DEFINER + a pinned search_path. Both were true before; a
  --     restate is exactly where they get lost.
  if (select prosecdef from pg_proc where oid = v_p) is not true then
    raise exception '§3(d): hr_companion_grant is no longer SECURITY DEFINER';
  end if;
  if not exists (select 1 from pg_proc where oid = v_p
                  and 'search_path=public' = any (coalesce(proconfig, array[]::text[]))) then
    raise exception '§3(d): hr_companion_grant lost its pinned search_path — a SECURITY DEFINER '
                    'function without one is resolvable by the caller''s search_path. proconfig = %',
                    (select proconfig from pg_proc where oid = v_p);
  end if;

  -- (e) THE THREE CONDITIONS ARE STRUCTURALLY PRESENT in the installed body.
  --     Text anchors, so §4's behavioural proofs cannot be the only evidence
  --     (a behavioural test can be satisfied by the wrong mechanism).
  select prosrc into v_src from pg_proc where oid = v_p;
  if v_src not like '%unknown_unlock:%' or v_src not like '%check_violation%' then
    raise exception '§3(e) C1: the installed body has no unknown_unlock translation';
  end if;
  if v_src not like '%missing_req_item%' then
    raise exception '§3(e) C2: the installed body has no missing_req_item refusal';
  end if;
  if v_src like '%v_egg := false;%' then
    raise exception '§3(e) C2: the fake control''s `v_egg := false;` fall-through is STILL in the '
                    'body — the precondition measures without deciding.';
  end if;
  if v_src not like '%claimed_source%' then
    raise exception '§3(e) C3: the installed body does not write claimed_source';
  end if;
  if v_src like '%''source'', p_source%' then
    raise exception '§3(e) C3: the installed body still writes the bare client key `source`';
  end if;
  -- The narrowness of the catch, asserted as TEXT as well as behaviour (§4(i)),
  -- in BOTH of its halves. `when others` would swallow every model violation the
  -- storage guard raises; and even under `when check_violation`, DROPPING THE
  -- MESSAGE TEST would swallow unlock_wrong_kind / unlock_over_ceiling /
  -- unlock_bad_rung / unlock_not_storable / unlock_regressed and report them as
  -- a tidy unknown_unlock. The re-raise is the backstop; it is anchored here so
  -- its removal cannot be a silent one-line edit.
  if v_src like '%exception when others%' then
    raise exception '§3(e) C1: the handler catches `when others`. It must catch check_violation and '
                    're-raise anything whose message is not unknown_unlock:, or the trigger''s '
                    'protection is gone.';
  end if;
  if v_src not like '%then raise; end if;%' then
    raise exception '§3(e) C1: the handler no longer RE-RAISES. Catching 23514 without testing the '
                    'message turns every storage-guard model violation into a false unknown_unlock '
                    'and silently disarms the trigger this translation sits on top of.';
  end if;

  -- (f) THE CLIENT-RPC BASELINE row still stands (this file does not change who
  --     may call the verb, and the hygiene detector reads this table).
  if not exists (select 1 from public.hr_client_rpc_baseline b
                  where b.proname = 'hr_companion_grant' and b.grantee = 'authenticated') then
    raise exception '§3(f): the hr_client_rpc_baseline row for hr_companion_grant is gone — the '
                    'grant-hygiene detector would report this verb as an unreviewed client surface.';
  end if;

  -- (g) THE ALLOWLIST IS UNTOUCHED. This file changes behaviour, never content.
  select count(*) into v_n from public.hr_companion_grants;
  if v_n <> 17 then raise exception '§3(g): hr_companion_grants moved to % rows', v_n; end if;
  select count(*) into v_n from public.hr_unlocks where namespace = 'companion';
  if v_n <> 21 then raise exception '§3(g): namespace=companion moved to % rows', v_n; end if;

  raise notice '§3 PASSED: one definition; ACL and owner byte-identical across the replace '
               '(%); authenticated-only, never anon/service_role/hr_engine; SECURITY DEFINER with '
               'search_path=public; C1+C2+C3 present by anchor; baseline row intact; catalogue '
               'untouched (17 grantable / 21 companion). New normalised body md5 = %.',
               v_before,
               md5(btrim(regexp_replace(regexp_replace(v_src, '--.*', '', 'gn'), '[[:space:]]+', ' ', 'g')));

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════
// tools/gen-temper.mjs — TEMPERING'S CATALOGUE, GENERATED FROM src/data/temper.js.
//
//   node tools/gen-temper.mjs              (re)write the newest file this tool owns (refused if APPLIED)
//   node tools/gen-temper.mjs --new <file> write a NEW forward file; place it in tests/schema-apply-order.json
//   node tools/gen-temper.mjs --check      exit 1 if the committed file differs from the data
//   node tools/gen-temper.mjs --selftest   a moved price or a dropped rung turns --check's comparison red
//
// It emits two sets of rows and no code: one MAX-merge ladder per track and tier in public.hr_unlocks, and the price of
// every rung in public.hr_unlock_offers, so the ONE existing spend RPC (public.hr_unlock_buy) sells them: rung order,
// already_owned, GREATEST, the per-day clamp, the intent key and the ledger are all its own. No magnitude crosses to
// Postgres: what a rung does is src/core/temper.js, and a rung is clamped to the ladder there.
//
// PURE ESM, Node only. Writes one file.
// ═══════════════════════════════════════════════════════════
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, normalize, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

import { generatedTarget, newestOwned } from './lib/generated-target.mjs';
import { TEMPER_OFFERS, TEMPER_UNLOCKS } from '../src/data/temper.js';

const ROOT = normalize(join(fileURLToPath(new URL('.', import.meta.url)), '..'));
const TOOL = 'gen-temper.mjs';
const die = (m) => { console.error('gen-temper: ' + m); process.exit(1); };
const argv = process.argv.slice(2);
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

export function render(unlocks, offers) {
  const digest = createHash('sha256').update(JSON.stringify({ unlocks, offers })).digest('hex');
  const ids = offers.map((r) => q(r.offer_id)).join(', ');
  const unlockIds = unlocks.map((u) => q(u.unlock_id)).join(', ');
  return `-- ═════════════════════════════════════════════════════════════
-- Hearthrise — TEMPERING'S CATALOGUE  (GENERATED — DO NOT EDIT BY HAND)
--   ${unlocks.length} ladders, ${offers.length} rungs  ·  digest ${digest}
--
--   Generated by tools/${TOOL} from src/data/temper.js. A hand edit fails
--   \`node tools/${TOOL} --check\` (the Tempering step in .github/workflows/smoke.yml).
--
-- Rows only: no function is replaced, no policy written, no grant changed. hr_unlock_buy sells whatever these tables
-- carry; hr_perks_of and hr_temper_view (2027-02-27-tempering.sql, the next file) read them back. The prices are the
-- designer's table, and each generator deletes only the rows it owns (hr_unlock_offers.source), so either catalogue may
-- be re-applied alone. SAFE TO RE-RUN.
--
-- REVERSIBILITY: delete from public.hr_unlock_offers where source = 'gen-temper';
--                delete from public.hr_unlocks where namespace = 'temper';
-- ═════════════════════════════════════════════════════════════

do $$
begin
  if to_regclass('public.hr_unlocks') is null or to_regclass('public.hr_unlock_offers') is null
     or to_regprocedure('public.hr_unlock_buy(uuid,int,bigint,uuid,text)') is null then
    raise exception 'PRECONDITION: the unlock catalogues or hr_unlock_buy are absent';
  end if;
  if not exists (select 1 from pg_trigger where tgrelid = 'public.player_progress'::regclass
                  and tgname = 'player_progress_unlock_guard' and not tgisinternal) then
    raise exception 'PRECONDITION: player_progress_unlock_guard is absent, and these ladders rely on it as their backstop';
  end if;
end $$;

insert into public.hr_unlocks (unlock_id, namespace, merge, progress_kind, max_value, rungs)
values
${unlocks.map((u) => `  (${q(u.unlock_id)}, ${q(u.namespace)}, ${q(u.merge)}, ${q(u.progress_kind)}, ${u.max_value}, array[${u.rungs.join(',')}]::int[])`).join(',\n')}
on conflict (unlock_id) do update
  set namespace = excluded.namespace, merge = excluded.merge,
      progress_kind = excluded.progress_kind, max_value = excluded.max_value, rungs = excluded.rungs;

delete from public.hr_unlock_offers where source = 'gen-temper';
insert into public.hr_unlock_offers
  (offer_id, table_name, name, unlock_id, value, gold, items, req_property_tier, req_item, refusal, source)
values
${offers.map((r) => `  (${q(r.offer_id)}, ${q(r.table_name)}, ${q(r.name)}, ${q(r.unlock_id)}, ${r.value}, ${r.gold}, ${q(JSON.stringify(r.items))}::jsonb, ${r.req_property_tier}, null, null, 'gen-temper')`).join(',\n')};

-- ── §4 SELF-CHECK — the rows, as hr_unlock_buy and the storage guard read them ──
do $$
declare v_n int; v_bad text;
begin
  select count(*) into v_n from public.hr_unlock_offers where source = 'gen-temper' and refusal is null and offer_id in (${ids});
  if v_n <> ${offers.length} then raise exception 'VERIFY: % of ${offers.length} Tempering rungs are sellable and owned', v_n; end if;
  select count(*) into v_n from public.hr_unlocks where namespace = 'temper' and unlock_id in (${unlockIds});
  if v_n <> ${unlocks.length} then raise exception 'VERIFY: % of ${unlocks.length} Tempering ladders are catalogued', v_n; end if;
  /* A rung off its own ladder is a player charged for a row the storage guard then refuses. */
  select string_agg(o.offer_id, ', ') into v_bad
    from public.hr_unlock_offers o join public.hr_unlocks u on u.unlock_id = o.unlock_id
   where o.source = 'gen-temper'
     and (u.namespace <> 'temper' or u.merge <> 'max' or u.progress_kind <> 'unlock' or not (o.value = any (u.rungs)) or o.value > u.max_value or o.gold <= 0);
  if v_bad is not null then raise exception 'VERIFY: Tempering rungs off their ladder: %', v_bad; end if;
  /* Every rung takes a positive count of a material hr_items holds: a rung with none is gold alone, and a name it doesn't hold is a sale nobody can make. */
  select string_agg(o.offer_id, ', ') into v_bad from public.hr_unlock_offers o
   where o.source = 'gen-temper' and (o.items = '{}'::jsonb or exists (select 1 from jsonb_each_text(o.items) t
     where t.value::bigint <= 0 or not exists (select 1 from public.hr_items i where i.item_id = t.key)));
  if v_bad is not null then raise exception 'VERIFY: Tempering rungs with no material hr_items holds: %', v_bad; end if;
  /* The tables' grants are unchanged: a client write here would be a client-authored price. */
  select count(*) into v_n from information_schema.role_table_grants
   where table_schema = 'public' and table_name = 'hr_unlock_offers'
     and grantee in ('anon', 'authenticated', 'service_role', 'PUBLIC') and privilege_type <> 'SELECT';
  if v_n > 0 then raise exception 'VERIFY: % client write grants on hr_unlock_offers', v_n; end if;
  raise notice 'tempering catalogue §4 OK: ${unlocks.length} ladders, ${offers.length} rungs';
end $$;
`;
}

if (argv.includes('--selftest')) {
  const base = render(TEMPER_UNLOCKS, TEMPER_OFFERS);
  const moved = render(TEMPER_UNLOCKS, TEMPER_OFFERS.map((r, i) => (i === 3 ? { ...r, gold: r.gold - 1 } : r)));
  const dropped = render(TEMPER_UNLOCKS, TEMPER_OFFERS.slice(1));
  if (moved === base) die('--selftest: a moved price does not change the file');
  if (dropped === base) die('--selftest: a dropped rung does not change the file');
  if (!base.includes("source = 'gen-temper'") || base.includes('delete from public.hr_unlock_offers;')) die('--selftest: the delete is not scoped to this tool\'s rows');
  console.log('gen-temper --selftest: a moved price and a dropped rung change the file, the delete is scoped');
  process.exit(0);
}

const text = render(TEMPER_UNLOCKS, TEMPER_OFFERS);
if (argv.includes('--check')) {
  const owned = newestOwned(ROOT, TOOL);
  if (!owned) die('no migration in tests/schema-apply-order.json carries "Generated by tools/' + TOOL + '"');
  const have = readFileSync(owned.path, 'utf8').replace(/\r\n/g, '\n');
  if (have !== text) die(owned.file + ' differs from src/data/temper.js: run node tools/' + TOOL + (owned.applied ? ' --new <file>' : ''));
  console.log('gen-temper --check: ' + owned.file + ' matches the data');
} else {
  const path = generatedTarget(ROOT, TOOL, argv, { write: true, die });
  writeFileSync(path, text);
  console.log('wrote ' + basename(path));
}

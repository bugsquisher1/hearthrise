#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-rally-action-times.mjs — GENERATE THE SERVER RALLY ACTION-TIME
//   CATALOGUE (what one gather / artisan action is worth in paced seconds).
//
// Rally points pay TIME, not haul (game-designer ruling 2026-10-10): every
// gather and artisan action pays its PACED duration in seconds,
//   round(ms x PACE.actionMs / 1000), minimum 1,
// read from the node / recipe the action was. Those times live in
// src/data/gathering.js, src/data/recipes.js and src/core/pacing.js and nowhere
// server-side, so this generator writes `public.hr_rally_action_s` from them.
// Copying game DATA into SQL by hand is the failure src/main.js `unifyObject`
// was written about; this file is machine-written and drift-guarded.
//
//   Regenerate:  node tools/gen-rally-action-times.mjs
//   Verify:      node tools/gen-rally-action-times.mjs --check   (CI)
//
// The POINT WEIGHT per paced second is NOT here: it lives in the one weights
// table, hr_rally_point_rules (2026-10-10-rally-points-server.sql).
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { TREES, ROCKS, FISH_SPOTS } from '../src/data/gathering.js';
import { ARTISAN_RECIPES } from '../src/data/recipes.js';
import { PACE } from '../src/core/pacing.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'supabase', 'migrations', '2026-10-10-rally-action-times.generated.sql');

export function pacedSeconds(ms) {
  return Math.max(1, Math.round((ms * PACE.actionMs) / 1000));
}

export function rows() {
  const out = [];
  const seen = new Set();
  const add = (kind, id, ms) => {
    if (!/^[a-z0-9_]+$/.test(id)) throw new Error(`${kind} id ${id} is not [a-z0-9_]`);
    if (!(Number.isFinite(ms) && ms > 0 && ms <= 600000)) throw new Error(`${kind} ${id} has out-of-range ms ${ms}`);
    const key = kind + ':' + id;
    if (seen.has(key)) throw new Error(`duplicate ${key}`);
    seen.add(key);
    out.push([kind, id, pacedSeconds(ms)]);
  };
  for (const n of [...TREES, ...ROCKS, ...FISH_SPOTS]) add('gather', n.id, n.ms);
  for (const skill of Object.keys(ARTISAN_RECIPES)) {
    for (const r of ARTISAN_RECIPES[skill]) add('artisan', r.id, r.ms);
  }
  return out.sort((a, b) => (a[0] + ':' + a[1]).localeCompare(b[0] + ':' + b[1]));
}

export function render() {
  const r = rows();
  const digest = createHash('sha256').update(JSON.stringify([PACE.actionMs, r])).digest('hex');
  const values = r.map(([k, id, s]) => `  ('${k}', '${id}', ${s})`).join(',\n');
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE RALLY ACTION-TIME CATALOGUE  (GENERATED — DO NOT EDIT)
--
--   Generated by tools/gen-rally-action-times.mjs from src/data/gathering.js,
--   src/data/recipes.js and src/core/pacing.js (PACE.actionMs = ${PACE.actionMs}).
--   Any hand edit FAILS \`node tools/gen-rally-action-times.mjs --check\` (CI).
--
--   digest: ${digest}
--   ${r.length} actions
--
-- Read by hr_rally_points_of (2026-10-10-rally-points-server.sql): one gather
-- node / artisan recipe action pays paced_s x the per-second weight in
-- hr_rally_point_rules. Paced seconds only — no weight lives here. Idempotent:
-- truncate + insert in the migration transaction.
-- ════════════════════════════════════════════════════════════════════════

create table if not exists public.hr_rally_action_s (
  kind        text not null check (kind in ('gather', 'artisan')),
  activity_id text not null,
  paced_s     int  not null check (paced_s between 1 and 600),
  primary key (kind, activity_id)
);
alter table public.hr_rally_action_s enable row level security;
-- Server-only reference data: no client reads it (the client never scores).
revoke all on public.hr_rally_action_s from public, anon, authenticated, service_role;

truncate table public.hr_rally_action_s;
insert into public.hr_rally_action_s (kind, activity_id, paced_s) values
${values};

do $$
declare v_n int;
begin
  select count(*) into v_n from public.hr_rally_action_s;
  if v_n <> ${r.length} then
    raise exception 'hr_rally_action_s has % rows, expected ${r.length}', v_n;
  end if;
  if has_table_privilege('authenticated', 'public.hr_rally_action_s', 'select')
     or has_table_privilege('anon', 'public.hr_rally_action_s', 'select') then
    raise exception 'hr_rally_action_s is client-readable';
  end if;
end $$;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const wanted = render();
  if (process.argv.includes('--check')) {
    const have = await readFile(OUT, 'utf8').catch(() => '');
    if (have.replace(/\r\n/g, '\n') !== wanted.replace(/\r\n/g, '\n')) {
      console.error('gen-rally-action-times --check FAILED: '
        + '2026-10-10-rally-action-times.generated.sql is stale. Run: node tools/gen-rally-action-times.mjs');
      process.exit(1);
    }
    console.log('gen-rally-action-times --check: catalogue matches src/data');
  } else {
    await writeFile(OUT, wanted);
    console.log(`wrote ${OUT}`);
  }
}

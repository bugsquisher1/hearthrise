--                                 DUNGEON SCRIP + RUN LOOT.
--                                 (§2 of docs/design/dungeon-settlement.md)
--
-- ⚠⚠⚠ REVIEW ONLY — NOT AUTO-APPLIED. The Coordinator applies this by hand
--     (execute_sql wrapped in begin/commit, or a Supabase branch apply) AFTER
--     the security review. It is a PROGRESSION surface: it credits the
--     server-owned Dungeon Scrip currency and run loot, and consumes the entry
--     key from inventory. Security review required before authority moves.
--
--   Reads:   2026-09-10-dungeon-catalogue.generated.sql (hr_dungeons /
--            hr_dungeon_loot) and player_state.dungeon_scrip
--            (2026-09-10-dungeon-scrip.sql). FAILS CLOSED without either.
--   Edge:    supabase/functions/hr-accrue/dungeon-settle.js (the ONLY caller)
--   Client:  src/dungeons.js / src/dungeon-scavenger.js (send the intent,
--            reconcile scrip + loot from the returned envelope)
--   Test:    tests/dungeon-settle.mjs (PGlite replay + mutation proof)
--
-- ⚠ AFTER APPLYING: this file re-derives hr_assert_grant_hygiene (§5, the
--   ⟦DERIVED⟧ block, generated by tools/derive-grant-hygiene.mjs) to admit the
--   ONE new engine grant. It becomes the CURRENT LAST TOUCHER of
--   hr_assert_grant_hygiene — LINKS[6] / HR_GRANT_HYGIENE_CHAIN's seventh link.
--   The detector is ALSO a live-hash-tracked body; re-seed the baseline with
--   `node tests/live-hash-drift.mjs --live --write` after the apply. It TAKES
--   OVER NO OTHER last-toucher role — hr_state_of is patched by the sibling
--   2026-09-10-dungeon-scrip.sql, not here.
--
-- ── WHAT THIS DOES, AND WHY ─────────────────────────────────────────────────
-- Dungeon scrip + run loot are minted CLIENT-side today (awardDungeonScrip /
-- awardLoot → window.addItem / G.inventory) with NO server write, so BLOB_RETIRED
-- wipes them on reload — the reported "dungeon scrip goes to 0" P1
-- (dungeon-settlement.md §0). This RPC settles a run ONCE, in ONE transaction:
--   · consumes the entry KEY from player_inventory (a run costs a real
--     server-held key — the b501 key drops folded into combat drops made keys
--     server-settled, which is the hard prerequisite for this);
--   · rolls each loot row with the SEEDED server PRNG (hr_seed) from the
--     generated catalogue and credits survivors into player_inventory;
--   · credits round(scrip_base * clamp(p_quality,0,1)) into
--     player_state.dungeon_scrip;
--   · bumps version, journals ONE kind='dungeon' row, and returns the hr_state_of
--     envelope + a `settled` receipt.
-- The template is hr_unlock_buy (2026-08-16-unlock-buy.sql): engine-only, one
-- protected block that raises through hr_reject → HR000 → rollback, idempotency
-- on player_intents via hr_intent_replay, per-day clamp from the append-only
-- ledger, self-verifying commit gate.
--
-- ── ANTI-FORGERY (why a forged client value mints nothing across a boundary) ─
-- The ONLY client-authored number is p_quality, and it is CLAMPED server-side to
-- [0,1] and scales SELF-ONLY scrip — never loot. Loot is a pure server-RNG roll
-- of the generated catalogue (rates + ids the client cannot name or price),
-- salted with the 256-bit server secret via hr_seed, so the next roll is not
-- computable in devtools. The entry key is debited from the caller's OWN
-- inventory. The cooldown and the per-day scrip cap read now() and the ledger.
-- The catalogues are client-UNREADABLE. So: a forged p_quality gains at most the
-- top of a fixed band on the caller's OWN scrip; a forged p_dungeon_id →
-- unknown_dungeon; a forged p_mode → bad_mode. Scrip is self-only (never traded),
-- so CLAUDE.md's target property — "a forged client value cannot cross into
-- ANOTHER player's economy or ranking" — holds: there is no cross-player surface.
--
--   ⚠ FLAGGED FOR THE GAME DESIGNER + SECURITY (a deliberate change, not a bug):
--     · LOOT NO LONGER SCALES WITH THE CLEAR. The client scaled manual/scavenger
--       loot qty by clear fraction (0.4x–2x) and added a BoP-chance bonus; this
--       RPC pays the FLAT catalogue roll regardless of mode/quality. That removes
--       the client's arithmetic lever over loot entirely (the server-authority
--       win) but IS a payout change the Designer should sign off. If a
--       clear-scaled loot multiplier is wanted, it belongs in the catalogue /
--       server, keyed off a SERVER-verifiable clear signal, not p_quality.
--     · Most dungeon loot is ORDINARY TRADEABLE material (26 of 33 ids); only 7
--       signature spoils are BoP. That is fine — loot is server-authored exactly
--       like a combat drop and gated by real server-held keys — but it means the
--       reward set is NOT "BoP-only". The bop flag is carried in the catalogue +
--       the journal so a future BoP-only policy has the fact to assert against.
--     · TWO BLAST-RADIUS FUSES, not balance (the clan_deposit posture; Designer
--       ruling 2026-09-05): c_daily_scrip_cap = 5,000 GROSS-EARNED scrip/UTC-day
--       (positive settle rows only — a Quartermaster spend never reduces it, or a
--       spend→earn→spend loop would launder the ceiling) and c_daily_count_cap =
--       250 SETTLES/UTC-day (anti-replay insurance; counts meta.op='settle' only,
--       so QM spend rows do not touch it). Over either → daily_cap, with a `dim`
--       of 'scrip' | 'count'. Tune as Designer numbers; both are far above honest
--       play and far below "grind the whole shop in a day".
--
-- ── WHAT IT DELIBERATELY DOES NOT DO ────────────────────────────────────────
--   · It does NOT stamp accrued_to. A run is not an activity change, so the
--     unpaid accrual window survives it (hr_unlock_buy's rule).
--   · It does NOT re-grant keys. Keys are ordinary server-rolled combat drops
--     (b501); this RPC only CONSUMES one as the entry gate.
--   · It does NOT consult hr_day_budget_check. That ceiling is on GROSS INFLOW;
--     the reward is a fixed server-owned grant kept OUT of the accrual budget
--     (qty_in/gold_in/xp_in = 0 explicit), like the muster credit.
--
-- ── REVERSIBILITY ───────────────────────────────────────────────────────────
--   drop function public.hr_dungeon_settle(uuid,int,bigint,uuid,text,text,numeric);
--   -- re-apply 2026-09-10-attended-loot-credit.sql (link 7, the base this body
--   --   was rebased onto for b504) to restore hr_assert_grant_hygiene WITHOUT the
--   --   dungeon_settle allowlist entry but WITH the hr_attended_kills entry — NOT
--   --   2026-08-20-live-progress-engine-allow.sql, which would also revert link 7.
--   The scrip / loot / ledger rows it wrote are ordinary player rows and survive.
--   The dungeon catalogues are dropped by re-running their own generated file's
--   revert; nothing here alters them.
--
-- SAFE TO RE-RUN. Every step is guarded and §6's probes roll themselves back.
-- ════════════════════════════════════════════════════════════════════════


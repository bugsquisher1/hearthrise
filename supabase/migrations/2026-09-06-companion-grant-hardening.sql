-- ── 1. THE HARDENED BODY ─────────────────────────────────────────────────
-- Restated in full from the measured live body (see the header). EVERY line
-- outside the three marked blocks is that body verbatim; the comments are the
-- authoring file's, restored, because production's copy was applied stripped.
--
-- ── THE SHAPE OF C1: TWO LAYERS, AND WHY BOTH ────────────────────────────
--   LAYER A — a pre-check on public.hr_unlocks, placed AFTER the owned-once
--     short-circuit (so an already-owned companion whose catalogue row vanished
--     is still reported already_owned — no write is needed, so no refusal is
--     owed) and BEFORE the req_item read. It is the path that fires in the
--     named incident, it returns a deterministic refusal, and it reaches no
--     mutation at all.
--   LAYER B — a NARROW handler around the mutation block, for the TOCTOU race
--     Layer A cannot close: nothing locks public.hr_unlocks, and the b453 class
--     IS a concurrent wholesale `delete from public.hr_unlocks`, so the row can
--     vanish between the pre-check and the insert. The handler catches SQLSTATE
--     23514 and re-raises unless the message begins 'unknown_unlock:'. Because
--     the req_item consume is INSIDE that subtransaction, a raced refusal rolls
--     the egg back with the grant — the alternative (an exception block around
--     the insert alone) would leave the egg consumed and the companion not
--     granted, which is a player-value loss dressed as a fix.
--   The trigger remains the BACKSTOP: Layer A does not decide storability, and
--   Layer B translates exactly one message and propagates every other.
create or replace function public.hr_companion_grant(
  p_slot int default 0,
  p_companion text default null,
  p_source text default null,
  p_idem uuid default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid   uuid := auth.uid();
  v_st    public.player_state%rowtype;
  v_cat   public.hr_companion_grants%rowtype;
  v_key   text;
  v_prev  bigint;
  v_have  bigint;
  v_egg   boolean := null;
  v_raced boolean := false;
  -- Acquisitions are rare (a bounded lifetime of 17 non-shop pets); 60/hour
  -- is generous and cheap, and a rejected call still consumes budget (A9).
  c_rate constant int := 60;
begin
  if v_uid is null then return jsonb_build_object('ok', false, 'error', 'not_signed_in'); end if;

  -- ── RATE GATE (A9) — hr_companion_equip's exact shape, SAMPLED writes ─────
  if not public.hr_rate_ok(v_uid, 'companion_grant', c_rate, interval '1 hour') then
    if public.hr_rate_sample_weight(public.hr_rate_over(v_uid, 'companion_grant') - c_rate) > 0 then
      perform public.hr_record_rejection(v_uid, coalesce(p_slot, 0), 'companion_grant', 'rate_limited',
        jsonb_build_object('limit', c_rate, 'per', '1 hour'),
        public.hr_rate_sample_weight(public.hr_rate_over(v_uid, 'companion_grant') - c_rate));
    end if;
    return jsonb_build_object('ok', false, 'error', 'rate_limited');
  end if;

  if p_slot is null or p_slot < 0 or p_slot > 5 then
    return jsonb_build_object('ok', false, 'error', 'bad_slot');
  end if;
  if p_companion is null or p_companion = '' then
    return jsonb_build_object('ok', false, 'error', 'unknown_companion');
  end if;

  -- ── THE ALLOWLIST GATE — the mint refusal, BEFORE any lock. A shop companion
  --    (sold for gold by hr_unlock_buy) and an unknown/forged id are both ABSENT
  --    here and refused by name. A perk a client could mint for itself for free
  --    dies here.
  select * into v_cat from public.hr_companion_grants where companion_id = p_companion;
  if not found then
    -- C3: the client's claim is named as a CLAIM even in a refusal. One value,
    -- one name, on every row this verb writes.
    perform public.hr_record_rejection(v_uid, coalesce(p_slot, 0), 'companion_grant', 'not_grantable',
      jsonb_build_object('companion', p_companion, 'claimed_source', p_source));
    return jsonb_build_object('ok', false, 'error', 'not_grantable',
      'detail', jsonb_build_object('companion', p_companion));
  end if;

  -- Serialise this character — the SAME advisory key hr_apply / hr_companion_equip take.
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text || ':' || p_slot::text, 0));

  select * into v_st from public.player_state where user_id = v_uid and slot = p_slot for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'no_character'); end if;

  v_key := 'companion:' || p_companion;

  -- ── OWNED-ONCE IDEMPOTENCY. A companion is a boolean; owning it already is a
  --    success that consumes NO req_item, writes NO journal row and does NOT bump
  --    the version — a replay is harmless. (The ON CONFLICT below is the second,
  --    independent guard against a concurrent double-grant.)
  select value into v_prev from public.player_progress
   where user_id = v_uid and slot = p_slot and kind = 'unlock' and key = v_key and period_key = '';
  if coalesce(v_prev, 0) > 0 then
    return jsonb_build_object('ok', true, 'companion', p_companion, 'already_owned', true);
  end if;

  -- ══ C1, LAYER A — THE STORAGE HOME, CHECKED BEFORE ANYTHING IS SPENT ═════
  -- Without this row player_progress_unlock_guard raises 23514 and the caller
  -- gets a 500 it cannot tell from an outage. Placed after owned-once (an owner
  -- needs no write) and before the req_item read (a refusal must cost nothing).
  if not exists (select 1 from public.hr_unlocks where unlock_id = v_key) then
    perform public.hr_record_rejection(v_uid, p_slot, 'companion_grant', 'unknown_unlock',
      jsonb_build_object('companion', p_companion, 'unlock_id', v_key,
                         'claimed_source', p_source, 'catalogue_source', v_cat.source_kind,
                         'raced', false));
    return jsonb_build_object('ok', false, 'error', 'unknown_unlock:' || v_key,
      'detail', jsonb_build_object('companion', p_companion, 'unlock_id', v_key, 'raced', false));
  end if;

  -- ══ C2 — THE SERVER-VERIFIABLE PRECONDITION, ENFORCED ════════════════════
  -- (dragon_egg hatch -> whelp.) Previously this read the inventory, recorded
  -- the answer in v_egg, and granted either way: a control that measured but
  -- did not decide. It now REFUSES, and refuses before any write. The FOR
  -- UPDATE row lock is taken HERE, at the check, and held for the rest of the
  -- transaction, so the consume below cannot race a concurrent spend of the
  -- same egg.
  if v_cat.req_item is not null then
    select qty into v_have from public.player_inventory
     where user_id = v_uid and slot = p_slot and item_id = v_cat.req_item for update;
    if coalesce(v_have, 0) < 1 then
      perform public.hr_record_rejection(v_uid, p_slot, 'companion_grant', 'missing_req_item',
        jsonb_build_object('companion', p_companion, 'item', v_cat.req_item,
                           'held', coalesce(v_have, 0), 'claimed_source', p_source,
                           'catalogue_source', v_cat.source_kind));
      return jsonb_build_object('ok', false, 'error', 'missing_req_item',
        'item', v_cat.req_item, 'companion', p_companion);
    end if;
  end if;

  -- ══ THE MUTATION — ONE SUBTRANSACTION (C1, LAYER B) ══════════════════════
  -- Consume + grant + version bump + journal are ATOMIC against the guard's
  -- refusal, so a raced unknown_unlock rolls the req_item back too.
  begin
    if v_cat.req_item is not null then
      if v_have = 1 then
        delete from public.player_inventory
         where user_id = v_uid and slot = p_slot and item_id = v_cat.req_item;
      else
        update public.player_inventory set qty = v_have - 1
         where user_id = v_uid and slot = p_slot and item_id = v_cat.req_item;
      end if;
      v_egg := true;
    end if;

    -- ── THE GRANT. A single-rung [1] unlock row. ON CONFLICT DO NOTHING makes a
    --    concurrent double-grant a no-op; hr_unlock_guard independently refuses any
    --    value off the companion:<id> ladder.
    insert into public.player_progress (user_id, slot, kind, key, period_key, value)
      values (v_uid, p_slot, 'unlock', v_key, '', 1)
    on conflict (user_id, slot, kind, key, period_key) do nothing;

    -- Version bump so an in-flight client re-reads the owned set (reconcileCompanions
    -- reads it from the envelope). accrued_to is UNTOUCHED — a grant does not reprice
    -- an in-flight accrual (the passive bonus is priced off the EQUIPPED id, which a
    -- grant does not change), so no collect-first guard and no confiscation.
    update public.player_state
       set version = version + 1, updated_at = now()
     where user_id = v_uid and slot = p_slot;

    -- ── THE JOURNAL. ONE row per acquisition (a rare event, bounded lifetime —
    --    journal rule 6 is about per-tick logging, which this is not).
    --    C3: `claimed_source` is what the CLIENT said; `catalogue_source` is what
    --    the SERVER's own allowlist says. They are no longer peers by name.
    insert into public.player_ledger (user_id, slot, kind, intent, meta)
      values (v_uid, p_slot, 'admin', 'companion_grant',
              jsonb_build_object('companion', p_companion, 'claimed_source', p_source,
                                 'catalogue_source', v_cat.source_kind,
                                 'req_item', v_cat.req_item, 'egg_consumed', v_egg,
                                 'idem', p_idem));
  exception when check_violation then
    -- NARROW BY MESSAGE, NOT BY SQLSTATE ALONE. hr_unlock_guard raises 23514 for
    -- unknown_unlock, unlock_wrong_kind, unlock_over_ceiling, unlock_bad_rung,
    -- unlock_not_storable and unlock_regressed, and every table here can raise
    -- 23514 from a check constraint. Only the FIRST is a refusal this verb owns;
    -- the rest are model violations that must stay loud. `raise;` re-raises the
    -- original, so the trigger's protection is intact.
    if sqlerrm not like 'unknown_unlock:%' then raise; end if;
    v_raced := true;
  end;

  if v_raced then
    -- The catalogue row was deleted between Layer A and the insert. Same machine
    -- code, flagged `raced` so the ledger can tell "it was already gone" from
    -- "it vanished mid-transaction" — the difference between a stale deploy and
    -- an active wholesale delete.
    perform public.hr_record_rejection(v_uid, p_slot, 'companion_grant', 'unknown_unlock',
      jsonb_build_object('companion', p_companion, 'unlock_id', v_key,
                         'claimed_source', p_source, 'catalogue_source', v_cat.source_kind,
                         'raced', true));
    return jsonb_build_object('ok', false, 'error', 'unknown_unlock:' || v_key,
      'detail', jsonb_build_object('companion', p_companion, 'unlock_id', v_key, 'raced', true));
  end if;

  return jsonb_build_object('ok', true, 'companion', p_companion, 'egg_consumed', v_egg);
end $$;


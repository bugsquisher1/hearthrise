// STATS AGAINST STATS. Nothing here reads a hero's Level (Tyler 2026-11-04 "They are just simply harder", 2026-11-18 NO LEVEL IN
// COMBAT). `base` is a flat rating every body has, so +10 Defense at Level 10 is not a doubling. The two monster ratings are
// AUTHORED, like its HP and its blow, from its own Level against THE REFERENCE HERO of that Level (balance-sheet.js formulaStats
// writes them on the row; the engine reads only the two numbers): a regular on a full ground lands STAT_FORMULA.hit on the
// reference hero and the reference hero lands STAT_FORMULA.heroHit on it, at every Level. Because the form is a ratio, a reference
// that is 5% off moves a chance by about 1.5 points: it degrades, it never runs into a clamp. `min` and `max` are safety rails only;
// no same-Level fight on Normal reaches them from Level 1 to 1,000 (tests/balance-sheet.mjs).
// What this retires (21-combat.md B2): the straight lines 0.55 + (skill - def) x 0.01 and baseAcc + (atk - Defense) x 0.02, their
// clamps, ACC_DEF_MUL and STAT_FORMULA.def.past, each a patch on a line that ran off its range.
//
// THE REFERENCE HERO (REF_HERO): the lone hammer's measured career (tools/balance-sim/skill-lines.json, the engine's own carry from
// Level 1), [Level, main skill, Defense, worn accuracy], every 5 Levels to 100, then sparser to 1,000, projected past the line's top
// on the skill curve's own cost (the same projection as tools/balance-sim/measure.mjs curves). GENERATED by tools/gen-ref-hero.mjs
// (never edit by hand; tests/balance-sheet.mjs runs its --check), and re-measured when the pace or the hammer's kit moves.
//
// PURE ESM. Data and pure functions only: no DOM, no clock, no randomness.

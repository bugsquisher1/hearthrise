// src/core/piece-value.js — WHAT A TRAIT PIECE IS WORTH, AND WHAT THE STORE PAYS FOR ONE (backend-architect, lane/t1b-piece-verbs,
// 2026-11-26; docs/design/redesign/13-market.md section 3.2 "V for a piece", 09-crafting.md section 4.6 the store floor, 20-v030-the-roads.md
// section 1.2 "Trait pieces are kept, carried over or sold to the store").
//
//   V(piece)   = floor(sharePm x hoursPm x rankPm x wage(item Level) / 10^9)      hoursPm: the rarity's "one in N hunted hours", in milli-hours
//   rankPm     = 1000 + rankValuePm x (top rank - 1)                                the piece's highest Trait (a Signature carries none: 1)
//   bid(piece) = floor(floorSharePm x V / 1000)                                     the store's floor share of V
//
// The levers are src/data/piece-price.js PIECE_VALUE (sharePm, rankValuePm), src/data/drop-hours.js DROP_HOURS.rarity (everyHours) and
// src/data/trades.js TRADE_LEVERS.store.floorShare. Exact whole-number arithmetic (BigInt), so the server's numeric twin
// (hr_piece_store_bid, generated by tools/gen-piece-value.mjs and pinned there against this file) reaches the same last gold.
// A rarity the drop table authors no hours for has no price (null): the store does not buy it.
//
// The browser never prices a piece: the `pieces` section carries the server's bid (CLAUDE.md §6). PURE ESM, dual-runtime, no clock.
// ════════════════════════════════════════════════════════════════════════
import { PIECE_VALUE } from '../data/piece-price.js';
import { DROP_HOURS } from '../data/drop-hours.js';
import { TRADE_LEVERS } from '../data/trades.js';
import { wage } from '../data/wage.js';

const own = (o, k) => !!o && Object.prototype.hasOwnProperty.call(o, k);

/** The levers as whole permille, the unit the server's catalogue stores. */
export const PIECE_PM = Object.freeze({
  share: PIECE_VALUE.sharePm,
  rankValue: PIECE_VALUE.rankValuePm,
  floorShare: Math.round(TRADE_LEVERS.store.floorShare * 1000),
});

/** Milli-hours of the rarity's "one in about N hunted hours", or null for a rarity the drop table does not author. */
export function rarityHoursPm(rarity) {
  const row = own(DROP_HOURS.rarity, rarity) ? DROP_HOURS.rarity[rarity] : null;
  const h = row ? Number(row.everyHours) : NaN;
  return h > 0 ? Math.round(h * 1000) : null;
}

/** The piece's highest Trait rank, 1 for none (a Signature) or any rank that is not a whole number of at least 1. */
export function topRankOf(traits) {
  let top = 1;
  for (const t of Array.isArray(traits) ? traits : []) {
    const r = t && Number.isInteger(t.rank) ? t.rank : 0;
    if (r > top) top = r;
  }
  return top;
}

/** V of a piece { rarity, il (item Level), traits }, whole gold; null where the rarity has no hours. */
export function pieceValue(piece) {
  const p = piece || {};
  const hoursPm = rarityHoursPm(p.rarity);
  if (hoursPm === null) return null;
  const rankPm = 1000 + PIECE_PM.rankValue * (topRankOf(p.traits) - 1);
  const il = Number.isInteger(p.il) ? p.il : 1;
  return Number((BigInt(PIECE_PM.share) * BigInt(hoursPm) * BigInt(rankPm) * BigInt(wage(il))) / 1000000000n);
}

/** What the store pays for a piece, whole gold; null where it does not buy one. */
export function pieceStoreBid(piece) {
  const v = pieceValue(piece);
  return v === null ? null : Number((BigInt(PIECE_PM.floorShare) * BigInt(v)) / 1000n);
}

#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tests/migration-names.mjs — EVERY MIGRATION SAYS WHERE IT RUNS, AND NO TWO LANES COLLIDE (CLAUDE.md rule 12).
//
//   node tests/migration-names.mjs             the guard (static, credential-free, under a second)
//   node tests/migration-names.mjs --selftest  planted trees: each defect caught by its named check
//
// THE FAILURES IT KILLS (2026-11-19). Every migration lane edited one shared file,
// tests/schema-apply-order.json, so every two migration lanes conflicted on it (four send-backs
// in one day), and three lanes picked the same "next date", 2027-05-28, whose relative order then
// lived only in that file. Since the sidecars (tools/lib/apply-order.mjs) a new migration is named
// NNNN-<slug>.sql by tools/new-migration.mjs, one more than the highest sequence on the lane's base:
// a file can depend only on files its lane could see, all of which sort before it.
//
// THE CHECKS:
//   NAME-1  the apply order derives: every .sql has a sidecar, every sidecar a file, no seq twice,
//           no date-named file past history.last_seq, no tests/schema-apply-order.json beside them.
//   NAME-2  every migration is history (YYYY-MM-DD-*.sql, with its frozen seq) or sequence-named
//           (NNNN-<slug>.sql, NNNN >= 1000). A new date-named file is the habit this rule ends.
//   NAME-3  a sequence-named file's sidecar carries its apply note, leading with its claim (STAGED /
//           NOT APPLIED / APPLIED): the deployment record an operator reads. History is grandfathered.
//   NAME-4  two files with the SAME sequence (two lanes cut from the same base) must not both write
//           the same function or both be one generator's output: their order is by name only, so
//           the later silently replaces the other's body. The later lane re-derives from the other
//           and takes the next number (node tools/new-migration.mjs --renumber <file>).
// LIMIT, stated: NAME-4 sees only exact-sequence siblings. A lane that merged main and then wrote
// against a newer file without renumbering is caught by the replay (schema-drift) or, for a body
// both sides restate, by live-hash-drift after the apply; the tool makes the right number by default.
//
// Exit: 0 green · 1 a finding · 2 harness.
// ════════════════════════════════════════════════════════════════════════
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { isMain } from './_is-main.mjs';
import {
  ROOT, MIG_DIR, NOTES_DIR, CHAIN_FILE, SEQ_FLOOR, readTree, deriveApplyOrder, isSeqName, isHistoryName,
  seqOfName, noteFileOf, sidecarText,
} from '../tools/lib/apply-order.mjs';

const CLAIM = /^\s*(?:STAGED\b|NOT\s+APPLIED\b|APPLIED\b)/i;
const codeOnly = (sql) => sql.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/--[^\n]*/g, ' ');

/** The functions a file writes: a create (or replace), or an anchored patch read off pg_get_functiondef. */
export function writtenFunctions(sql) {
  const code = codeOnly(sql);
  const out = new Set();
  for (const m of code.matchAll(/create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?"?([a-z0-9_]+)"?\s*\(/gi)) out.add(m[1].toLowerCase());
  for (const m of code.matchAll(/pg_get_functiondef\(\s*'(?:public\.)?([a-z0-9_]+)/gi)) out.add(m[1].toLowerCase());
  return out;
}
export const generatorOf = (sql) => { const m = /Generated by (tools\/[\w./-]+\.mjs)/.exec(sql); return m ? m[1] : null; };

/**
 * Every finding over one tree. Pure apart from reading the .sql text through `read`.
 * @param {object} tree  readTree()
 * @param {(file:string)=>string} read
 * @returns {{check:string, detail:string}[]}
 */
export function findings(tree, read) {
  const out = [];
  const say = (check, detail) => out.push({ check, detail });
  const { manifest, problems } = deriveApplyOrder(tree);
  for (const p of problems) say('NAME-1', p);

  for (const f of tree.onDisk) {
    if (isSeqName(f)) {
      if (seqOfName(f) < SEQ_FLOOR) say('NAME-2', `${f}: a sequence under ${SEQ_FLOOR} (history's range). Name new files with node tools/new-migration.mjs <slug>.`);
      continue;
    }
    if (!isHistoryName(f)) {
      say('NAME-2', `${f} is neither history (YYYY-MM-DD-*.sql) nor sequence-named (NNNN-<slug>.sql). New files: node tools/new-migration.mjs <slug>.`);
    }
  }

  for (const f of tree.onDisk) {
    if (!isSeqName(f)) continue;
    const sc = tree.sidecars.get(f);
    if (!sc) continue;   // NAME-1 has it
    const note = Array.isArray(sc.note) ? sc.note.join(' ') : sc.note;
    if (typeof note !== 'string' || !CLAIM.test(note)) {
      say('NAME-3', `${NOTES_DIR}/${noteFileOf(f)}: the note must lead with its claim (STAGED, NOT APPLIED … / APPLIED <date> …); `
        + `it reads ${JSON.stringify(String(note || '').slice(0, 60))}`);
    }
  }

  /* NAME-4: same-sequence siblings in the chain */
  const bySeq = new Map();
  for (const f of manifest.order) if (isSeqName(f)) bySeq.set(seqOfName(f), [...(bySeq.get(seqOfName(f)) || []), f]);
  for (const [seq, files] of bySeq) {
    if (files.length < 2) continue;
    const info = files.map((f) => { const sql = read(f); return { f, fns: writtenFunctions(sql), gen: generatorOf(sql) }; });
    for (let i = 0; i < info.length; i++) {
      for (let j = i + 1; j < info.length; j++) {
        const a = info[i]; const b = info[j];
        const both = [...a.fns].filter((n) => b.fns.has(n));
        if (both.length) {
          say('NAME-4', `${a.f} and ${b.f} share sequence ${seq} (two lanes cut from the same base) and both write `
            + `${both.join(', ')}: by name, ${b.f} runs last and drops what ${a.f} changed. Re-derive the later lane's body `
            + `from the other's, then node tools/new-migration.mjs --renumber ${b.f}.`);
        }
        if (a.gen && a.gen === b.gen) {
          say('NAME-4', `${a.f} and ${b.f} share sequence ${seq} and are both ${a.gen}'s output: each was rendered `
            + `without the other lane's data. Regenerate on the merged tree into one file (--renumber the later).`);
        }
      }
    }
  }
  return out;
}

function main() {
  const tree = readTree(ROOT);
  const list = findings(tree, (f) => readFileSync(join(ROOT, MIG_DIR, f), 'utf8'));
  if (list.length) {
    console.error('MIGRATION NAMES (CLAUDE.md rule 12):\n');
    for (const x of list) console.error(`  ${x.check}  ${x.detail}\n`);
    console.error(`${list.length} finding(s).`);
    process.exit(1);
  }
  const seqd = tree.onDisk.filter(isSeqName).length;
  console.log(`migration-names: ${tree.onDisk.length} migration(s) placed (${tree.onDisk.length - seqd} history, ${seqd} sequence-named), `
    + `${tree.retiredDisk.length} retired; every sidecar matches a file, no two same-sequence siblings write one function.`);
}

// ════════════════════════════════════════════════════════════════════════
// --selftest: planted trees, each defect caught by the check written for it
// ════════════════════════════════════════════════════════════════════════
function selftest() {
  let bad = 0;
  const FN = (n) => `create or replace function public.${n}() returns int language sql as $$ select 1 $$;\n`;
  const base = {
    '2026-08-08-a.sql': { sql: FN('hr_a'), sc: { seq: 1, note: 'APPLIED 2026-08-08' } },
    '2026-08-09-b.sql': { sql: FN('hr_b'), sc: { seq: 2 } },
    '1000-first.sql': { sql: FN('hr_c'), sc: { note: 'STAGED, NOT APPLIED (lane/x)' } },
    '1001-second.sql': { sql: FN('hr_c'), sc: { note: 'STAGED, NOT APPLIED (lane/x)' } },
  };
  const build = (over = {}) => {
    const d = mkdtempSync(join(tmpdir(), 'hr-migration-names-'));
    mkdirSync(join(d, MIG_DIR), { recursive: true });
    mkdirSync(join(d, NOTES_DIR), { recursive: true });
    writeFileSync(join(d, CHAIN_FILE), JSON.stringify({ history: { last_seq: 2 } }));
    for (const [f, v] of Object.entries({ ...base, ...over })) {
      if (v === null) continue;
      if (v.sql !== undefined) writeFileSync(join(d, MIG_DIR, f), v.sql);
      if (v.sc !== undefined) writeFileSync(join(d, NOTES_DIR, noteFileOf(f)), sidecarText(v.sc));
    }
    return d;
  };
  const run = (d) => findings(readTree(d), (f) => readFileSync(join(d, MIG_DIR, f), 'utf8'));
  const CASES = [
    ['clean tree: history + consecutive sequences, one function restated in order', {}, null],
    ['NEGATIVE CONTROL: two same-sequence siblings writing DIFFERENT functions', {
      '1002-left.sql': { sql: FN('hr_left'), sc: { note: 'STAGED, NOT APPLIED (lane/l)' } },
      '1002-right.sql': { sql: FN('hr_right'), sc: { note: 'STAGED, NOT APPLIED (lane/r)' } },
    }, null],
    ['a NEW date-named file with a sidecar past history (the 2027-05-28 habit)', {
      '2027-05-28-late.sql': { sql: FN('hr_late'), sc: { seq: 3, note: 'STAGED, NOT APPLIED' } } }, 'NAME-1'],
    ['a new date-named file reusing a history seq', {
      '2027-05-28-late.sql': { sql: FN('hr_late'), sc: { seq: 2, note: 'STAGED, NOT APPLIED' } } }, 'NAME-1'],
    ['a migration with no sidecar (unplaced)', { '1002-orphan.sql': { sql: FN('hr_o') } }, 'NAME-1'],
    ['a sidecar with no migration (stale)', { '1002-gone.sql': { sc: { note: 'STAGED, NOT APPLIED' } } }, 'NAME-1'],
    ['a sequence under the floor', { '0999-low.sql': { sql: FN('hr_low'), sc: { note: 'STAGED, NOT APPLIED' } } }, 'NAME-2'],
    ['a name of neither shape, placed by hand', { 'fix.sql': { sql: FN('hr_fix'), sc: { seq: 3, note: 'STAGED' } } }, 'NAME-2'],
    ['a new file whose note makes no claim', { '1002-quiet.sql': { sql: FN('hr_q'), sc: { note: 'adds hr_q' } } }, 'NAME-3'],
    ['a new file with no note at all', { '1002-mute.sql': { sql: FN('hr_m'), sc: {} } }, 'NAME-3'],
    ['two same-sequence siblings both replacing hr_c (two lanes, one base)', {
      '1002-left.sql': { sql: FN('hr_c'), sc: { note: 'STAGED, NOT APPLIED (lane/l)' } },
      '1002-right.sql': { sql: `do $m$ declare v text; begin v := pg_get_functiondef('public.hr_c()'::regprocedure); execute replace(v, '1', '2'); end $m$;\n`,
        sc: { note: 'STAGED, NOT APPLIED (lane/r)' } },
    }, 'NAME-4'],
    ['two same-sequence siblings rendered by one generator', {
      '1002-left.generated.sql': { sql: '-- Generated by tools/gen-x.mjs\nselect 1;\n', sc: { note: 'STAGED, NOT APPLIED (lane/l)' } },
      '1002-right.generated.sql': { sql: '-- Generated by tools/gen-x.mjs\nselect 2;\n', sc: { note: 'STAGED, NOT APPLIED (lane/r)' } },
    }, 'NAME-4'],
    ['the old shared JSON back beside the sidecars', { __legacy: true }, 'NAME-1'],
  ];
  for (const [what, over, want] of CASES) {
    const legacy = over.__legacy; const o = { ...over }; delete o.__legacy;
    const d = build(o);
    try {
      if (legacy) { mkdirSync(join(d, 'tests'), { recursive: true }); writeFileSync(join(d, 'tests', 'schema-apply-order.json'), '{}'); }
      const got = run(d);
      const pass = want === null ? got.length === 0 : got.some((x) => x.check === want);
      console.log(`  ${pass ? 'ok ' : 'x  '} ${what}${want ? ` -> ${want}` : ' -> silent'}`
        + (pass ? '' : `\n     got: ${got.map((x) => `${x.check} ${x.detail.slice(0, 90)}`).join(' | ') || '(nothing)'}`));
      if (!pass) bad += 1;
    } finally { rmSync(d, { recursive: true, force: true }); }
  }
  if (!existsSync(join(ROOT, NOTES_DIR))) { console.error('  x  the real tree has no sidecars'); bad += 1; }
  if (bad) { console.error(`\n${bad} case(s) failed.`); process.exit(1); }
  console.log(`\nmigration-names --selftest: all ${CASES.length} planted trees behaved as their check requires`);
}

if (isMain(import.meta.url)) {
  try { if (process.argv.includes('--selftest')) selftest(); else main(); }
  catch (e) { console.error(e.harness ? `HARNESS: ${e.message}` : e); process.exit(2); }
}

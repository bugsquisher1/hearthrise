#!/usr/bin/env node
// tools/gm-allow.mjs — MAKE ONE FRESH ACCOUNT THE GAME MASTER, AS A GENERATED MIGRATION.
//
//   node tools/gm-allow.mjs add <user-uuid> --note "<who, no email>"
//   options: --date YYYY-MM-DD (file date; default today UTC)
//            --offline         skip the read-only production lookup
//            --dry-run         print the SQL, write nothing
//
// One row of public.hr_gm_accounts is both the powers and the wall (supabase/migrations/2027-03-05-gm-tools.sql). No client can write
// that table; it changes only through a migration, so a change is reviewable, journalled in git, and replays. This tool writes that
// migration, supabase/migrations/<date>-gm-add-<uuid8>.sql, and registers it at the end of tests/schema-apply-order.json as STAGED. The
// Coordinator applies it with tools/apply-migration.mjs. It also admits the account (closed mode), since a Game Master who cannot sign in
// is nothing.
//
// THE WALL IS ONLY HONEST ON A FRESH ACCOUNT. Before writing it asks production ONE read-only question (unless --offline): does this
// auth user exist, and has it a hero? An account with a hero is refused here, and by the table's own trigger if it got past: a real
// hero must never become grantable (CLAUDE.md §2). There is no `remove`: lifting the wall would release what was granted.
//
// The repository is PUBLIC: the note names a person the way the team does ("Tyler's Game Master"), never an email address. The
// management-API token is read as file bytes from ~/.supabase-token and never printed.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from '../tests/_is-main.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const URL_Q = 'https://api.supabase.com/v1/projects/nezapsylztqbbwuwembx/database/query';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const NOTE = /^[A-Za-z0-9 ().,:'+-]{1,120}$/;

/** Validate the inputs. Returns an error string or null. Pure. */
export function checkInputs(verb, uuid, note) {
  if (verb !== 'add') return 'the verb is add (there is no remove: lifting the wall would release what was granted)';
  if (!UUID.test(String(uuid || ''))) return 'the user id is not a lower-case uuid';
  if (!NOTE.test(String(note || ''))) return 'the note must be 1-120 letters, digits, spaces or ().,:\'+- (no email)';
  return null;
}

/** The migration text. Pure; inputs must already pass checkInputs. */
export function gmSql(uuid, note, file) {
  const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
  return [
    '-- ════════════════════════════════════════════════════════════════════════',
    `-- ${file} — GENERATED by tools/gm-allow.mjs. Do not edit; generate a new file.`,
    '--   MAKES one fresh account the Game Master (2027-03-05-gm-tools.sql) and admits it. STAGED: the Coordinator',
    '--   applies it with tools/apply-migration.mjs. Idempotent; a database without this auth user (the repo replay)',
    '--   changes nothing and says so. The table refuses an account that already has a hero.',
    '-- ════════════════════════════════════════════════════════════════════════',
    'do $mig$',
    'begin',
    "  if to_regclass('public.hr_gm_accounts') is null then",
    "    raise exception 'PRECONDITION: apply 2027-03-05-gm-tools.sql before this file';",
    '  end if;',
    'end $mig$;',
    '',
    'insert into public.hr_access_allowlist (user_id, note)',
    `select ${q(uuid)}::uuid, ${q(note)}`,
    ` where exists (select 1 from auth.users where id = ${q(uuid)}::uuid)`,
    'on conflict (user_id) do nothing;',
    'insert into public.hr_gm_accounts (user_id, note)',
    `select ${q(uuid)}::uuid, ${q(note)}`,
    ` where exists (select 1 from auth.users where id = ${q(uuid)}::uuid)`,
    'on conflict (user_id) do nothing;',
    '',
    '-- §4 self-check, executed',
    'do $mig$',
    'begin',
    `  if not exists (select 1 from auth.users where id = ${q(uuid)}::uuid) then`,
    `    raise notice 'account ${uuid} is not on this database — nobody was made Game Master';`,
    '    return;',
    '  end if;',
    `  if not exists (select 1 from public.hr_gm_accounts where user_id = ${q(uuid)}::uuid) then`,
    `    raise exception '${file}: the account is not the Game Master';`,
    '  end if;',
    `  if not exists (select 1 from public.hr_lb_hidden where user_id = ${q(uuid)}::uuid and slot is null) then`,
    `    raise exception '${file}: the boards do not hide the account';`,
    '  end if;',
    'end $mig$;',
    '',
  ].join('\n');
}

/* Read-only: does the account exist, how many heroes has it, is it already the Game Master? `uuid` has passed checkInputs. */
async function lookup(uuid) {
  const token = readFileSync(join(homedir(), '.supabase-token'), 'utf8').trim();
  const sql = `select exists (select 1 from auth.users where id = '${uuid}'::uuid) as present, `
    + `(select count(*)::int from public.player_state where user_id = '${uuid}'::uuid) as heroes, `
    + `to_regclass('public.hr_gm_accounts') is not null as has_table`;
  if (/\b(insert|update|delete|create|alter|drop|grant|revoke|truncate|call|do)\b/i.test(sql)) throw new Error('not select-only');
  const res = await fetch(URL_Q, {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query: sql }),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${text.slice(0, 300)}`);
  return JSON.parse(text)[0];
}

async function main(argv) {
  const verb = argv[0];
  const uuid = String(argv[1] || '').toLowerCase();
  const opt = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : null; };
  const note = opt('--note');
  const date = opt('--date') || new Date().toISOString().slice(0, 10);
  const bad = checkInputs(verb, uuid, note) || (/^\d{4}-\d{2}-\d{2}$/.test(date) ? null : '--date is YYYY-MM-DD');
  if (bad) { console.error(`gm-allow: ${bad}`); return 2; }

  if (!argv.includes('--offline')) {
    let r;
    try { r = await lookup(uuid); } catch (e) { console.error(`gm-allow: production lookup failed (${e.message}); use --offline to skip`); return 1; }
    if (r.present !== true) { console.error(`gm-allow: no auth user ${uuid} on production — check the id`); return 1; }
    if (r.heroes > 0) { console.error(`gm-allow: that account has ${r.heroes} hero(es). A Game Master account starts empty: sign up a new one.`); return 1; }
    if (!r.has_table) console.error('gm-allow: note — 2027-03-05-gm-tools.sql is not applied yet; this file must apply after it');
  }

  const file = `${date}-gm-add-${uuid.slice(0, 8)}.sql`;
  const path = join(ROOT, 'supabase', 'migrations', file);
  const sql = gmSql(uuid, note, file);
  if (argv.includes('--dry-run')) { process.stdout.write(sql); return 0; }
  if (existsSync(path)) { console.error(`gm-allow: ${file} already exists`); return 1; }
  writeFileSync(path, sql);
  const mp = join(ROOT, 'tests', 'schema-apply-order.json');
  const m = JSON.parse(readFileSync(mp, 'utf8'));
  m.order.push(file);
  m._order_notes[file] = `STAGED, NOT APPLIED - generated by tools/gm-allow.mjs: makes ${uuid} (${note}) the Game Master and admits it. Apply with tools/apply-migration.mjs; idempotent.`;
  writeFileSync(mp, JSON.stringify(m, null, 2) + '\n');
  console.log(`wrote supabase/migrations/${file} and registered it in tests/schema-apply-order.json (STAGED).`);
  console.log('Next: commit it on a lane branch; the Coordinator applies it with tools/apply-migration.mjs.');
  return 0;
}

if (isMain(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}

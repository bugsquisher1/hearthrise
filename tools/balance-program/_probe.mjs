import { collectAll } from './collect.mjs';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const { anchors, memoryRead } = await collectAll({ root });
writeFileSync(process.argv[2], JSON.stringify(anchors));
const by = {};
for (const a of anchors) by[a.kind] = (by[a.kind] || 0) + 1;
console.log(memoryRead, anchors.length, JSON.stringify(by));

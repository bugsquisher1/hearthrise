#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-gear-catalogue.mjs — WRITE EVERY PIECE OF GEAR'S DERIVED STATS (Systems, lane/gear-catalogue-steps, 2026-11-22).
//
// src/core/gear-stats.js gearStats is the one formula, src/data/gear-profiles.js its levers. The data layer can't call src/core, so this
// writes the answer for every piece into src/data/gear-stats.generated.js (GEAR_STATS: id -> its base stats), and every item module reads
// it back through withGearStats. The inputs a piece gives the formula are its slot, item Level (`iL`, else `reqLv`), profile (its
// weaponType, hands and discipline, its armourClass, or `gearProfile`), rarity and named offset (`statPlus`); a row with `statsAs: <id>`
// is that row's piece (its own offset on top). Never a row's stat fields: a stale table can't feed itself.
//
// WHAT IS WRITTEN: every gear row of src/data/items.js ITEMS (ammo is a supply) and the hidden fist wraps (src/data/fists.js), keyed by
// id, and the staged special-attribute sample (src/data/special-attributes.js) under 'special:<id>' (a hidden row's id can be a live
// item's); a sample with a `base` is that standard piece, its attribute on top. NOT written: the copies items.js builds from other rows
// at load (a Tower weapon `towerKey`, a Catacomb piece `catacombTier`, a crafted jewel's grade `jewelGrade`): they take their base's.
//
//   node tools/gen-gear-catalogue.mjs             write src/data/gear-stats.generated.js
//   node tools/gen-gear-catalogue.mjs --check     exit 1 if it is not what this would write, or a row carries stats it was not given
//   node tools/gen-gear-catalogue.mjs --selftest  every refusal and the drift check bite
//
// mutant-anchors: none — --selftest plants defects in an in-memory copy of the rows; no tracked file is patched
//
// REFUSES (throws, nothing written): a gear row with no profile, a statPlus naming a field that is not a base stat, a statsAs that is
// not an item.
// ════════════════════════════════════════════════════════════════════════
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'src', 'data', 'gear-stats.generated.js');
const imp = (p) => import(pathToFileURL(join(ROOT, p)).href);

/* a copy items.js builds from another row at load: its stats are its base's */
export const isCopy = (it) => !!(it && (it.towerKey || it.catacombTier || it.jewelGrade));

/** id -> base stats for every piece the catalogue holds (the inputs only: slot, item Level, profile, rarity, statPlus, statsAs). */
export function deriveAll(GS, items, fists, sample) {
  const out = {};
  const put = (key, row, pool) => {
    const s = GS.statsOfRow(row, undefined, pool);
    if (!s) throw new Error('gen-gear-catalogue: ' + key + ' (slot ' + row.slot + ') has no gear profile');
    out[key] = s;
  };
  for (const [id, it] of Object.entries(items)) if (GS.isGearRow(it) && !isCopy(it)) put(id, it, items);
  for (const [id, it] of Object.entries(fists)) if (GS.isGearRow(it) && !Object.prototype.hasOwnProperty.call(out, id)) put(id, it, items);
  for (const [id, s] of Object.entries(sample)) put('special:' + id, s.base ? { ...s.row, statsAs: s.base } : s.row, items);
  return out;
}

const num = (v) => (Number.isInteger(v) ? String(v) : String(Math.round(v * 1000) / 1000));
export function render(all) {
  const lines = Object.keys(all).sort().map((id) => '  ' + JSON.stringify(id) + ': f({ ' + Object.entries(all[id]).map(([k, v]) => k + ': ' + num(v)).join(', ') + ' }),');
  return [
    '// GENERATED by tools/gen-gear-catalogue.mjs from src/core/gear-stats.js and src/data/gear-profiles.js. Do not edit: change a profile,',
    "// a curve or a row's statPlus and run `node tools/gen-gear-catalogue.mjs` (`--check` is the drift guard).",
    '// Every piece of gear\'s base stats, by id (a staged special-attribute sample row as \'special:<id>\').',
    'const f = Object.freeze;',
    'export const GEAR_STATS = f({',
    ...lines,
    '});',
    '',
  ].join('\n');
}

/* a row's base stats as the catalogue holds them (the read-back half of --check) */
async function loaded() {
  const GS = await imp('src/core/gear-stats.js');
  const { ITEMS } = await imp('src/data/items.js');
  const { FIST_ITEMS } = await imp('src/data/fists.js');
  const SA = await imp('src/data/special-attributes.js');
  const { GEAR_STAT_FIELDS } = await imp('src/data/gear-profiles.js');
  /* the sample's rows as authored: SPECIAL_SAMPLE's rows carry the read-back stats, so strip them to the inputs */
  const strip = (r) => Object.fromEntries(Object.entries(r).filter(([k]) => !GEAR_STAT_FIELDS.includes(k)));
  const sample = Object.fromEntries(Object.entries(SA.SPECIAL_SAMPLE).map(([id, s]) => [id, { ...s, row: strip(s.row) }]));
  return { GS, ITEMS, FIST_ITEMS, SPECIAL_SAMPLE: SA.SPECIAL_SAMPLE, sample, GEAR_STAT_FIELDS };
}

/** Every disagreement between the generated table and the catalogue as loaded (a row that kept a stat by hand, a stale entry). */
export function readBack(all, L) {
  const bad = [];
  const same = (a, b) => L.GEAR_STAT_FIELDS.every((k) => (a[k] || 0) === (b[k] || 0));
  const statsOf = (it) => Object.fromEntries(L.GEAR_STAT_FIELDS.filter((k) => it[k]).map((k) => [k, it[k]]));
  for (const [id, it] of Object.entries(L.ITEMS)) {
    if (!L.GS.isGearRow(it) || isCopy(it)) continue;
    if (!all[id] || !same(all[id], statsOf(it))) bad.push(id + ' carries ' + JSON.stringify(statsOf(it)) + ', the formula gives ' + JSON.stringify(all[id] || null));
  }
  for (const [id, s] of Object.entries(L.SPECIAL_SAMPLE)) {
    const k = 'special:' + id;
    if (!all[k] || !same(all[k], statsOf(s.row))) bad.push(k + ' carries ' + JSON.stringify(statsOf(s.row)) + ', the formula gives ' + JSON.stringify(all[k] || null));
  }
  return bad;
}

async function selftest() {
  const L = await loaded();
  const bites = [];
  const base = deriveAll(L.GS, L.ITEMS, L.FIST_ITEMS, L.sample);
  const refuses = (why, items) => { try { deriveAll(L.GS, items, {}, {}); bites.push('did not refuse: ' + why); } catch { /* bit */ } };
  refuses('a gear row with no profile', { x: { slot: 'weapon', type: 'weapon', weaponType: 'spoon', reqLv: 10 } });
  refuses('a statPlus on a field that is not a base stat', { x: { slot: 'weapon', type: 'weapon', weaponType: 'sword', reqLv: 10, statPlus: { steadyPm: 5 } } });
  refuses('a statsAs that is not an item', { x: { slot: 'body', type: 'armor', armourClass: 'plate', reqLv: 10, statsAs: 'no_such_piece' } });
  /* the drift check: a planted change to a row's stats as loaded, and an item the table never wrote */
  const id = 'rune_platebody';
  const planted = { ...L, ITEMS: { ...L.ITEMS, [id]: { ...L.ITEMS[id], defB: (L.ITEMS[id].defB || 0) + 1 } } };
  if (!readBack(base, planted).some((b) => b.startsWith(id + ' '))) bites.push('a hand-typed armor point on ' + id + ' read as derived');
  const missing = { ...base }; delete missing.dawn_sword;
  if (!readBack(missing, L).some((b) => b.startsWith('dawn_sword '))) bites.push('a piece missing from the table read as derived');
  /* the formula moves with its lever: a profile change moves its family's rows */
  const sword = L.GS.gearStats({ slot: 'weapon', iL: 60, profile: 'sword', rarity: 'common' });
  if (!(sword.atkB > 0 && sword.strB > 0 && sword.atkB > sword.strB)) bites.push('the sword profile is not the sword');
  if (bites.length) { console.error('gen-gear-catalogue --selftest FAILED:\n  ' + bites.join('\n  ')); process.exit(1); }
  console.log('gen-gear-catalogue --selftest: 5 refusals and drift plants bite');
}

if (isMain(import.meta.url)) {
  try {
    if (process.argv.includes('--selftest')) { await selftest(); process.exit(0); }
    const L = await loaded();
    const all = deriveAll(L.GS, L.ITEMS, L.FIST_ITEMS, L.sample);
    const text = render(all);
    if (process.argv.includes('--check')) {
      const have = readFileSync(OUT, 'utf8').replace(/\r/g, '');
      const bad = readBack(all, L);
      if (have !== text) bad.unshift('src/data/gear-stats.generated.js is stale. Run: node tools/gen-gear-catalogue.mjs');
      if (bad.length) { console.error('gen-gear-catalogue --check FAILED (' + bad.length + '):\n  ' + bad.slice(0, 20).join('\n  ')); process.exit(1); }
      console.log('gen-gear-catalogue --check: ' + Object.keys(all).length + ' pieces derived, the table and the catalogue agree');
      process.exit(0);
    }
    writeFileSync(OUT, text);
    console.log('gen-gear-catalogue: wrote ' + Object.keys(all).length + ' pieces to src/data/gear-stats.generated.js');
  } catch (e) { console.error(String(e && e.stack || e)); process.exit(2); }
}

#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-farm-catalogues.mjs — GENERATE THE SERVER FARM-GATE CATALOGUES.
//
// The server-authoritative farm RPCs (2026-08-22-server-farming-complete.sql)
// must own four sets of numbers that, until now, lived ONLY on the client:
//
//   1. hr_crops.regrow_limit — the FINITE-PERENNIAL cap. A `regrows:true` crop
//        is not infinite; one seed buys REGROW_LIMITS[id] regrows then withers.
//        Source: src/core/farm.js REGROW_LIMITS × the `regrows` flag in
//        src/data/gathering.js CROPS. Emitted as a column-add + UPDATE so the
//        column exists and carries the values on an older-generator database
//        (hr_crops itself is generated by tools/gen-catalogues.mjs; this file
//        only fills the ONE farm-owned column so regenerating the whole master
//        catalogue — and redeploying hr-accrue — is not required).
//   2. hr_crop_plot_tier  — which PLOT TIER unlocks a crop. Source:
//        PLOT_TIERS[t].unlocks in src/core/farm.js.
//   3. hr_plot_tier       — the DEED cost to reach each plot level. Source:
//        PLOT_TIERS[t].cost in src/core/farm.js.
//   4. hr_farm_yield_perk — the FLAT farmYield paid at harvest by the SERVER-
//        owned perk stack: the Garden room rung (src/data/perks.js
//        ROOM_PERKS.garden), the Scarecrow plot building (src/core/perks.js
//        PLOT_PERKS.scarecrow) and any companion carrying `bonus.farmYield`
//        (src/data/companions.js COMPANIONS).
//
// Copying game DATA into SQL by hand is the failure src/main.js `unifyObject`
// was written about. This file is machine-written from those single sources and
// drift-guarded (`--check`, a preflight in tests/run-smoke.mjs), so the copy
// cannot rot.
//
//   Regenerate:  node tools/gen-farm-catalogues.mjs
//   Verify:      node tools/gen-farm-catalogues.mjs --check   (run in run-smoke)
//
// DELIBERATELY NOT HERE (documented UNDER-pay of farmYield — the safe direction
// per CLAUDE.md; never over-pay): food buffs and world-event farmYield (not
// durable server state), and the companion doubleYield PROC (an RNG event at
// harvest, a different mechanic). The server pays the permanent, server-owned
// portion only.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { PLOT_TIERS, MAX_PLOT_LEVEL, REGROW_LIMITS } from '../src/core/farm.js';
import { ROOM_PERKS } from '../src/data/perks.js';
import { PLOT_PERKS } from '../src/core/perks.js';
import { COMPANIONS } from '../src/data/companions.js';
import { CROPS } from '../src/data/gathering.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'supabase', 'migrations', '2026-08-22-farm-catalogues.generated.sql');

// ── 0. crop → finite regrow limit (0 for a non-regrow crop) ─────────────
// A regrowing crop MUST carry a finite (>0) limit; the assertion below and the
// harvest RPC both reject an infinite perennial. A non-regrow crop is 0 (the
// value is never read for it — it does not restart the cycle).
function regrowLimits() {
  const rows = [];
  for (const id of Object.keys(CROPS).sort()) {
    const c = CROPS[id];
    const regrows = c.regrows === true;
    const lim = REGROW_LIMITS[id];
    if (regrows) {
      if (!Number.isInteger(lim) || lim <= 0) {
        throw new Error(`regrowing crop ${id} has no finite REGROW_LIMITS entry (got ${lim})`);
      }
    } else if (lim !== undefined) {
      throw new Error(`non-regrow crop ${id} must not carry a REGROW_LIMITS entry`);
    }
    rows.push([id, regrows ? lim : 0]);
  }
  return rows;
}

// ── 1. crop → the LOWEST plot tier whose unlock set contains it ──────────
function cropPlotTiers() {
  const seen = new Map();
  for (let lv = 1; lv <= MAX_PLOT_LEVEL; lv++) {
    const t = PLOT_TIERS[lv];
    if (!t || !Array.isArray(t.unlocks)) throw new Error(`PLOT_TIERS[${lv}] has no unlocks array`);
    for (const crop of t.unlocks) {
      if (!/^[a-z0-9_]+$/.test(crop)) throw new Error(`crop id ${crop} is not [a-z0-9_]`);
      if (!seen.has(crop)) seen.set(crop, lv);   // first (lowest) tier wins
    }
  }
  return [...seen.entries()].sort((a, b) => a[0].localeCompare(b[0]));
}

// ── 2. plot level → DEEDS required to REACH it (PLOT_TIERS[lv].cost) ─────
function plotTierCosts() {
  const rows = [];
  for (let lv = 1; lv <= MAX_PLOT_LEVEL; lv++) {
    const c = PLOT_TIERS[lv].cost;
    if (!Number.isInteger(c) || c < 0) throw new Error(`PLOT_TIERS[${lv}].cost is not a non-negative int: ${c}`);
    rows.push([lv, c]);
  }
  if (rows[0][1] !== 0) throw new Error('level 1 must cost 0 deeds (the starting state)');
  return rows;
}

// ── 3. perk key → flat farmYield ────────────────────────────────────────
function yieldPerks() {
  const rows = [];
  const garden = ROOM_PERKS.garden;
  if (!Array.isArray(garden)) throw new Error('ROOM_PERKS.garden missing');
  garden.forEach((rung, i) => {
    const v = (rung && rung.farmYield) || 0;
    if (!Number.isInteger(v) || v < 0) throw new Error(`garden rung ${i + 1} farmYield not a non-negative int: ${v}`);
    rows.push([`garden:${i + 1}`, v]);
  });
  const sc = (PLOT_PERKS.scarecrow && PLOT_PERKS.scarecrow.farmYield) || 0;
  if (!Number.isInteger(sc) || sc < 0) throw new Error(`scarecrow farmYield not a non-negative int: ${sc}`);
  rows.push(['scarecrow', sc]);
  for (const id of Object.keys(COMPANIONS).sort()) {
    const v = COMPANIONS[id].bonus && COMPANIONS[id].bonus.farmYield;
    if (v === undefined || v === null) continue;
    if (!Number.isInteger(v) || v < 0) throw new Error(`companion ${id} farmYield not a non-negative int: ${v}`);
    if (!/^[a-z0-9_]+$/.test(id)) throw new Error(`companion id ${id} is not [a-z0-9_]`);
    rows.push([`companion:${id}`, v]);
  }
  return rows;
}

export function render() {
  const regrow = regrowLimits();
  const crops = cropPlotTiers();
  const tiers = plotTierCosts();
  const perks = yieldPerks();
  const nRegrowFinite = regrow.filter(([, v]) => v > 0).length;
  const digest = createHash('sha256')
    .update(JSON.stringify({ regrow, crops, tiers, perks })).digest('hex');
  const regrowV = regrow.map(([id, v]) => `  ('${id}', ${v})`).join(',\n');
  const cropsV = crops.map(([id, t]) => `  ('${id}', ${t})`).join(',\n');
  const tiersV = tiers.map(([lv, c]) => `  (${lv}, ${c})`).join(',\n');
  const perksV = perks.map(([k, v]) => `  ('${k}', ${v})`).join(',\n');
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE SERVER FARM-GATE CATALOGUES  (GENERATED — DO NOT EDIT)
--
--   Generated by tools/gen-farm-catalogues.mjs from src/core/farm.js,
--   src/data/gathering.js, src/data/perks.js, src/core/perks.js and
--   src/data/companions.js. Any hand edit is reverted by the next generation
--   and FAILS \`node tools/gen-farm-catalogues.mjs --check\` (a preflight in
--   tests/run-smoke.mjs).
--
--   farm-catalogue digest: ${digest}
--   ${regrow.length} crops (${nRegrowFinite} finite perennials) · ${crops.length} crop plot-tiers · ${tiers.length} plot levels · ${perks.length} yield perks
--
-- Read by hr_farm_plant / hr_farm_harvest / hr_farm_water / hr_farm_upgrade_plot
-- (2026-08-22-server-farming-complete.sql). Numbers only; no client value
-- crosses. Idempotent: truncate+insert / update inside the migration
-- transaction. Apply BEFORE the RPC migration (which asserts every regrowing
-- crop carries a finite regrow_limit).
-- ════════════════════════════════════════════════════════════════════════

-- ── hr_crops.regrow_limit — the finite-perennial cap ─────────────────────
-- The column lives on the generated master catalogue (hr_crops); this ALTER
-- makes it exist on a database built by an older generator, and the UPDATE
-- fills the ONE farm-owned value from REGROW_LIMITS. 0 = non-regrow / legacy
-- infinite sentinel (unreachable on a regrowing crop — the assertion forbids it).
do $$
begin
  if to_regclass('public.hr_crops') is null then
    raise exception 'hr_crops absent — apply the master catalogue (gen-catalogues) first';
  end if;
end $$;
alter table public.hr_crops add column if not exists regrow_limit int not null default 0;

update public.hr_crops as k set regrow_limit = v.lim
  from (values
${regrowV}
  ) as v(crop_id, lim)
 where k.crop_id = v.crop_id and k.regrow_limit is distinct from v.lim;

-- ── the three farm-gate catalogues ───────────────────────────────────────
do $$
begin
  if to_regclass('public.hr_crop_plot_tier') is null then
    create table public.hr_crop_plot_tier (
      crop_id   text primary key,
      plot_tier int  not null check (plot_tier between 1 and ${MAX_PLOT_LEVEL})
    );
    alter table public.hr_crop_plot_tier enable row level security;
  end if;
  if to_regclass('public.hr_plot_tier') is null then
    create table public.hr_plot_tier (
      plot_level int primary key check (plot_level between 1 and ${MAX_PLOT_LEVEL}),
      deed_cost  int not null check (deed_cost >= 0)
    );
    alter table public.hr_plot_tier enable row level security;
  end if;
  if to_regclass('public.hr_farm_yield_perk') is null then
    create table public.hr_farm_yield_perk (
      perk_key   text primary key,
      farm_yield int  not null check (farm_yield >= 0)
    );
    alter table public.hr_farm_yield_perk enable row level security;
  end if;
end $$;

-- Read-only catalogues: readable by everyone signed in, written by NO client.
do $$
declare t text;
begin
  foreach t in array array['hr_crop_plot_tier','hr_plot_tier','hr_farm_yield_perk'] loop
    execute format('revoke all on public.%I from public, anon, authenticated, service_role', t);
    execute format('grant select on public.%I to anon, authenticated, service_role', t);
    execute format('drop policy if exists %I on public.%I', t || '_sel', t);
    execute format('create policy %I on public.%I for select using (true)', t || '_sel', t);
  end loop;
end $$;

truncate table public.hr_crop_plot_tier;
insert into public.hr_crop_plot_tier (crop_id, plot_tier) values
${cropsV};

truncate table public.hr_plot_tier;
insert into public.hr_plot_tier (plot_level, deed_cost) values
${tiersV};

truncate table public.hr_farm_yield_perk;
insert into public.hr_farm_yield_perk (perk_key, farm_yield) values
${perksV};

-- ── Self-verification ────────────────────────────────────────────────────
do $$
declare v_n int; v_bad int;
begin
  select count(*) into v_n from public.hr_crop_plot_tier;
  if v_n <> ${crops.length} then raise exception 'hr_crop_plot_tier has % rows, expected ${crops.length}', v_n; end if;
  select count(*) into v_n from public.hr_plot_tier;
  if v_n <> ${tiers.length} then raise exception 'hr_plot_tier has % rows, expected ${tiers.length}', v_n; end if;
  select count(*) into v_n from public.hr_farm_yield_perk;
  if v_n <> ${perks.length} then raise exception 'hr_farm_yield_perk has % rows, expected ${perks.length}', v_n; end if;

  -- Every regrowing crop MUST carry a finite (>0) regrow_limit (no infinite
  -- perennial — arming the harvest RPC otherwise reverts the b420/b428 ruling).
  select count(*) into v_bad from public.hr_crops where regrows and regrow_limit <= 0;
  if v_bad > 0 then raise exception '% regrowing crop(s) have no finite regrow_limit', v_bad; end if;

  -- Every gated crop must be a real hr_crops row (the plant RPC joins them).
  select count(*) into v_bad from public.hr_crop_plot_tier c
    where not exists (select 1 from public.hr_crops k where k.crop_id = c.crop_id);
  if v_bad > 0 then raise exception '% plot-tier crops are absent from hr_crops', v_bad; end if;

  -- Level 1 must be free; no client write policy may exist on a catalogue.
  if (select deed_cost from public.hr_plot_tier where plot_level = 1) <> 0 then
    raise exception 'plot level 1 must cost 0 deeds';
  end if;
  select count(*) into v_bad from pg_policies
    where schemaname = 'public'
      and tablename in ('hr_crop_plot_tier','hr_plot_tier','hr_farm_yield_perk')
      and cmd in ('INSERT','UPDATE','DELETE','ALL');
  if v_bad > 0 then raise exception '% write policies on the farm catalogues', v_bad; end if;
end $$;
`;
}

const wanted = render();
if (process.argv.includes('--check')) {
  const have = await readFile(OUT, 'utf8').catch(() => '');
  if (have.replace(/\r\n/g, '\n') !== wanted.replace(/\r\n/g, '\n')) {
    console.error('gen-farm-catalogues --check FAILED: '
      + '2026-08-22-farm-catalogues.generated.sql is stale. Run: node tools/gen-farm-catalogues.mjs');
    process.exit(1);
  }
  console.log('gen-farm-catalogues --check: catalogues match src/core/farm.js + gathering + perks + companions');
} else {
  await writeFile(OUT, wanted);
  console.log(`wrote ${OUT}`);
}

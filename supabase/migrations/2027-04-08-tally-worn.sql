-- ── THE RULE ────────────────────────────────────────────────────────────────
--   Her pick is the next Scarce armor piece of the task's ground in the hero's chosen weight and slot order that she has
--   not given this hero, SKIPPING a piece whose slot the hero already wears at that piece's gear tier or higher, of any
--   weight (the designer: "skips a slot the hero already wears at that tier or better and moves to the next slot in the
--   player's order"). Every piece given or worn: the task's materials in turn, as before. The gold is paid either way.
--   A piece only CARRIED still does not move her pick (2027-02-15-panel-truth.sql: her board's line is what she pays,
--   and a hunt's drops land in the bag, never on the hero), so nothing but the player's own equip changes the line.
--
-- ── THE CONTRACT ────────────────────────────────────────────────────────────
--   hr_tally_pick(p_user, p_slot, p_task) RESTATED WHOLE (§0 md5 pin: panel-truth's image), owner-only, the same
--   signature and answer shape ({pick: piece|material, item, qty} | null). Its two readers are unchanged and agree by
--   construction: hr_tally_view (her board's line) and hr_tally_claim (the payment, under the character lock, both
--   settle doors and the town visit). The tier of a worn item is hr_tally_tiers, GENERATED by tools/gen-tally-tasks.mjs
--   from src/data/items.js through gear-tiers.js's rule (gearTier: the item's material tier, a named piece with none at
--   its Level's rung) into 2027-04-08-tally-worn.generated.sql, whose self-check holds it to hr_item_slots both ways and
--   every piece's tier to it. No hand-typed tier and no client value: the server reads player_equipment.
--   No new client verb, no new error: a claim pays exactly what it paid before for a hero who wears none of her pieces.
--
-- ── CONCURRENCY + IDEMPOTENCY ───────────────────────────────────────────────
--   Unchanged. The pick is a STABLE read; hr_tally_claim calls it under the hero's character lock (hr_hunt_lock, also
--   held by hr_apply's equip), so an equip and a payment serialize and the payment reads the equipment it commits
--   against. The board reads without the lock: an equip between the board and the payment moves the line, and the
--   next board read shows it (the player's own act, not a drop). Replays: unchanged (instance CAS, intent keys, the
--   per-day UNIQUE, the given rows).
--
-- ── EXPLOIT SURFACE DELTA ───────────────────────────────────────────────────
--   No new mint. Still one piece or one materials stack per claim, at most paid_per_day (3) claims a hero a day, each
--   piece at most once per hero forever (hero_tally_given). New lever: by equipping or unequipping before a payment a
--   hero chooses between her next piece and her materials for that claim (the piece stays owed and comes later). The
--   claim's value is bounded by max(piece, materials) instead of their sequence; no extra claim, no extra piece, no
--   gold change. Nothing crosses to another player.
--
-- ── COST (100x players) ─────────────────────────────────────────────────────
--   One indexed NOT EXISTS per candidate piece (player_equipment PK + hr_tally_tiers PK), per board row (6) and per
--   done task paid (<= 3 a hero a day). hr_tally_tiers: 154 rows, ~6 KB, catalogue only. No new per-hero row.
--
-- ── REVERSIBILITY ───────────────────────────────────────────────────────────
--   Re-apply panel-truth's hr_tally_pick (2027-02-15-panel-truth.sql §1, its md5 is §0's pre-image). hr_tally_tiers
--   may stay (read by nothing else) or go with the next generated tally file.
--
-- ORDER: right after 2027-04-08-tally-worn.generated.sql (hr_tally_tiers; §0 refuses without it), after
--   2027-02-15-panel-truth.sql (the pinned pre-image). EDGE: none (src/data/tally-tasks.js and the generator are not in
--   the hr-accrue bundle; the engine never picks). CLIENT: the board's sentence about her pick rides the next release
--   AFTER this file (until then it reads as today's, which this file only makes truer for a hero in matching armor).

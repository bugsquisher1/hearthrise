-- ── §1 THE HELPERS ──────────────────────────────────────────────────────────
create or replace function public.hr_hunt_role_of(p_user uuid, p_slot integer)
returns text language sql stable set search_path = public, pg_catalog as $$
  -- TOWN-DEFAULTS (2027-01-25-town-defaults.sql): the role the worn set gives (the role key's first role, or the set's
  -- pick when the key allows it), on the hero's open hunt's set, else its current set: hr_hunt_settings_view's own rule.
  select case when a.options->>'role' = any (w.roles) then a.options->>'role' else w.roles[1] end
    from public.hr_hunt_weapon_roles w
    left join public.player_action_sets a
      on a.user_id = p_user and a.slot = p_slot
     and a.preset = coalesce((select h.preset::int from public.hunt_sessions h
                               where h.user_id = p_user and h.slot = p_slot and h.ended_at is null
                               order by h.entered_at desc limit 1), public.hr_hunt_active_set(p_user, p_slot))
   where w.weapon_type = public.hr_hunt_weapon_of(p_user, p_slot)
$$;

create or replace function public.hr_hunt_role_default(p_role text, p_party text[])
returns jsonb language sql stable set search_path = public, pg_catalog as $$
  -- TOWN-DEFAULTS (2027-01-25-town-defaults.sql): src/core/hunt/roles.js defaultSettings(role, party) as option keys,
  -- from its generated table: alone, with a Melee seat, or without one (the hero's own role always counted). The
  -- generator (tools/gen-catalogues.mjs) proves this rule against the engine for every party up to PARTY.maxSize + 1.
  with d as (select public.hr_hunt_role_defaults() as j),
       p as (select case when p_role = any (coalesce(p_party, '{}'::text[])) then array_remove(p_party, null)
                         else array_remove(coalesce(p_party, '{}'::text[]), null) || p_role end as roles)
  select d.j->p_role->(case when cardinality(p.roles) <= 1 then 'solo'
                            when exists (select 1 from unnest(p.roles) r where coalesce((d.j->r->>'melee')::boolean, false)) then 'party'
                            else 'party_nomelee' end)
    from d, p
$$;


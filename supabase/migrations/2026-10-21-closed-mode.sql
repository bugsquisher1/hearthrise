-- ── §8 L1: THE PRE-REQUEST HOOK ─────────────────────────────────────────────
do $mig$
declare v_cur text;
begin
  if not exists (select 1 from pg_roles where rolname = 'authenticator') then
    raise notice 'no authenticator role (not a Supabase database) — pre-request hook skipped';
    return;
  end if;
  select substr(c, length('pgrst.db_pre_request=') + 1) into v_cur
    from pg_db_role_setting s, unnest(s.setconfig) c
   where s.setrole = 'authenticator'::regrole and s.setdatabase = 0
     and c like 'pgrst.db_pre_request=%';
  if v_cur = 'public.hr_access_check' then
    raise notice 'pre-request hook already public.hr_access_check — skipped'; return;
  end if;
  if v_cur is not null and v_cur <> '' then
    raise exception 'authenticator already has pgrst.db_pre_request = % — refusing to replace another hook; '
                    'fold it into public.hr_access_check first', v_cur;
  end if;
  execute 'alter role authenticator set pgrst.db_pre_request = ''public.hr_access_check''';
end $mig$;
notify pgrst, 'reload config';


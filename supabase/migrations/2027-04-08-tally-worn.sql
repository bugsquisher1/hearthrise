-- ── §1 HER PICK SKIPS A SLOT THE HERO ALREADY WEARS AT THAT TIER OR BETTER ──
create or replace function public.hr_tally_pick(p_user uuid, p_slot integer, p_task text)
returns jsonb language plpgsql stable security definer set search_path = public, pg_catalog as $$
declare v_t public.hr_tally_tasks%rowtype; v_w text; v_order text[]; v_item text; v_n bigint; v_len bigint; v_m record;
begin
  -- TALLY (2026-12-23-tally-tasks.sql). PANEL-TRUTH (2027-02-15-panel-truth.sql): a piece the hero found does not move it.
  -- TALLY-WORN (2027-04-08-tally-worn.sql): a piece whose slot the hero wears at its tier or better, any weight, is skipped.
  select * into v_t from public.hr_tally_tasks where task_id = p_task;
  if not found then return null; end if;
  select h.weight, coalesce(nullif(h.slot_order, '{}'::text[]), c.slot_order) into v_w, v_order
    from public.hr_tally_config c left join public.hero_tally h on h.user_id = p_user and h.slot = p_slot
   where c.only_row;
  if v_w is not null then
    select p.item_id into v_item from public.hr_tally_pieces p
     where p.hunt_id = v_t.hunt_id and p.weight = v_w
       and not exists (select 1 from public.hero_tally_given g where g.user_id = p_user and g.slot = p_slot and g.item_id = p.item_id)
       and not exists (select 1 from public.player_equipment e
                         join public.hr_tally_tiers w on w.item_id = e.item_id and w.equip_slot = e.equip_slot
                        where e.user_id = p_user and e.slot = p_slot and e.equip_slot = p.equip_slot and w.tier >= p.tier)
     order by coalesce(array_position(v_order, p.equip_slot), 99), p.tier desc, p.item_id
     limit 1;
    if v_item is not null then return jsonb_build_object('pick', 'piece', 'item', v_item, 'qty', 1); end if;
  end if;
  select count(*) into v_len from public.hr_tally_materials m where m.task_id = p_task;
  if v_len = 0 then return null; end if;
  select count(*) into v_n from public.hero_tally_claims k
   where k.user_id = p_user and k.slot = p_slot and k.task_id = p_task and k.pick = 'material';
  select m.item_id, m.qty into v_m from public.hr_tally_materials m where m.task_id = p_task order by m.ord offset (v_n % v_len) limit 1;
  return jsonb_build_object('pick', 'material', 'item', v_m.item_id, 'qty', v_m.qty);
end $$;
revoke all on function public.hr_tally_pick(uuid, integer, text) from public, anon, authenticated, service_role;

-- ── §4 SELF-CHECK (CLAUDE.md §4), EXECUTED, every probe row rolled back ─────
-- Fails on the pre-image: (c) a hero wearing her first piece is paid that piece again; (e) a hero wearing every piece
-- is paid a piece, not the materials. The end-to-end paths (both settle doors, the town visit) are tests/tally-tasks.mjs
-- TT-6b on the replayed chain.
do $$
declare
  c_u    constant uuid := '000000d5-0000-4000-a000-00007a110408';
  v      jsonb;
  v_task text;
  v_w    text;
  v_gold bigint;
  v_p1   record;
  v_p2   text;
  v_low  text;
  v_side text;
  v_mat  text;
  v_purse bigint;
begin
  -- (a) THE SHAPE: no client reaches the pick or the tier book; the pick keeps its pinned search_path.
  if has_function_privilege('anon', 'public.hr_tally_pick(uuid,integer,text)', 'execute')
     or has_function_privilege('authenticated', 'public.hr_tally_pick(uuid,integer,text)', 'execute') then
    raise exception 'tally-worn §4(a): hr_tally_pick is reachable by a client'; end if;
  if has_table_privilege('anon', 'public.hr_tally_tiers', 'select') or has_table_privilege('authenticated', 'public.hr_tally_tiers', 'select') then
    raise exception 'tally-worn §4(a): a client reads hr_tally_tiers'; end if;
  if not exists (select 1 from pg_proc p where p.oid = 'public.hr_tally_pick(uuid,integer,text)'::regprocedure
                  and p.prosecdef and p.proconfig @> array['search_path=public, pg_catalog']) then
    raise exception 'tally-worn §4(a): hr_tally_pick lost security definer or its pinned search_path'; end if;

  -- THE FIXTURE: the first task (board order) and weight whose first piece has tier 2 or more, a second piece in another
  -- slot, and a lower-tier item and a same-tier item of another weight in the first piece's slot. Read from the
  -- catalogue, never named, so the check follows the data.
  select t.task_id, p.weight, t.gold into v_task, v_w, v_gold
    from public.hr_tally_tasks t join public.hr_tally_pieces p on p.hunt_id = t.hunt_id, public.hr_tally_config c
   where c.only_row and p.tier >= 2
     and exists (select 1 from public.hr_tally_pieces q where q.hunt_id = p.hunt_id and q.weight = p.weight and q.equip_slot <> p.equip_slot)
     and not exists (select 1 from public.hr_tally_pieces q where q.hunt_id = p.hunt_id and q.weight = p.weight
                      and (coalesce(array_position(c.slot_order, q.equip_slot), 99), -q.tier, q.item_id)
                        < (coalesce(array_position(c.slot_order, p.equip_slot), 99), -p.tier, p.item_id))
   order by t.ord, p.weight limit 1;
  if v_task is null then raise exception 'tally-worn §4-harness: no task leads with a piece of tier 2 or more beside a second slot'; end if;
  select p.item_id, p.equip_slot, p.tier into v_p1
    from public.hr_tally_pieces p join public.hr_tally_tasks t on t.hunt_id = p.hunt_id, public.hr_tally_config c
   where c.only_row and t.task_id = v_task and p.weight = v_w
   order by coalesce(array_position(c.slot_order, p.equip_slot), 99), p.tier desc, p.item_id limit 1;
  select p.item_id into v_p2
    from public.hr_tally_pieces p join public.hr_tally_tasks t on t.hunt_id = p.hunt_id, public.hr_tally_config c
   where c.only_row and t.task_id = v_task and p.weight = v_w and p.equip_slot <> v_p1.equip_slot
   order by coalesce(array_position(c.slot_order, p.equip_slot), 99), p.tier desc, p.item_id limit 1;
  select w.item_id into v_low from public.hr_tally_tiers w
   where w.equip_slot = v_p1.equip_slot and w.tier < v_p1.tier order by w.tier desc, w.item_id limit 1;
  select w.item_id into v_side from public.hr_tally_tiers w join public.hr_items i on i.item_id = w.item_id
   where w.equip_slot = v_p1.equip_slot and w.tier = v_p1.tier and i.armour_weight is distinct from v_w order by w.item_id limit 1;
  select m.item_id into v_mat from public.hr_tally_materials m where m.task_id = v_task order by m.ord limit 1;
  if v_p2 is null or v_low is null or v_side is null or v_mat is null then
    raise exception 'tally-worn §4-harness: % / % has no second piece (%), lower-tier item (%), other-weight item (%) or material (%)',
      v_task, v_w, v_p2, v_low, v_side, v_mat; end if;

  begin
    insert into auth.users (id) values (c_u) on conflict (id) do nothing;
    insert into public.profiles (id) values (c_u) on conflict do nothing;
    insert into public.hr_access_allowlist (user_id, note) values (c_u, 'tally-worn §4 probe') on conflict (user_id) do nothing;
    perform set_config('request.jwt.claim.sub', c_u::text, true);
    perform set_config('request.jwt.claims', jsonb_build_object('sub', c_u, 'role', 'authenticated')::text, true);
    v := public.hr_create_character(0);
    if coalesce(v->>'ok', '') <> 'true' then raise exception 'tally-worn §4-harness: hr_create_character refused: %', v; end if;
    delete from public.player_equipment e where e.user_id = c_u and e.slot = 0
       and e.equip_slot in (select s from public.hr_tally_config c, unnest(c.slot_order) s where c.only_row);
    insert into public.hero_tally (user_id, slot, weight) values (c_u, 0, v_w)
      on conflict (user_id, slot) do update set weight = excluded.weight, slot_order = '{}'::text[];

    -- (b) THE CONTROLS: bare, she picks her first piece; carried in the bag it still is (panel-truth); worn at a LOWER
    --     tier it still is (a better piece is an upgrade).
    if public.hr_tally_pick(c_u, 0, v_task)->>'item' is distinct from v_p1.item_id then
      raise exception 'tally-worn §4(b): bare, her first pick on % (%) is %, want %', v_task, v_w, public.hr_tally_pick(c_u, 0, v_task), v_p1.item_id; end if;
    insert into public.player_inventory as pi (user_id, slot, item_id, qty) values (c_u, 0, v_p1.item_id, 14)
      on conflict (user_id, slot, item_id) do update set qty = 14;
    if public.hr_tally_pick(c_u, 0, v_task)->>'item' is distinct from v_p1.item_id then
      raise exception 'tally-worn §4(b): 14 % in the bag moved her pick to %', v_p1.item_id, public.hr_tally_pick(c_u, 0, v_task); end if;
    insert into public.player_equipment (user_id, slot, equip_slot, item_id) values (c_u, 0, v_p1.equip_slot, v_low);
    if public.hr_tally_pick(c_u, 0, v_task)->>'item' is distinct from v_p1.item_id then
      raise exception 'tally-worn §4(b): wearing the lower-tier % skipped the tier-% %', v_low, v_p1.tier, v_p1.item_id; end if;

    -- (c) WEARING HER FIRST PIECE: the board says the second, and the payment IS the second (gold as the task's).
    update public.player_equipment set item_id = v_p1.item_id where user_id = c_u and slot = 0 and equip_slot = v_p1.equip_slot;
    if public.hr_tally_pick(c_u, 0, v_task)->>'item' is distinct from v_p2 then
      raise exception 'tally-worn §4(c): wearing % her board says %, want %', v_p1.item_id, public.hr_tally_pick(c_u, 0, v_task), v_p2; end if;
    insert into public.hero_tally_tasks (user_id, slot, place, task_id, kills, target, done_at)
      select c_u, 0, 1, t.task_id, t.target, t.target, now() from public.hr_tally_tasks t where t.task_id = v_task;
    v_purse := coalesce((select w.gold from public.account_wallet w where w.user_id = c_u), 0);
    v := public.hr_tally_claim(c_u, 0, null);
    if jsonb_array_length(coalesce(v->'paid', '[]'::jsonb)) <> 1 or v->'paid'->0->>'item' is distinct from v_p2
       or v->'paid'->0->>'pick' is distinct from 'piece' then
      raise exception 'tally-worn §4(c): wearing % she paid %, want the piece %', v_p1.item_id, v, v_p2; end if;
    if exists (select 1 from public.hero_tally_given g where g.user_id = c_u and g.item_id = v_p1.item_id)
       or not exists (select 1 from public.hero_tally_given g where g.user_id = c_u and g.item_id = v_p2)
       or (select w.gold from public.account_wallet w where w.user_id = c_u) is distinct from v_purse + v_gold then
      raise exception 'tally-worn §4(c): the given rows or the purse are wrong after paying % (purse % -> %, task gold %)',
        v_p2, v_purse, (select w.gold from public.account_wallet w where w.user_id = c_u), v_gold; end if;

    -- (d) ANY WEIGHT: the same tier in another weight skips her piece too ("at that tier or better", the slot's).
    update public.player_equipment set item_id = v_side where user_id = c_u and slot = 0 and equip_slot = v_p1.equip_slot;
    if public.hr_tally_pick(c_u, 0, v_task)->>'item' is not distinct from v_p1.item_id then
      raise exception 'tally-worn §4(d): wearing the tier-% % (another weight) she still picks %', v_p1.tier, v_side, v_p1.item_id; end if;

    -- (e) WEARING EVERY PIECE: her materials, in turn, and the gold; no piece is given.
    delete from public.player_equipment e where e.user_id = c_u and e.slot = 0
       and e.equip_slot in (select s from public.hr_tally_config c, unnest(c.slot_order) s where c.only_row);
    insert into public.player_equipment (user_id, slot, equip_slot, item_id)
      select distinct on (p.equip_slot) c_u, 0, p.equip_slot, p.item_id
        from public.hr_tally_pieces p join public.hr_tally_tasks t on t.hunt_id = p.hunt_id
       where t.task_id = v_task and p.weight = v_w
       order by p.equip_slot, p.tier desc, p.item_id;
    delete from public.hero_tally_given g where g.user_id = c_u;
    if public.hr_tally_pick(c_u, 0, v_task) is distinct from (select jsonb_build_object('pick', 'material', 'item', m.item_id, 'qty', m.qty)
                                                                   from public.hr_tally_materials m where m.task_id = v_task order by m.ord limit 1) then
      raise exception 'tally-worn §4(e): wearing every piece her board says %, want her first material %', public.hr_tally_pick(c_u, 0, v_task), v_mat; end if;
    insert into public.hero_tally_tasks (user_id, slot, place, task_id, kills, target, done_at)
      select c_u, 0, 1, t.task_id, t.target, t.target, now() from public.hr_tally_tasks t where t.task_id = v_task;
    v_purse := (select w.gold from public.account_wallet w where w.user_id = c_u);
    v := public.hr_tally_claim(c_u, 0, null);
    if jsonb_array_length(coalesce(v->'paid', '[]'::jsonb)) <> 1 or v->'paid'->0->>'pick' is distinct from 'material'
       or v->'paid'->0->>'item' is distinct from v_mat
       or exists (select 1 from public.hero_tally_given g where g.user_id = c_u)
       or (select w.gold from public.account_wallet w where w.user_id = c_u) is distinct from v_purse + v_gold then
      raise exception 'tally-worn §4(e): wearing every piece she paid % (want % and % g, no piece given)', v, v_mat, v_gold; end if;

    raise exception using errcode = 'HRW08', message = 'tally-worn §4 complete - rolling back';
  exception when sqlstate 'HRW08' then null;   -- every probe row is discarded with the subtransaction
  end;
  perform set_config('request.jwt.claim.sub', '', true);
  perform set_config('request.jwt.claims', '', true);
  if exists (select 1 from auth.users where id = c_u) or exists (select 1 from public.player_ledger where user_id = c_u) then
    raise exception 'tally-worn §4: LEAKED a probe row'; end if;
  raise notice 'tally-worn: % (%) pays % to a hero wearing %, her materials to a hero wearing every piece, the lower tier still pays; all green',
    v_task, v_w, v_p2, v_p1.item_id;
end $$;

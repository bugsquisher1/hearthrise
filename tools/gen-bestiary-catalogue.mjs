#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-bestiary-catalogue.mjs — THE SERVER CATALOGUE OF THE ACCOUNT
// BESTIARY (Tyler 2026-10-19).
//
// The data files are the only source of these rows; Postgres needs them to
// count, price and project the bestiary by itself (a client never names a
// threshold, a fee or a multiplier):
//   src/data/bestiary-stages.js  BESTIARY_STAGES  -> hr_bestiary_stages
//                                BESTIARY_FEE     -> hr_bestiary_fee
//   src/data/hunt-grounds.js + src/data/hunts.js + src/data/monsters.js
//                                the monsters a ground can spawn, its
//                                commonness there, whether it drops a relic
//                                                 -> hr_bestiary_monsters
//
//   Regenerate:  node tools/gen-bestiary-catalogue.mjs
//   Verify:      node tools/gen-bestiary-catalogue.mjs --check     (exit 1 on drift)
//   Selftest:    node tools/gen-bestiary-catalogue.mjs --selftest  (every refusal bites)
//
// REFUSES (throws, nothing written): a stage table its own validate() rejects;
// a ground monster missing from the roster; a hunt ground with no hunts.js row;
// a drop row whose `tier` is anything but 'relic'; a monster listed twice on one
// ground.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { BESTIARY_STAGES, BESTIARY_FEE, RELIC_TIER, hasRelic, validate } from '../src/data/bestiary-stages.js';
import { HUNT_GROUNDS } from '../src/data/hunt-grounds.js';
import { HUNT_INDEX } from '../src/data/hunts.js';
import { MONSTERS } from '../src/data/monsters.js';
import { isMain } from '../tests/_is-main.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'supabase', 'migrations', '2026-10-28-bestiary-catalogue.generated.sql');
export const COMMONNESS = Object.freeze(['common', 'uncommon', 'rare', 'boss']);

/**
 * The bestiary's roster: every monster a hunt ground can spawn (its pockets'
 * packs, the room holders included), in ground then pocket order, with its
 * commonness there (the hunts.js spawn rarity; a monster that holds a room and
 * is no weighted spawn is 'boss') and whether it drops a relic.
 */
export function bestiaryRoster({ grounds = HUNT_GROUNDS, hunts = HUNT_INDEX, monsters = MONSTERS } = {}) {
  const out = [];
  for (const g of Object.values(grounds)) {
    const hunt = hunts[g.hunt];
    if (!hunt) throw new Error(`ground ${g.id} names hunt ${g.hunt}, which hunts.js does not have`);
    const seen = new Set();
    for (const p of g.pockets) {
      for (const s of (p.pack || p.spawns)) {
        if (seen.has(s.monster)) continue;
        seen.add(s.monster);
        const row = monsters[s.monster];
        if (!row) throw new Error(`ground ${g.id} spawns ${s.monster}, which the roster does not have`);
        for (const d of row.drops || []) {
          if (d && d.tier !== undefined && d.tier !== RELIC_TIER) throw new Error(`${s.monster} drop ${d.id} has tier ${JSON.stringify(d.tier)}; the only drop tier is '${RELIC_TIER}'`);
        }
        const spawn = (hunt.spawns || []).find((x) => x.monster === s.monster);
        const rarity = spawn ? spawn.rarity : 'boss';
        if (!COMMONNESS.includes(rarity)) throw new Error(`${g.hunt} spawn ${s.monster} has rarity ${rarity}`);
        out.push({ monster: s.monster, hunt: g.hunt, rarity, ord: out.length + 1, relic: hasRelic(row) });
      }
    }
  }
  return out;
}

function stageRows() {
  const bad = validate();
  if (bad.length) throw new Error('src/data/bestiary-stages.js is invalid: ' + bad.join('; '));
  return { stages: BESTIARY_STAGES, fee: BESTIARY_FEE };
}

const sq = (s) => "'" + String(s).replace(/'/g, "''") + "'";

export function render(roster = bestiaryRoster(), r = stageRows()) {
  const digest = createHash('sha256').update(JSON.stringify({ roster, stages: r.stages, fee: r.fee })).digest('hex');
  return `-- ════════════════════════════════════════════════════════════════════════
-- Hearthrise — THE ACCOUNT BESTIARY CATALOGUE
-- (GENERATED by tools/gen-bestiary-catalogue.mjs — DO NOT EDIT BY HAND)
--
--   hr_bestiary_stages    src/data/bestiary-stages.js BESTIARY_STAGES
--   hr_bestiary_fee       src/data/bestiary-stages.js BESTIARY_FEE
--   hr_bestiary_monsters  src/data/hunt-grounds.js x hunts.js x monsters.js
--   digest ${digest}
--   ${r.stages.length} stages, ${roster.length} ground monsters
--
-- Server-only: RLS on, NO policy, no client grant (the client reads the
-- \`account_bestiary\` envelope section). Idempotent: delete + insert; nothing
-- references these rows by foreign key. Any hand edit FAILS
-- \`node tools/gen-bestiary-catalogue.mjs --check\`.
-- ORDER: after 2026-10-27-core-bodies.sql (needs hr_activities, hr_hunts).
-- No begin/commit (CLAUDE.md §2).
-- ════════════════════════════════════════════════════════════════════════

do $pre$
begin
  if to_regclass('public.hr_activities') is null or to_regclass('public.hr_hunts') is null then
    raise exception 'PRECONDITION: hr_activities / hr_hunts are absent (apply the core and hunt catalogues first)'; end if;
end $pre$;

create table if not exists public.hr_bestiary_stages (
  stage          smallint primary key check (stage between 1 and 9),
  kills          bigint not null check (kills > 0),
  relic_permille int not null check (relic_permille between 1001 and 2000),
  fee_mult       int not null check (fee_mult >= 1)
);
create table if not exists public.hr_bestiary_fee (
  id        boolean primary key default true check (id),
  base      int not null check (base > 0),
  per_level int not null check (per_level >= 0)
);
create table if not exists public.hr_bestiary_monsters (
  monster_id text not null check (monster_id ~ '^[a-z0-9_]{1,40}$'),
  hunt_id    text not null check (hunt_id ~ '^[a-z0-9_]{1,64}$'),
  rarity     text not null check (rarity in ('common', 'uncommon', 'rare', 'boss')),
  ord        int not null check (ord >= 1),
  has_relic  boolean not null,
  primary key (monster_id, hunt_id)
);
alter table public.hr_bestiary_stages enable row level security;
alter table public.hr_bestiary_fee enable row level security;
alter table public.hr_bestiary_monsters enable row level security;
revoke all on public.hr_bestiary_stages, public.hr_bestiary_fee, public.hr_bestiary_monsters
  from public, anon, authenticated, service_role;

delete from public.hr_bestiary_stages;
insert into public.hr_bestiary_stages (stage, kills, relic_permille, fee_mult) values
${r.stages.map((s) => `  (${s.stage}, ${s.kills}, ${s.relicPermille}, ${s.feeMult})`).join(',\n')};

delete from public.hr_bestiary_fee;
insert into public.hr_bestiary_fee (id, base, per_level) values (true, ${r.fee.base}, ${r.fee.perLevel});

delete from public.hr_bestiary_monsters;
insert into public.hr_bestiary_monsters (monster_id, hunt_id, rarity, ord, has_relic) values
${roster.map((m) => `  (${sq(m.monster)}, ${sq(m.hunt)}, ${sq(m.rarity)}, ${m.ord}, ${m.relic})`).join(',\n')};

-- §4 SELF-CHECK (CLAUDE.md §4): the rows are the data's, every monster and hunt
-- is in the server's own catalogues, the ladder rises, and no client role reaches a table.
do $chk$
declare v_role text;
begin
  if (select count(*) from public.hr_bestiary_stages) <> ${r.stages.length}
     or (select count(*) from public.hr_bestiary_fee) <> 1
     or (select count(*) from public.hr_bestiary_monsters) <> ${roster.length} then
    raise exception 'VERIFY: the bestiary catalogue row counts are not the data''s'; end if;
  if exists (select 1 from public.hr_bestiary_monsters m
              where not exists (select 1 from public.hr_activities a where a.kind = 'combat' and a.activity_id = m.monster_id)
                 or not exists (select 1 from public.hr_hunts h where h.hunt_id = m.hunt_id)) then
    raise exception 'VERIFY: a bestiary monster or hunt is not in the server''s combat / hunt catalogue'; end if;
  if exists (select 1 from public.hr_bestiary_stages a join public.hr_bestiary_stages b on b.stage = a.stage + 1
              where b.kills <= a.kills or b.relic_permille <= a.relic_permille or b.fee_mult < a.fee_mult)
     or (select min(stage) from public.hr_bestiary_stages) <> 1
     or (select max(stage) from public.hr_bestiary_stages) <> (select count(*) from public.hr_bestiary_stages) then
    raise exception 'VERIFY: the bestiary stages do not rise 1..n'; end if;
  foreach v_role in array array['anon', 'authenticated'] loop
    if has_table_privilege(v_role, 'public.hr_bestiary_stages', 'select,insert,update,delete')
       or has_table_privilege(v_role, 'public.hr_bestiary_fee', 'select,insert,update,delete')
       or has_table_privilege(v_role, 'public.hr_bestiary_monsters', 'select,insert,update,delete') then
      raise exception 'VERIFY: % reaches a bestiary catalogue table', v_role; end if;
  end loop;
  raise notice 'bestiary catalogue: % stages, % ground monsters; all green', ${r.stages.length}, ${roster.length};
end $chk$;
`;
}

function selftest() {
  const ground = (pockets, hunt = 'mill_cellar') => ({ g: { id: 'g', hunt, pockets } });
  const pk = (...ids) => [{ spawns: ids.map((monster) => ({ monster })) }];
  const cases = [
    ['a ground monster missing from the roster', { grounds: ground(pk('not_a_monster')) }],
    ['a ground whose hunt hunts.js does not have', { grounds: ground(pk('rat'), 'not_a_hunt') }],
    ['a drop row with an unknown tier', { grounds: ground(pk('rat')), monsters: { ...MONSTERS, rat: { ...MONSTERS.rat, drops: [{ id: 'bones', ch: 0.1, tier: 'legendary' }] } } }],
  ];
  let bad = 0;
  for (const [why, o] of cases) {
    try { bestiaryRoster(o); console.error(`  ✗ ${why}: NOT refused`); bad++; } catch { console.log(`  ✓ ${why}: refused`); }
  }
  /* A relic row is honoured; a monster on a ground's packs but no spawn is a 'boss'. */
  const relic = bestiaryRoster({ grounds: ground(pk('rat', 'slime')), monsters: { ...MONSTERS, rat: { ...MONSTERS.rat, drops: [{ id: 'bones', ch: 0.001, tier: 'relic' }] } },
    hunts: { mill_cellar: { spawns: [{ monster: 'slime', rarity: 'common' }] } } });
  if (relic[0].relic !== true || relic[0].rarity !== 'boss' || relic[1].relic !== false || relic[1].rarity !== 'common') {
    console.error('  ✗ the relic flag / room-holder commonness is not derived: ' + JSON.stringify(relic)); bad++;
  } else console.log('  ✓ a relic row and a room holder are derived');
  try { stageRows(); bestiaryRoster(); console.log('  ✓ the shipped rows pass'); } catch (e) { console.error('  ✗ the shipped rows are refused: ' + e.message); bad++; }
  if (bad) { console.error(`gen-bestiary-catalogue --selftest: ${bad} case(s) wrong`); process.exit(1); }
  console.log(`gen-bestiary-catalogue --selftest: all ${cases.length + 2} cases right`);
}

async function main() {
  if (process.argv.includes('--selftest')) return selftest();
  const wanted = render();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = (await readFile(OUT, 'utf8')).replace(/\r\n/g, '\n'); } catch { /* absent */ }
    if (have !== wanted) {
      console.error('gen-bestiary-catalogue --check FAILED: 2026-10-28-bestiary-catalogue.generated.sql is stale. Run: node tools/gen-bestiary-catalogue.mjs');
      process.exit(1);
    }
    console.log('gen-bestiary-catalogue --check: catalogue matches src/data');
    return;
  }
  await writeFile(OUT, wanted);
  console.log('wrote ' + OUT);
}

if (isMain(import.meta.url)) main().catch((e) => { console.error('gen-bestiary-catalogue: ' + e.message); process.exit(1); });

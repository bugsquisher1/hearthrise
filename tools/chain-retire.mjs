import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { isMain } from '../tests/_is-main.mjs';
import {
  ROOT, MIG_DIR, RETIRED_DIR, NOTES_DIR, CHAIN_FILE, loadApplyOrder, readSidecar, writeSidecar, noteFileOf, sidecarText,
} from './lib/apply-order.mjs';

const harness = (msg) => { const e = new Error(msg); e.harness = true; return e; };
const sqlCode = (s) => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/--[^\n]*/g, ' ');
/* a JS file's code without its comments: a generator's "CARRIED FROM <file>" header names history, it does not load it */
const jsCode = (s) => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1');

/** What one migration's text says about it. Pure. */
export function describe(sql) {
  const c = sqlCode(sql.replace(/\r\n/g, '\n'));
  /* TOP LEVEL only for a replace: a delete inside a do-block or a body may be conditional */
  const top = c.replace(/(\$[a-z_]*\$)[\s\S]*?\1/gi, ' ');
  const set = (text, re) => new Set([...text.matchAll(re)].map((m) => m[1].toLowerCase()));
  return {
    gen: (/Generated by (tools\/[\w./-]+\.mjs)/.exec(sql) || [])[1] || null,
    /* every write, bodies included (a conditional insert is still a write) */
    writes: set(c, /insert\s+into\s+(?:public\.)?([a-z0-9_]+)/gi),
    replaces: new Set([
      ...set(top, /(?<=(?:^|;)\s*)delete\s+from\s+(?:public\.)?([a-z0-9_]+)\s*;/gi),
      ...set(top, /(?<=(?:^|;)\s*)truncate\s+(?:table\s+)?(?:public\.)?([a-z0-9_]+)\s*(?:restrict\s*)?;/gi),
    ]),
    code: /create\s+(?:or\s+replace\s+)?function|pg_get_functiondef|drop\s+function|create\s+(?:or\s+replace\s+)?trigger|drop\s+trigger/i.test(c),
  };
}

/**
 * The candidates over one chain. Pure: the selftest plants chains.
 * @param {string[]} order the chain
 * @param {(f:string)=>string} read  a file's SQL
 * @param {(f:string)=>boolean} applied
 * @param {(f:string)=>boolean} named  does any guard, tool or src file name it in code (or a baseline track its bodies)?
 * @returns {{candidates:{file:string, supersededBy:string}[], kept:Map<string,string>}}
 */
export function candidatesOf(order, read, applied, named) {
  const info = new Map(order.map((f) => [f, describe(read(f))]));
  const candidates = [];
  const kept = new Map();
  order.forEach((f, i) => {
    const a = info.get(f);
    if (!a.gen) return;
    const keep = (why) => kept.set(f, why);
    if (!a.writes.size) return keep('writes no rows');
    if (a.code) return keep('touches a function or trigger');
    if (!applied(f)) return keep('not applied (the apply plan is not touched)');
    if (named(f)) return keep('named in code by a guard, tool or src file');
    /* the superseder is APPLIED too: a STAGED file may still be dropped before it ever runs */
    let s = -1;
    for (let j = i + 1; j < order.length; j++) {
      const b = info.get(order[j]);
      if (b.gen === a.gen && applied(order[j]) && [...a.writes].every((t) => b.replaces.has(t) && b.writes.has(t))) { s = j; break; }
    }
    if (s < 0) return keep('no later APPLIED file of its generator fully replaces every table it writes');
    const seen = order.slice(i + 1, s).filter(named);
    if (seen.length) return keep(`a guard or tool names ${seen[0]}${seen.length > 1 ? ` (+${seen.length - 1})` : ''}, between it and ${order[s]}`);
    candidates.push({ file: f, supersededBy: order[s] });
  });
  return { candidates, kept };
}

/** The repo's code that may name a migration: tests, tools, src (comments stripped), the CI workflow, live-hash's tracked files. */
function namedIndex(root) {
  const texts = [];
  const walk = (d) => {
    if (!existsSync(join(root, d))) return;
    for (const n of readdirSync(join(root, d))) {
      const p = `${d}/${n}`;
      const st = statSync(join(root, p));
      if (st.isDirectory()) { if (!['node_modules', '.pglite-cache', '.ci-local', 'fixtures-big'].includes(n)) walk(p); continue; }
      if (/\.(mjs|js)$/.test(n) && st.size < 4e6) texts.push(jsCode(readFileSync(join(root, p), 'utf8')));
      else if (/\.json$/.test(n) && !/\.baseline\.json$/.test(n) && st.size < 4e6) texts.push(readFileSync(join(root, p), 'utf8'));
    }
  };
  for (const d of ['tests', 'tools', 'src']) walk(d);
  for (const f of ['.github/workflows/smoke.yml', 'tests/live-hash-drift.baseline.json']) if (existsSync(join(root, f))) texts.push(readFileSync(join(root, f), 'utf8'));
  return (file) => texts.some((t) => t.includes(file));
}

export function listCandidates(root = ROOT) {
  const m = loadApplyOrder(root);
  const read = (f) => readFileSync(join(root, MIG_DIR, f), 'utf8');
  const applied = (f) => /^\s*APPLIED\b/.test(String(m._order_notes[f] || ''));
  return { m, ...candidatesOf(m.order, read, applied, namedIndex(root)) };
}

// ── the proof: the END STATE, measured ─────────────────────────────────────
async function endState() {
  const { bootReplay, inventory, closeReplays } = await import('../tests/schema-replay.mjs');
  const t0 = performance.now();
  const { db, applied } = await bootReplay({});
  const ms = performance.now() - t0;
  const inv = await inventory(db);
  const q = async (sql) => (await db.query(sql)).rows;
  const cols = (await q(`select table_name||'.'||column_name||' #'||ordinal_position||' '||data_type||' '||coalesce(column_default,'')||' '||is_nullable as c
    from information_schema.columns where table_schema = 'public' order by table_name, ordinal_position`)).map((r) => r.c);
  const seqs = (await q(`select sequencename||'='||coalesce(last_value::text,'null') as s from pg_sequences where schemaname = 'public' order by 1`)).map((r) => r.s);
  /* per table: every row (`all`), and every row without its clock / uuid / byte columns (`stable`), for the
     tables a replay fills from now() or gen_random_uuid() (meta rows, the wipe log, secrets) */
  const VOLATILE = new Set(['timestamp with time zone', 'timestamp without time zone', 'date', 'time without time zone', 'uuid', 'bytea']);
  const colTypes = await q(`select table_schema as s, table_name as t, column_name as c, data_type as d
    from information_schema.columns where table_schema in ('public','cron') order by table_schema, table_name, ordinal_position`);
  const data = {};
  for (const { s, t } of await q(`select n.nspname as s, c.relname as t from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where c.relkind in ('r','p') and n.nspname in ('public','cron') order by 1, 2`)) {
    const keep = colTypes.filter((x) => x.s === s && x.t === t && !VOLATILE.has(x.d)).map((x) => `x."${x.c}"`);
    const stable = keep.length ? `md5(coalesce(string_agg(row(${keep.join(', ')})::text, E'\\n' order by row(${keep.join(', ')})::text), ''))` : `''`;
    const r = (await q(`select count(*)::int as n, md5(coalesce(string_agg(x::text, E'\\n' order by x::text), '')) as h, ${stable} as st from "${s}"."${t}" x`))[0];
    data[`${s}.${t}`] = { n: r.n, all: r.h, stable: r.st };
  }
  await closeReplays();
  return { ms, files: applied.length, schema: createHash('sha256').update(JSON.stringify(inv)).digest('hex'), cols, seqs, data };
}

/**
 * Before vs after, judged against a CONTROL (the unchanged chain replayed twice): a table whose rows
 * differ between two identical replays is volatile (now(), random), and only its stable projection,
 * or (when even that moves) its row count, can be compared. Everything else must be byte-identical.
 * @returns {{diff:string[], volatile:string[]}}
 */
function stateDiff(a, b, control) {
  const out = [];
  const volatile = [];
  if (a.schema !== b.schema) out.push(`schema fingerprint ${a.schema.slice(0, 12)} -> ${b.schema.slice(0, 12)}`);
  const list = (name, x, y) => { const X = new Set(x); const Y = new Set(y); for (const v of x) if (!Y.has(v)) out.push(`${name} - ${v}`); for (const v of y) if (!X.has(v)) out.push(`${name} + ${v}`); };
  list('column', a.cols, b.cols);
  /* a sequence's position: compared where the control holds it still */
  const seqMap = (l) => new Map(l.map((v) => [v.slice(0, v.lastIndexOf('=')), v.slice(v.lastIndexOf('=') + 1)]));
  const [sa, sb, sc] = [seqMap(a.seqs), seqMap(b.seqs), seqMap(control.seqs)];
  for (const k of new Set([...sa.keys(), ...sb.keys()])) {
    if (!sa.has(k) || !sb.has(k)) out.push(`sequence ${k} ${sa.has(k) ? 'vanished' : 'appeared'}`);
    else if (sa.get(k) !== sb.get(k) && sc.get(k) === sa.get(k)) out.push(`sequence ${k}: ${sa.get(k)} -> ${sb.get(k)}`);
  }
  for (const k of new Set([...Object.keys(a.data), ...Object.keys(b.data)])) {
    const x = a.data[k]; const y = b.data[k]; const c = control.data[k];
    if (!x || !y) { out.push(`table ${k} ${x ? 'vanished' : 'appeared'}`); continue; }
    if (x.all === y.all) continue;
    if (c && c.all === x.all) { out.push(`rows of ${k}: ${x.n}:${x.all.slice(0, 8)} -> ${y.n}:${y.all.slice(0, 8)}`); continue; }
    if (c && c.stable === x.stable) {
      if (x.stable !== y.stable) out.push(`rows of ${k} (clock/uuid columns aside): ${x.n} -> ${y.n}`);
      else volatile.push(`${k} (rows equal but for clock/uuid columns)`);
      continue;
    }
    if (x.n !== y.n) out.push(`row count of volatile ${k}: ${x.n} -> ${y.n}`);
    else volatile.push(`${k} (random content; ${x.n} row(s) both sides)`);
  }
  return { diff: out, volatile };
}

async function retire(root, files) {
  const { m, candidates } = listCandidates(root);
  const by = new Map(candidates.map((c) => [c.file, c]));
  for (const f of files) if (!by.has(f)) throw harness(`${f} is not a candidate (node tools/chain-retire.mjs --list says why)`);
  if (!files.length) { console.log('chain-retire: nothing to retire'); return 0; }
  console.log(`chain-retire: replaying the chain as it stands (${m.order.length} files), twice (the second is the control)...`);
  const before = await endState();
  console.log(`  ${before.files} files in ${(before.ms / 1000).toFixed(1)} s; ${Object.keys(before.data).length} tables`);
  const control = await endState();
  console.log(`  control: ${control.files} files in ${(control.ms / 1000).toFixed(1)} s`);
  mkdirSync(join(root, RETIRED_DIR), { recursive: true });
  const moved = [];
  const undo = () => {
    for (const [f, sc] of moved.reverse()) { renameSync(join(root, RETIRED_DIR, f), join(root, MIG_DIR, f)); writeSidecar(root, f, sc); }
  };
  let after;
  try {
    for (const f of files) {
      const sc = readSidecar(root, f);
      renameSync(join(root, MIG_DIR, f), join(root, RETIRED_DIR, f));
      moved.push([f, sc]);
      /* the record, completed below once the proof holds */
      writeSidecar(root, f, { retired: { seq: sc.seq, superseded_by: by.get(f).supersededBy, proof: 'pending' }, note: sc.note });
    }
    console.log(`chain-retire: replaying without ${files.length} file(s)...`);
    after = await endState();
  } catch (e) { undo(); throw e; }
  const { diff, volatile } = stateDiff(before, after, control);
  /* a volatile table is compared by less than its rows, so no retired file may write it */
  const written = new Set(files.flatMap((f) => [...describe(readFileSync(join(root, RETIRED_DIR, f), 'utf8')).writes]));
  for (const v of volatile) { const t = v.split(' ')[0].replace(/^public\./, ''); if (written.has(t)) diff.push(`${v}: a retired file writes it`); }
  if (diff.length) {
    undo();
    console.error(`chain-retire: the END STATE MOVED (${diff.length} difference(s)); every file went back:\n  ${diff.slice(0, 40).join('\n  ')}`);
    return 1;
  }
  const exact = Object.keys(before.data).length - volatile.length;
  const day = new Date().toISOString().slice(0, 10);
  const proof = `${day}: tools/chain-retire.mjs replayed the chain with and without the ${files.length} file(s) retired together (plus a control replay); `
    + `the end state is identical: schema fingerprint ${before.schema.slice(0, 12)}, ${before.cols.length} columns with ordinals, every sequence the `
    + `control holds still, every row of ${exact} tables, and ${volatile.length} volatile tables (now()/random rows, written by no retired file) `
    + 'equal but for those columns or by count. No guard or tool names a file between it and its superseder.';
  if (volatile.length) console.log(`  volatile (compared without clock/uuid columns, or by count): ${volatile.join('; ')}`);
  for (const [f, sc] of moved) writeSidecar(root, f, { retired: { seq: sc.seq, superseded_by: by.get(f).supersededBy, proof }, note: sc.note });
  console.log(`chain-retire: retired ${files.length} file(s) to ${RETIRED_DIR}/; replay ${(before.ms / 1000).toFixed(1)} s -> ${(after.ms / 1000).toFixed(1)} s `
    + `(${before.files} -> ${after.files} files). End state identical.`);
  for (const f of files) console.log(`  ${f}  (superseded by ${by.get(f).supersededBy})`);
  return 0;
}

// ── --selftest ─────────────────────────────────────────────────────────────
function selftest() {
  let bad = 0;
  const ok = (c, m, x = '') => { console.log(`  ${c ? 'ok ' : 'x  '} ${m}${c ? '' : `\n     ${x}`}`); if (!c) bad += 1; };
  const G = (tag, tables, { replace = true, extra = '' } = {}) => `-- Generated by tools/gen-${tag}.mjs\n`
    + tables.map((t) => `${replace ? `delete from public.${t};\n` : ''}insert into public.${t} (k) values (1);\n`).join('') + extra;
  const files = {
    '01-a.sql': G('cat', ['t1', 't2']),
    '02-hand.sql': 'alter table public.t9 add column x int;\n',
    '03-a.sql': G('cat', ['t1', 't2']),
    '04-up.sql': G('up', ['u1'], { replace: false }),
    '05-up.sql': G('up', ['u1'], { replace: false }),
    '06-fn.sql': G('cat', ['t1', 't2'], { extra: 'create or replace function public.f() returns int language sql as $$ select 1 $$;\n' }),
    '07-a.sql': G('cat', ['t1', 't2']),
    '08-guarded.sql': 'select 1;\n',
    '09-a.sql': G('cat', ['t1', 't2']),
    '10-staged.sql': G('cat', ['t1', 't2']),
    '11-a.sql': G('cat', ['t1', 't2']),
    '12-named.sql': G('cat', ['t1', 't2']),
    '13-a.sql': G('cat', ['t1', 't2']),
    '14-dc.sql': G('dc', ['d1']),
    '15-dc.sql': '-- Generated by tools/gen-dc.mjs\ndo $$ begin if false then delete from public.d1; end if; end $$;\ninsert into public.d1 (k) values (2);\n',
    '17-cons.sql': '-- Generated by tools/gen-cons.mjs\ndelete from public.c1;\ndelete from public.c2;\ninsert into public.c1 (k) values (1);\ninsert into public.c2 (k) values (1);\n',
    '18-cons.sql': '-- Generated by tools/gen-cons.mjs\ndelete from public.c1;\ndelete from public.c2;\ninsert into public.c1 (k) values (2);\ninsert into public.c2 (k) values (2);\n',
  };
  const order = Object.keys(files);
  const named = (f) => f === '08-guarded.sql' || f === '12-named.sql';
  const applied = (f) => f !== '10-staged.sql';
  const { candidates, kept } = candidatesOf(order, (f) => files[f], applied, named);
  const c = new Map(candidates.map((x) => [x.file, x.supersededBy]));
  ok(c.get('01-a.sql') === '03-a.sql', 'a full-replace catalogue with a quiet gap is a candidate (a hand file in the gap is judged by the replay)', JSON.stringify([...c]));
  ok(!c.has('04-up.sql') && /fully replaces/.test(kept.get('04-up.sql') || ''), 'an UPSERT catalogue is kept: its rows outlive the next file', kept.get('04-up.sql'));
  ok(!c.has('06-fn.sql') && /function/.test(kept.get('06-fn.sql') || ''), 'a catalogue that touches a function is kept', kept.get('06-fn.sql'));
  ok(!c.has('07-a.sql') && /08-guarded/.test(kept.get('07-a.sql') || ''), 'a guard naming a file inside the gap keeps it (the guard could stop there)', kept.get('07-a.sql'));
  ok(!c.has('10-staged.sql') && /not applied/.test(kept.get('10-staged.sql') || ''), 'a STAGED catalogue is kept', kept.get('10-staged.sql'));
  ok(!c.has('12-named.sql') && /named/.test(kept.get('12-named.sql') || ''), 'a catalogue a guard names is kept', kept.get('12-named.sql'));
  ok(!c.has('13-a.sql'), 'the newest file of a generator is kept', JSON.stringify([...c]));
  ok(c.get('09-a.sql') === '11-a.sql', 'a STAGED full replace never supersedes (it may be dropped): the next APPLIED one does',
    JSON.stringify([...c]));
  ok(!c.has('14-dc.sql'), 'a delete inside a do-block (conditional) is not a full replace', JSON.stringify([...c]));
  ok(c.get('17-cons.sql') === '18-cons.sql', 'back-to-back top-level deletes each count as a replace', JSON.stringify([...c]));
  if (bad) { console.error(`\n${bad} case(s) failed.`); process.exit(1); }
  console.log('\nchain-retire --selftest: the candidate rules keep everything they must');
}

async function main(argv) {
  if (argv.includes('--selftest')) return selftest();
  if (argv.includes('--list')) {
    const { candidates, kept } = listCandidates(ROOT);
    console.log(`${candidates.length} candidate(s):`);
    for (const c of candidates) console.log(`  ${c.file.padEnd(70)} superseded by ${c.supersededBy}`);
    const tally = {};
    for (const why of kept.values()) { const k = why.replace(/ \S+\.sql.*$/, ' …'); tally[k] = (tally[k] || 0) + 1; }
    console.log(`\nkept (${kept.size}):`);
    for (const [k, n] of Object.entries(tally).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(4)}  ${k}`);
    return;
  }
  if (argv.includes('--retire')) {
    const files = argv.includes('--all') ? listCandidates(ROOT).candidates.map((c) => c.file) : argv.filter((a) => a.endsWith('.sql'));
    process.exitCode = await retire(ROOT, files);
    return;
  }
  throw harness('usage: node tools/chain-retire.mjs --list | --retire --all | --retire <file>... | --selftest');
}

if (isMain(import.meta.url)) {
  main(process.argv.slice(2)).catch((e) => { console.error(e.harness ? `chain-retire: ${e.message}` : e); process.exit(2); });
}

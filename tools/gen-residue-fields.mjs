#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-residue-fields.mjs — GENERATE THE SERVER'S RESIDUE ALLOWLIST.
//
// CLAUDE.md §6: "the residue is an ALLOWLIST". The client's half is
// src/session/residue.js RESIDUE_FIELDS (a field not named there is never read
// from an envelope and never sent). Until 2027-04-02 the server's half was a
// DENY list: hr_put_client_state stored any key it did not recognise as
// authority, up to 256 KiB a hero (architecture audit 2026-11-09 F4). The two
// halves are now ONE list: this generator writes the server's from the client's,
// so they cannot drift.
//   hr_residue_fields        one row a field: its name and the most bytes its JSON text may be
//                            (src/session/residue.js RESIDUE_BYTES)
//   hr_residue_total_bytes() the most bytes a hero's whole stored bag may be (RESIDUE_TOTAL_BYTES)
//
//   Regenerate:  node tools/gen-residue-fields.mjs
//   Verify:      node tools/gen-residue-fields.mjs --check     (exit 1 on drift: the twin guard)
//   Selftest:    node tools/gen-residue-fields.mjs --selftest  (every refusal bites)
//
// A NEW RESIDUE FIELD is a new dated file: add the field and its bound to
// residue.js, move OUT_FILE, regenerate, and apply it BEFORE the client that
// sends the field ships (CLAUDE.md §3.3 lane C): until then the server answers
// that field `unknown_field` and stores nothing of the put that carries it.
//
// REFUSES (throws, nothing written): a field with no bound or a bound with no
// field; a name the server would not key on; a bound that is not a whole number
// of bytes from 1 to the total; a total outside 1 KiB to 256 KiB; no field at all.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
/* The dated file this generator writes. A changed list or bound is a new dated file; an applied one stays as history. */
export const OUT_FILE = '2027-04-02-residue-fields.generated.sql';
const OUT = join(ROOT, 'supabase', 'migrations', OUT_FILE);
const FIELD = /^[A-Za-z][A-Za-z0-9]{0,31}$/;
export const TOTAL_MIN = 1024, TOTAL_MAX = 262144;
const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";

/** The catalogue rows for the client's residue module, validated. */
export function catalogue(R) {
  const fields = Array.isArray(R.RESIDUE_FIELDS) ? R.RESIDUE_FIELDS : [];
  const bytes = R.RESIDUE_BYTES && typeof R.RESIDUE_BYTES === 'object' ? R.RESIDUE_BYTES : {};
  const total = R.RESIDUE_TOTAL_BYTES;
  const problems = [];
  if (!fields.length) problems.push('RESIDUE_FIELDS names no field');
  if (!Number.isInteger(total) || total < TOTAL_MIN || total > TOTAL_MAX) problems.push('RESIDUE_TOTAL_BYTES ' + total + ' is not a whole number of bytes from ' + TOTAL_MIN + ' to ' + TOTAL_MAX);
  const seen = new Set();
  for (const f of fields) {
    if (typeof f !== 'string' || !FIELD.test(f)) { problems.push('field ' + JSON.stringify(f) + ' is not a name the server keys on (' + FIELD + ')'); continue; }
    if (seen.has(f)) problems.push('field ' + f + ' is listed twice');
    seen.add(f);
    const b = bytes[f];
    if (b === undefined) { problems.push('field ' + f + ' has no bound in RESIDUE_BYTES'); continue; }
    if (!Number.isInteger(b) || b < 1 || (Number.isInteger(total) && b > total)) problems.push('field ' + f + '\'s bound ' + b + ' is not a whole number of bytes from 1 to the total');
  }
  for (const f of Object.keys(bytes)) if (!seen.has(f)) problems.push('RESIDUE_BYTES bounds ' + f + ', which RESIDUE_FIELDS does not name');
  if (problems.length) throw new Error('gen-residue-fields: ' + problems.join('; '));
  return { rows: fields.map((f) => ({ field: f, bytes: bytes[f] })).sort((a, b) => (a.field < b.field ? -1 : 1)), total };
}

/** The generated SQL. */
export function buildSql(C) {
  const values = C.rows.map((r) => `  (${lit(r.field)}, ${r.bytes})`).join(',\n');
  const names = 'array[' + C.rows.map((r) => lit(r.field)).join(', ') + ']::text[]';
  return `-- ════════════════════════════════════════════════════════════════════════
-- Generated by tools/gen-residue-fields.mjs from src/session/residue.js
-- (RESIDUE_FIELDS, RESIDUE_BYTES, RESIDUE_TOTAL_BYTES).
-- Do not hand-edit: any hand edit FAILS \`node tools/gen-residue-fields.mjs --check\`.
-- THE SERVER'S RESIDUE ALLOWLIST (CLAUDE.md §6; architecture audit 2026-11-09 F4;
-- lane/c-server-debt, 2026-11-10): ${C.rows.length} fields, each with the most bytes its JSON
-- text may be, and ${C.total} bytes for a hero's whole stored bag. ROWS ONLY plus
-- the one total: hr_residue_fields is replaced whole; no player row, no value.
-- hr_put_client_state reads it from 2027-04-02-residue-allowlist.sql on.
-- No begin/commit.
-- ════════════════════════════════════════════════════════════════════════

create table if not exists public.hr_residue_fields (
  field     text    primary key check (field ~ '^[A-Za-z][A-Za-z0-9]{0,31}$'),
  max_bytes integer not null check (max_bytes between 1 and ${TOTAL_MAX})   -- of the field's JSON text
);
alter table public.hr_residue_fields enable row level security;
revoke all on public.hr_residue_fields from public, anon, authenticated, service_role;
comment on table public.hr_residue_fields is
  'GENERATED by tools/gen-residue-fields.mjs from src/session/residue.js: the client-only display fields a hero may keep (client_state) and each one''s bound. Read only by hr_put_client_state. No client grant, no policy.';

delete from public.hr_residue_fields where field <> all (${names});
insert into public.hr_residue_fields (field, max_bytes) values
${values}
  on conflict (field) do update set max_bytes = excluded.max_bytes;

-- The most bytes a hero's whole stored bag may be. One number, generated; owner-only.
create or replace function public.hr_residue_total_bytes()
returns integer language sql immutable set search_path = pg_catalog as $fn$ select ${C.total} $fn$;
revoke all on function public.hr_residue_total_bytes() from public, anon, authenticated, service_role;
comment on function public.hr_residue_total_bytes() is
  'tools/gen-residue-fields.mjs: the most bytes a hero''s stored client_state may be (src/session/residue.js RESIDUE_TOTAL_BYTES). Server-only.';

-- SELF-CHECK (CLAUDE.md §4), executed.
do $chk$
declare r text;
begin
  foreach r in array array['anon', 'authenticated', 'service_role'] loop
    if has_table_privilege(r, 'public.hr_residue_fields', 'select,insert,update,delete,truncate,references,trigger') then
      raise exception 'residue-fields: % holds a privilege on hr_residue_fields', r; end if;
    if has_function_privilege(r, 'public.hr_residue_total_bytes()', 'execute') then
      raise exception 'residue-fields: % can execute hr_residue_total_bytes', r; end if;
  end loop;
  if not (select c.relrowsecurity from pg_class c where c.oid = 'public.hr_residue_fields'::regclass) then
    raise exception 'residue-fields: row level security is off on hr_residue_fields'; end if;
  if exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'hr_residue_fields') then
    raise exception 'residue-fields: a policy stands on hr_residue_fields'; end if;
  -- the rows ARE the client's list: these names, these bounds, nothing else
  if (select jsonb_object_agg(f.field, f.max_bytes order by f.field) from public.hr_residue_fields f)
     is distinct from ${lit(JSON.stringify(Object.fromEntries(C.rows.map((r) => [r.field, r.bytes]))))}::jsonb then
    raise exception 'residue-fields: the rows are not the generated list: %', (select jsonb_object_agg(f.field, f.max_bytes order by f.field) from public.hr_residue_fields f); end if;
  if public.hr_residue_total_bytes() is distinct from ${C.total}
     or exists (select 1 from public.hr_residue_fields f where f.max_bytes > public.hr_residue_total_bytes()) then
    raise exception 'residue-fields: the total is not ${C.total}, or a field''s bound is over it'; end if;
  raise notice 'residue-fields: ${C.rows.length} fields, ${C.total} bytes a bag; all green';
end $chk$;
`;
}

async function inputs(root) {
  return import(pathToFileURL(join(root, 'src', 'session', 'residue.js')).href);
}

async function selftest() {
  const R = await inputs(ROOT);
  let bad = 0;
  const base = () => ({ RESIDUE_FIELDS: R.RESIDUE_FIELDS.slice(), RESIDUE_BYTES: Object.assign({}, R.RESIDUE_BYTES), RESIDUE_TOTAL_BYTES: R.RESIDUE_TOTAL_BYTES });
  const expectThrow = (name, edit, want) => {
    const D = base(); edit(D);
    try { catalogue(D); console.error('  MISSED  ' + name); bad++; }
    catch (e) { if (String(e.message).includes(want)) console.log('  caught  ' + name); else { console.error('  MISSED  ' + name + ' (threw: ' + e.message + ')'); bad++; } }
  };
  try { const C = catalogue(R); console.log('  ok      the real list generates: ' + C.rows.length + ' fields, ' + C.total + ' bytes a bag'); }
  catch (e) { console.error('  FAIL    the real list does not generate: ' + e.message); bad++; }
  expectThrow('a field with no bound', (D) => { D.RESIDUE_FIELDS.push('newField'); }, 'newField has no bound');
  expectThrow('a bound with no field', (D) => { D.RESIDUE_BYTES.ghost = 64; }, 'bounds ghost, which RESIDUE_FIELDS does not name');
  expectThrow('a field named like a column', (D) => { D.RESIDUE_FIELDS.push('gold_coins'); D.RESIDUE_BYTES.gold_coins = 64; }, 'is not a name the server keys on');
  expectThrow('a bound over the total', (D) => { D.RESIDUE_BYTES[D.RESIDUE_FIELDS[0]] = D.RESIDUE_TOTAL_BYTES + 1; }, 'is not a whole number of bytes from 1 to the total');
  expectThrow('a bound of zero', (D) => { D.RESIDUE_BYTES[D.RESIDUE_FIELDS[0]] = 0; }, 'is not a whole number of bytes from 1 to the total');
  expectThrow('a total back at a megabyte', (D) => { D.RESIDUE_TOTAL_BYTES = 1048576; }, 'RESIDUE_TOTAL_BYTES 1048576 is not');
  expectThrow('a field listed twice', (D) => { D.RESIDUE_FIELDS.push(D.RESIDUE_FIELDS[0]); }, 'is listed twice');
  expectThrow('no field at all', (D) => { D.RESIDUE_FIELDS = []; D.RESIDUE_BYTES = {}; }, 'names no field');
  console.log(bad ? 'gen-residue-fields --selftest: ' + bad + ' arm(s) failed' : 'gen-residue-fields --selftest: every refusal bites');
  return bad ? 1 : 0;
}

async function main() {
  if (process.argv.includes('--selftest')) process.exit(await selftest());
  const wanted = buildSql(catalogue(await inputs(ROOT)));
  if (process.argv.includes('--check')) {
    const have = await readFile(OUT, 'utf8').then((s) => s.replace(/\r\n/g, '\n'), () => null);
    if (have !== wanted) {
      console.error('gen-residue-fields: supabase/migrations/' + OUT_FILE + ' is not what src/session/residue.js generates.\n'
        + '  A changed field or bound needs a NEW dated file (move OUT_FILE, regenerate), applied before the client that sends it.');
      process.exit(1);
    }
    console.log('gen-residue-fields: ' + OUT_FILE + ' is in sync with src/session/residue.js');
    return;
  }
  await writeFile(OUT, wanted);
  console.log('gen-residue-fields: wrote supabase/migrations/' + OUT_FILE);
}

if (isMain(import.meta.url)) main().catch((e) => { console.error(String(e && e.message || e)); process.exit(1); });

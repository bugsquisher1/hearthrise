#!/usr/bin/env node
// tools/board-from-git.mjs — the priority board's STATUS section, generated from git and the
// repo's own records (CLAUDE.md §8, 2026-09-08). Hand-written narrative lives only below the
// marker; everything above it is rewritten by this tool. Sources: BUILD.cache + CHANGELOG head,
// origin/main vs local main, release/next branches, tests/schema-apply-order.json notes,
// the last five merges, and the live-hash/apply-order guards' verdicts.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const sh = (c) => { try { return execSync(c, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { return ''; } };
const build = (readFileSync('src/build-info.js', 'utf8').match(/cache:\s*(\d+)/) || [])[1];
const changelogHead = (readFileSync('CHANGELOG.md', 'utf8').match(/^## (v[^\n]+)/m) || [])[1] || '';
const head = sh('git log --oneline -1');
const originMain = sh('git rev-parse --short origin/main');
const localMain = sh('git rev-parse --short main');
const ahead = sh('git rev-list --count origin/main..main');
const branches = sh("git for-each-ref --format='%(refname:short) %(objectname:short) %(committerdate:short)' refs/heads/next refs/heads/release/* refs/remotes/origin/release/*").split('\n').filter(Boolean);
const merges = sh('git log --merges --oneline -5').split('\n').filter(Boolean);
let staged = [];
try { const j = JSON.parse(readFileSync('tests/schema-apply-order.json', 'utf8')); for (const [f, n] of Object.entries(j._order_notes || {})) if (/^STAGED/i.test(n)) staged.push(f); } catch {}
const guard = (c) => { try { execSync(c, { stdio: 'ignore' }); return 'green'; } catch { return 'RED'; } };

// The board is edited on Windows as often as Linux, so it can carry CRLF line
// endings (mixed with LF, since editors rarely normalize a whole file on one
// touch). Detect the file's own EOL and emit the block in that style — a
// hardcoded '\n' regex/join silently fails to match a CRLF marker and the
// board is regenerated as a same-content no-op printed as success.
function detectEol(text) { return text.includes('\r\n') ? '\r\n' : '\n'; }

function buildLines(eolTimestamp) {
  return [
    `<!-- GENERATED by tools/board-from-git.mjs at ${eolTimestamp}Z — do not edit above the marker -->`,
    `| Fact | Value |`, `|---|---|`,
    `| Local BUILD.cache (live = last pushed main) | ${build} — ${changelogHead} |`,
    `| Local main | ${head} |`,
    `| origin/main | ${originMain} (${ahead} local commit(s) not pushed) |`,
    `| Release / staging branches | ${branches.join('<br>') || 'none'} |`,
    `| Staged migrations (not applied) | ${staged.join('<br>') || 'none'} |`,
    `| apply-order-honesty | ${guard('node tests/apply-order-honesty.mjs')} |`,
    `| live-hash-drift (offline record) | ${guard('node tests/live-hash-drift.mjs')} |`,
    `| Last five merges | ${merges.join('<br>')} |`,
    `<!-- END GENERATED -->`,
  ];
}

// Replaces an existing GENERATED...END GENERATED block, or inserts one above
// the `_Last updated:` anchor, in `text`, whatever its own EOL style is.
// Returns { next, matched } — matched is false when neither the marker nor
// the anchor was found, so the caller never mistakes "nothing to do" for
// "wrote the update".
function applyBoardBlock(text) {
  const eol = detectEol(text);
  const block = buildLines(new Date().toISOString().slice(0, 16)).join(eol) + eol + eol;
  const genRe = /<!-- GENERATED by tools\/board-from-git\.mjs[\s\S]*?<!-- END GENERATED -->\r?\n(?:\r?\n)?/;
  const anchorRe = /^(_Last updated:[^\r\n]*\r?\n)/m;
  if (genRe.test(text)) return { next: text.replace(genRe, block), matched: true };
  if (anchorRe.test(text)) return { next: text.replace(anchorRe, block + '$1'), matched: true };
  return { next: text, matched: false };
}

if (process.argv.includes('--selftest')) {
  runSelftest();
} else {
  const P = 'docs/planning/PRIORITY_BOARD.md';
  const s = readFileSync(P, 'utf8');
  const { next, matched } = applyBoardBlock(s);
  if (process.argv.includes('--write')) {
    if (!matched) {
      console.error('board-from-git --write: FAILED — neither the GENERATED marker nor the '
        + '_Last updated: anchor matched docs/planning/PRIORITY_BOARD.md. Refusing a silent no-op.');
      process.exit(1);
    }
    writeFileSync(P, next);
    console.log('board status section written');
  } else {
    process.stdout.write(buildLines(new Date().toISOString().slice(0, 16)).join(detectEol(s)) + detectEol(s) + detectEol(s));
  }
}

function runSelftest() {
  const dir = mkdtempSync(join(tmpdir(), 'board-selftest-'));
  const OLD_STAMP = '2026-09-08T17:24Z';
  const minimal = (eol) => [
    '# Board',
    '',
    `<!-- GENERATED by tools/board-from-git.mjs at ${OLD_STAMP} — do not edit above the marker -->`,
    '| Fact | Value |',
    '|---|---|',
    '| x | y |',
    '<!-- END GENERATED -->',
    '',
    '_Last updated: nobody yet_',
    '',
  ].join(eol);

  let failures = [];
  const check = (label, cond) => { if (!cond) failures.push(label); };

  // Positive arm: the FIXED replace logic must update both a CRLF and an LF plant.
  for (const [label, eol] of [['CRLF', '\r\n'], ['LF', '\n']]) {
    const text = minimal(eol);
    const path = join(dir, `board-${label}.md`);
    writeFileSync(path, text);
    const { next, matched } = applyBoardBlock(text);
    check(`${label} plant: marker matched`, matched === true);
    check(`${label} plant: stamp changed`, !next.includes(OLD_STAMP));
    check(`${label} plant: no mixed EOL introduced`,
      eol === '\r\n' ? !/(?<!\r)\n/.test(next) : !next.includes('\r\n'));
    check(`${label} plant: EOL style preserved`, next.includes(eol));
    rmSync(path);
  }

  // Mutation arm: the OLD hardcoded '\n\n'-only regex must MISS the CRLF plant
  // (proves this selftest actually exercises the bug the fix closes).
  {
    const text = minimal('\r\n');
    const oldGenRe = /<!-- GENERATED by tools\/board-from-git\.mjs[\s\S]*?<!-- END GENERATED -->\n\n/;
    const oldMatched = oldGenRe.test(text);
    check('mutation arm: old regex MISSES the CRLF plant (bites)', oldMatched === false);
  }

  rmSync(dir, { recursive: true, force: true });

  if (failures.length) {
    console.error('board-from-git --selftest: FAILED\n  - ' + failures.join('\n  - '));
    process.exit(1);
  }
  console.log(`board-from-git --selftest: green (${2 * 4 + 1} assertions)`);
}

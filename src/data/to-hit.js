//   chance(attack, defense) = attack >= defense ?  1 - defense / (2 x attack)  :  attack / (2 x defense)
//
//   a hero's blow      attack = TO_HIT.base + its weapon skill + worn accuracy     defense = the monster's `evasion`
//   a monster's blow   attack = the monster's `aim`                               defense = TO_HIT.base + Defense + guard

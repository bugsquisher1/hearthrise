grant execute on function public.hr_companion_grant(int, text, text, uuid) to authenticated;

-- ── 3. STRUCTURAL ASSERTIONS ─────────────────────────────────────────────
do $$
declare
  v_p     oid;
  v_n     int;
  v_r     text;
  v_before text;
  v_owner  text;
  v_src   text;
begin
  v_p := to_regprocedure('public.hr_companion_grant(int,text,text,uuid)');
  if v_p is null then raise exception '§3: hr_companion_grant did not install'; end if;

  -- (a) EXACTLY ONE definition — a replace, never a new overload. An overload
  --     would leave the OLD body reachable under a different argument list.

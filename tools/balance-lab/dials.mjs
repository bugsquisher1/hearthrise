// tools/balance-lab/dials.mjs — THE LAB'S DIALS, applied to the ENGINE'S OWN DATA ROWS for one run and put back after.
//
// Nothing here forks a formula: a dial moves a data row the engine already reads (src/data/monsters.js MONSTERS,
// src/data/hunt-tiers.js through tierRowOf), the same road tools/balance-sim/worker.mjs's what-ifs take, and the run
// reads it through the engine's own code (atTier, payKill). applyDials answers the undo; the worker calls it
// before a run and the undo after, so a baseline played next reads today's data digit for digit.
//
// A SCALED HUNT is the game's own module (src/data/scaled-hunts.js): its scaledMonsters rows replace the ground's roster
// rows and its scaledTierRow is the tier the run plays. The lab computes no ratio of its own; when the module says a
// ground can't be scaled for that leader, or doesn't offer that tier scaled, the run stops and says so.
//
// ── THE DIALS JSON ("Copy dials as JSON"; schema hearthrise.balance-dials/1) ───────────────────────────────────────
//   {
//     "schema":  "hearthrise.balance-dials/1",
//     "engine":  "0.2.106",                     the game version the lab bundled (src/build-info.js)
//     "ground":  "mosslight_glade",             the ground whose rows the tier dials were read from
//     "monsters": { "dmgPm": 1000, "hpPm": 1000, "xpPm": 1000, "goldPm": 1000 },
//                every monster's atk (its to-hit and its blow, as a tier's power), HP, Level XP a kill and coin a kill,
//                permille of its row; 1000 = the row as written. Applied on top of a scaled hunt's rows too.
//     "tiers": { "normal":    { "pull": [0,0,0,0], "dmgPm": 1000, "hpPm": 1000, "xpPm": 1000 },
//                "dangerous": { "pull": [3,5,5,6], "dmgPm": 1170, "hpPm": 1000, "xpPm": 1100 },
//                "deadly":    { "pull": [8,8,8,8], "dmgPm": 1330, "hpPm": 1000, "xpPm": 1200 } },
//                one row per tier in hunt-tiers.js's shape (balance-sheet.js TIER_DIALS): pull = monsters a pull for
//                1..4 heroes (0 = the ground as it stands), then whole permilles. Coin never moves with a tier (Tyler
//                2026-11-07). Not read while scaled: the scaled tier row is the game's (scaledTierRow).
//     "scale":   { "leaderLevel": null | N }   a SCALED HUNT for a party led by a hero of Level N (src/data/scaled-hunts.js:
//                only past the band's top, capped at its topLevel, Normal and Dangerous only)
//     "run":     { "ground", "tier", "party": [{ "style", "level", "gear" }], "hours", "seeds" }   what was played
//   }
// The formula generator (tools/gen-ground-stats.mjs) and the tier table read `tiers` as written; `monsters` is a global
// multiplier on top of the rows they write.
import { MONSTERS } from '../../src/data/monsters.js';
import * as TIERS from '../../src/data/hunt-tiers.js';
/* GENERATED by build.mjs: `export * from src/data/balance-sheet.js` when that file exists, else nothing (the lab then
   grades on Tyler's 10-25 targets) */
import * as SHEET from './virtual/sheet.mjs';
/* GENERATED by build.mjs: `export * from src/data/scaled-hunts.js` when that file exists, else nothing (no scaled hunt) */
import * as SCALED from './virtual/scaled.mjs';

export const DIALS_SCHEMA = 'hearthrise.balance-dials/1';
export const TIER_KEYS = Object.freeze(['normal', 'dangerous', 'deadly']);
const PM = 1000;

/** Does this bundle hold the stat formula and the target sheet (src/data/balance-sheet.js)? */
export const hasSheet = () => typeof SHEET.formulaStats === 'function' && !!SHEET.BALANCE_SHEET;
/** Does this bundle hold the game's scaled hunts (src/data/scaled-hunts.js)? */
export const hasScaled = () => typeof SCALED.scaledMonsters === 'function' && typeof SCALED.scaledTierRow === 'function';

/** A tier row as the dials read it, from whatever shape hunt-tiers.js holds: { pull[4], dmgPm, hpPm, xpPm }. */
export function tierDialOf(row) {
  const r = row || {};
  /* the sheet's TIER_DIALS hold ONE pull for every group (2026-11-08); an engine row, one per party size */
  return { pull: Array.isArray(r.pull) ? r.pull.slice(0, 4).concat([0, 0, 0, 0]).slice(0, 4) : Number.isInteger(r.pull) ? [r.pull, r.pull, r.pull, r.pull] : [0, 0, 0, 0],
    dmgPm: Number.isFinite(r.dmgPm) ? r.dmgPm : Number.isFinite(r.powerPm) ? r.powerPm : PM,
    hpPm: Number.isFinite(r.hpPm) ? r.hpPm : PM, xpPm: Number.isFinite(r.xpPm) ? r.xpPm : PM };
}

/** Today's data for a ground: the tier rows the engine plays, and which tiers the ground offers. */
export function tierDefaults(groundId) {
  const offered = typeof TIERS.tiersOf === 'function' ? TIERS.tiersOf(groundId) : ['normal'];
  return { offered, tiers: Object.fromEntries(TIER_KEYS.map((t) => [t, tierDialOf(TIERS.tierRowOf(groundId, t))])) };
}

/** The dials that change nothing: today's rows for `groundId`. */
export function defaultDials(groundId) {
  return { schema: DIALS_SCHEMA, ground: groundId, monsters: { dmgPm: PM, hpPm: PM, xpPm: PM, goldPm: PM }, tiers: tierDefaults(groundId).tiers, scale: { leaderLevel: null } };
}

/** The sheet's own tier rows for a ground whose band starts at `floor` (balance-sheet.js tierRowFor, else its TIER_DIALS whole): the designer's proposal, or null. */
export function sheetTierDials(floor) {
  if (!hasSheet()) return null;
  try {
    if (typeof SHEET.tierRowFor === 'function') return Object.fromEntries(TIER_KEYS.map((t) => [t, tierDialOf(SHEET.tierRowFor(floor, t))]));
    if (SHEET.TIER_DIALS) return Object.fromEntries(TIER_KEYS.map((t) => [t, tierDialOf(SHEET.TIER_DIALS[t])]));
  } catch (e) { /* a sheet mid-change: no proposal rather than a wrong one */ }
  return null;
}

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const scaledLeader = (d) => (d && d.scale && Number.isInteger(d.scale.leaderLevel) ? d.scale.leaderLevel : null);

/**
 * THE SCALED HUNT AS THE GAME DEFINES IT, for the page's words and fee: the Level the ground is fought at (null when the module
 * refuses it, with why), its slider line (scaleFor), the price of a banked hour (pricePerHour) and the tier rows it plays.
 */
export function scaleInfo(groundId, leaderLevel) {
  if (!hasScaled()) return { ok: false, why: 'this bundle has no src/data/scaled-hunts.js' };
  const g = SCALED.SCALABLE_GROUNDS && SCALED.SCALABLE_GROUNDS[groundId];
  if (!g) return { ok: false, why: 'this ground is not scalable (the top ground has nothing above it to stay under)' };
  const level = SCALED.scaleLevelFor(groundId, leaderLevel);
  if (level === null) return { ok: false, why: 'the leader (Level ' + leaderLevel + ') has not outgrown this ground: it scales only past its band\'s top, ' + g.top };
  const tiers = Object.fromEntries(TIER_KEYS.map((t) => { const r = SCALED.scaledTierRow(groundId, t, leaderLevel); return [t, r ? tierDialOf(r) : null]; }));
  return { ok: true, level, cap: SCALED.SCALED_HUNTS.topLevel, line: SCALED.scaleFor(groundId, leaderLevel), pricePerHour: SCALED.pricePerHour(groundId, leaderLevel),
    tiers, offered: TIER_KEYS.filter((t) => tiers[t]), xpPm: SCALED.SCALED_HUNTS.xpPm, coinPm: SCALED.SCALED_HUNTS.coinPm[g.fit], fit: g.fit, danger: g.danger || 1 };
}

/** The tier row a run plays under these dials: the scaled hunt's own when scaled (null = not offered scaled), else the dial's. */
export function runTierRow(dials, groundId, tier) {
  const leader = scaledLeader(dials);
  if (leader !== null) {
    if (!hasScaled()) throw new Error('balance-lab dials: a scaled hunt needs src/data/scaled-hunts.js in the bundle');
    const r = SCALED.scaledTierRow(groundId, tier, leader);
    return r ? tierDialOf(r) : null;
  }
  const today = tierDialOf(TIERS.tierRowOf(groundId, tier));
  return dials && dials.tiers && dials.tiers[tier] ? { ...today, ...dials.tiers[tier] } : today;
}

/**
 * Move the engine's rows for one run of `tier` on `groundId`. `dials` as defaultDials answers (any field may be
 * missing = unchanged). Answers undo(). A scaled hunt (dials.scale.leaderLevel) first puts the game's scaledMonsters rows
 * in place of the roster's and plays its scaledTierRow; the monster dials then multiply on top.
 */
export function applyDials(dials, { groundId, tier }) {
  const undo = [];
  const set = (obj, k, v) => { undo.push([obj, k, Object.prototype.hasOwnProperty.call(obj, k), obj[k]]); obj[k] = v; };
  const rollback = () => { for (let i = undo.length - 1; i >= 0; i--) { const [o, k, had, v] = undo[i]; if (had) o[k] = v; else delete o[k]; } undo.length = 0; };
  const d = dials || {};
  const mon = { dmgPm: PM, hpPm: PM, xpPm: PM, goldPm: PM, ...(d.monsters || {}) };
  const leader = scaledLeader(d);
  /* THE SCALED ROWS, read from today's rows before anything moves */
  let scaled = null;
  if (leader !== null) {
    const info = scaleInfo(groundId, leader);
    if (!info.ok) throw new Error('No scaled hunt: ' + info.why + '.');
    if (!info.tiers[tier]) throw new Error('No scaled hunt on ' + tier + ': a scaled ground offers ' + info.offered.join(' and ') + ' only.');
    scaled = SCALED.scaledMonsters(MONSTERS, groundId, leader);
  }
  /* THE TIER ROW: written only where it differs from today's row, in whole permilles (the engine reads integers only) */
  const today = TIERS.tierRowOf(groundId, tier);
  const raw = runTierRow(d, groundId, tier);
  const want = { pull: raw.pull.map((n) => Math.max(0, Math.round(n))), dmgPm: Math.round(raw.dmgPm), hpPm: Math.round(raw.hpPm), xpPm: Math.round(raw.xpPm) };
  let hpOnRows = PM;
  if (!same(want, tierDialOf(today))) {
    const next = { ...today, id: tier, pull: want.pull.slice() };
    if ('powerPm' in today || !('dmgPm' in today)) next.powerPm = want.dmgPm; else next.dmgPm = want.dmgPm;
    if ('hpPm' in today) next.hpPm = want.hpPm; else hpOnRows = want.hpPm;
    next.xpPm = want.xpPm;
    /* an unfrozen row is the one the engine reads (a ground's own row): move it in place. A frozen one (the shared Normal)
       gets a ground's own row beside it, as balance-sim's what-ifs do. */
    if (!Object.isFrozen(today)) {
      for (const [k, v] of Object.entries(next)) set(today, k, v);
    } else if (TIERS.GROUND_TIERS && typeof TIERS.GROUND_TIERS === 'object' && !Object.isFrozen(TIERS.GROUND_TIERS)) {
      if (!TIERS.GROUND_TIERS[groundId]) set(TIERS.GROUND_TIERS, groundId, {});
      set(TIERS.GROUND_TIERS[groundId], tier, next);
    } else {
      throw new Error('balance-lab dials: hunt-tiers.js holds a shape the lab cannot write (a frozen row and no per-ground table); update tools/balance-lab/dials.mjs');
    }
    const read = tierDialOf(TIERS.tierRowOf(groundId, tier));
    if (read.xpPm !== want.xpPm || read.dmgPm !== want.dmgPm || ('hpPm' in today && read.hpPm !== want.hpPm)) {
      rollback();
      throw new Error('balance-lab dials: wrote the ' + tier + ' row on ' + groundId + ' but the engine reads another (hunt-tiers.js changed shape); update tools/balance-lab/dials.mjs');
    }
  }
  /* A SCALED HUNT'S ROWS: every field the game's scaledMonsters moved, as it wrote them */
  if (scaled) for (const [id, row] of Object.entries(scaled)) {
    const live = MONSTERS[id];
    for (const [k, v] of Object.entries(row)) if (!same(live[k], v)) set(live, k, Array.isArray(v) ? v.slice() : v);
  }
  /* THE MONSTER DIALS on top: atk and Level XP stay fractional (atTier already makes them so on a harder tier; the engine
     floors a blow and rounds a kill's XP), HP and coin stay whole (a unit's HP, the coin roll's integer range) */
  const hpPm = (mon.hpPm * hpOnRows) / PM;
  if (mon.dmgPm !== PM || hpPm !== PM || mon.xpPm !== PM || mon.goldPm !== PM) {
    for (const row of Object.values(MONSTERS)) {
      if (mon.dmgPm !== PM && Number.isFinite(row.atk)) set(row, 'atk', (row.atk * mon.dmgPm) / PM);
      if (hpPm !== PM && Number.isFinite(row.hp)) set(row, 'hp', Math.max(1, Math.round((row.hp * hpPm) / PM)));
      if (mon.xpPm !== PM && Number.isFinite(row.xp)) set(row, 'xp', (row.xp * mon.xpPm) / PM);
      if (mon.goldPm !== PM && Array.isArray(row.gp)) {
        const lo = Math.max(0, Math.round((row.gp[0] * mon.goldPm) / PM));
        set(row, 'gp', [lo, Math.max(lo, Math.round((row.gp[1] * mon.goldPm) / PM))]);
      }
    }
  }
  return rollback;
}

/** What the monster dials actually move on these monsters (coin and HP round to whole numbers): mean % per field. */
export function effectiveMonsterChange(dials, monsterIds) {
  const m = { dmgPm: PM, hpPm: PM, xpPm: PM, goldPm: PM, ...((dials && dials.monsters) || {}) };
  const acc = { hp: [0, 0], gold: [0, 0] };
  for (const id of monsterIds) {
    const r = MONSTERS[id];
    if (!r) continue;
    if (Number.isFinite(r.hp)) { acc.hp[0] += r.hp; acc.hp[1] += Math.max(1, Math.round((r.hp * m.hpPm) / PM)); }
    if (Array.isArray(r.gp)) {
      const lo = Math.max(0, Math.round((r.gp[0] * m.goldPm) / PM));
      acc.gold[0] += r.gp[0] + r.gp[1]; acc.gold[1] += lo + Math.max(lo, Math.round((r.gp[1] * m.goldPm) / PM));
    }
  }
  const pct = (a) => (a[0] ? Math.round((1000 * a[1]) / a[0]) / 10 : 100);
  return { dmgPct: m.dmgPm / 10, hpPct: pct(acc.hp), xpPct: m.xpPm / 10, goldPct: pct(acc.gold) };
}

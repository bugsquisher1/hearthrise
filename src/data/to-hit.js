/** The ratio: the chance a blow of rating `attack` lands on rating `defense` (each held at 1 or more). Pure. */
export function toHitRatio(attack, defense) {
  const a = Math.max(1, Number(attack) || 0), d = Math.max(1, Number(defense) || 0);
  return a >= d ? 1 - d / (2 * a) : a / (2 * d);
}

/** A chance held to the rails. */
export const heldToHit = (p) => Math.max(TO_HIT.min, Math.min(TO_HIT.max, p));

/** The reference hero at Level `level`: { main, defense, accuracy }, read straight between the table's rows, and past its last
    row on the slope of its last two (Levels are endless). Pure. */
export function refHeroAt(level, table = REF_HERO) {
  const L = Math.max(1, Number(level) || 1), T = table;
  const at = (a, b) => (i) => a[i] + ((b[i] - a[i]) * (L - a[0])) / (b[0] - a[0]);
  let f;
  if (L <= T[0][0]) f = (i) => T[0][i];
  else {
    let k = 1;
    while (k < T.length - 1 && L > T[k][0]) k++;
    f = at(T[k - 1], T[k]);
  }
  return { main: f(1), defense: f(2), accuracy: f(3) };
}

/** A monster's AIM: the attack rating that lands `hit` on the reference hero of Level `level` (the inverse of the ratio against
    TO_HIT.base + its Defense). `hit` is held inside (0, 1) by the rails. Unrounded. */
export function aimFor(hit, level, table = REF_HERO) {
  const h = heldToHit(hit), d = TO_HIT.base + refHeroAt(level, table).defense;
  return h >= 0.5 ? d / (2 * (1 - h)) : 2 * h * d;
}

/** A monster's EVASION: the defense rating the reference hero of Level `level` lands `heroHit` on, times its role's `mult`. Unrounded. */
export function evasionFor(heroHit, level, mult = 1, table = REF_HERO) {
  const h = heldToHit(heroHit), r = refHeroAt(level, table), a = TO_HIT.base + r.main + r.accuracy;
  return (h >= 0.5 ? 2 * (1 - h) * a : a / (2 * h)) * mult;
}

/** The chance of an aim written to land `hit` on its reference, raised `k` times (a tier's or an enrage's harder blow), against
    that same reference: free of the reference's numbers, since the aim is a multiple of them (balance-sheet.js swingWorth). Pure. */
export function raisedHit(hit, k) {
  const h = heldToHit(hit), x = (h >= 0.5 ? 1 / (2 * (1 - h)) : 2 * h) * k;
  return heldToHit(x >= 1 ? 1 - 1 / (2 * x) : x / 2);
}

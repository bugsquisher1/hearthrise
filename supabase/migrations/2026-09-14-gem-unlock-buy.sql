-- ── 7. SELF-VERIFYING COMMIT GATE (§4) ─────────────────────────────────────
-- Proves the load-bearing properties by EXECUTING them, not by matching markers.
-- The apply is atomic, so a raise here reverts every section above it. The
-- row-writing probes live in a subtransaction discarded by a sentinel raise
-- (HR842), so this block is NET-ZERO on production — asserted, not asserted
-- about, by the leak check at the end.
do $$
declare
  v_uid   constant uuid := '00000000-0000-4000-8000-0000b5460001';
  v_n     int;
  v_bad   text;
  v_r     jsonb;
  v_env   jsonb;
  v_gems0 bigint;
  v_cost  bigint;
  v_id    text;
  v_free  text;
begin
  -- (a) THE CATALOGUE IS THE ONLY PRICE. No literal gem number may appear in the
  --     verb's own EXECUTABLE body: that is what makes "the price is generated" a
  --     property rather than a habit. The body may hold small integers (slot
  --     bounds, the daily clamp, the id length) — the assertion is specifically
  --     that nothing reads like a PRICE, i.e. no three-or-more-digit literal.
  --     ⚠ COMMENTS ARE STRIPPED FIRST, and that is not a softening: the prose in
  --       this verb cites "the 1,000-gem Volcanic Keep" and the b371 incident, and
  --       an assertion that a comment cannot mention a number would be paid for by
  --       deleting the explanation instead of the defect. `--` to end of line;
  --       no string literal in this body contains a double hyphen.
  select regexp_replace(p.prosrc, '--[^' || chr(10) || ']*', '', 'g') into v_bad
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'hr_buy_gem_unlock__ungated';
  if v_bad is null then raise exception 'GATE(a): hr_buy_gem_unlock__ungated is missing'; end if;
  if v_bad ~ '[^0-9a-zA-Z_]\d{3,}' then
    raise exception 'GATE(a): hr_buy_gem_unlock__ungated contains a 3+ digit literal outside a '
                    'comment — a price typed into the verb is a second copy of a money number';
  end if;
  if position('hr_gem_unlocks' in v_bad) = 0 then
    raise exception 'GATE(a): the verb does not read public.hr_gem_unlocks at all';
  end if;

  -- (b) THE PROJECTION IS TOP-LEVEL AND IT IS THIS FUNCTION'S ANSWER. Not "the
  --     body mentions gem_unlocks" — the exact spliced expression, because a key
  --     projected inside `state`, or filled from a different source, is the
  --     shipped bug under a new name (tests/renown-projection.mjs R2's lesson).
  select p.prosrc into v_bad from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'hr_state_of';
  if position($q$'gem_unlocks', public.hr_gem_unlocks_of(p_user, v_st.slot)$q$ in v_bad) = 0 then
    raise exception 'GATE(b): hr_state_of does not project gem_unlocks from hr_gem_unlocks_of';
  end if;
  -- AND THE NEIGHBOURS SURVIVED. This body is 21 anchored edits deep; the way
  -- this file could hurt somebody is by dropping one of them.
  if position($q$'renown_high'$q$ in v_bad) = 0
     or position($q$'hero_slots'$q$ in v_bad) = 0
     or position($q$'traits'$q$ in v_bad) = 0
     or position($q$'inventory_complete'$q$ in v_bad) = 0 then
    raise exception 'GATE(b): a pre-existing hr_state_of projection was LOST by this splice';
  end if;

  -- (c) THE CLIENT SURFACE. The wrapper is callable by `authenticated`, the
  --     ungated twin and the predicate are callable by NOBODY, and the wrapper
  --     carries defaults so PostgREST can resolve a one-argument POST.
  if not has_function_privilege('authenticated', 'public.hr_buy_gem_unlock(text,int,uuid)', 'execute') then
    raise exception 'GATE(c): hr_buy_gem_unlock is not callable by authenticated — a dead button';
  end if;
  if has_function_privilege('authenticated', 'public.hr_buy_gem_unlock__ungated(text,int,uuid)', 'execute')
     or has_function_privilege('anon', 'public.hr_buy_gem_unlock__ungated(text,int,uuid)', 'execute')
     or has_function_privilege('service_role', 'public.hr_buy_gem_unlock__ungated(text,int,uuid)', 'execute') then
    raise exception 'GATE(c): the UNGATED verb is client-executable — the rate gate is bypassable';
  end if;
  if has_function_privilege('anon', 'public.hr_buy_gem_unlock(text,int,uuid)', 'execute') then
    raise exception 'GATE(c): anon may buy a cosmetic';
  end if;
  if has_function_privilege('authenticated', 'public.hr_gem_unlocks_of(uuid,int)', 'execute')
     or has_function_privilege('anon', 'public.hr_gem_unlocks_of(uuid,int)', 'execute') then
    raise exception 'GATE(c): hr_gem_unlocks_of is client-executable — it takes an ARBITRARY uuid';
  end if;
  select count(*) into v_n from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'hr_buy_gem_unlock' and p.pronargdefaults = 2;
  if v_n <> 1 then
    raise exception 'GATE(c): hr_buy_gem_unlock does not carry two argument defaults — PostgREST '
                    'would answer PGRST202 to a {p_unlock_id} post, a 404 nobody can tell from an '
                    'unapplied migration';
  end if;
  -- THE SEAM (tests/rejections-journal.mjs P6). Exactly one, in the wrapper.
  select (select count(*) from regexp_matches(p.prosrc, 'hr_note_rejection\(', 'g')) into v_n
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'hr_buy_gem_unlock';
  if v_n <> 1 then
    raise exception 'GATE(c): the wrapper carries % hr_note_rejection calls (need exactly 1) — a '
                    'refusal nothing records is a refusal nobody can see', v_n;
  end if;

  -- (d) THE CATALOGUE IS NOT REACHABLE FROM A BROWSER, restated here because the
  --     generated file and this one can be applied minutes apart and only this
  --     one hands out an EXECUTE.
  select coalesce(string_agg(distinct grantee, ', '), '') into v_bad
    from information_schema.role_table_grants
   where table_schema = 'public' and table_name = 'hr_gem_unlocks'
     and grantee in ('anon', 'authenticated', 'service_role', 'PUBLIC');
  if v_bad <> '' then raise exception 'GATE(d): hr_gem_unlocks is reachable by %', v_bad; end if;
  select count(*) into v_n from pg_policies
   where schemaname = 'public' and tablename = 'player_progress'
     and cmd in ('INSERT','UPDATE','DELETE','ALL');
  if v_n > 0 then
    raise exception 'GATE(d): player_progress has % client write policies — the entitlement this '
                    'verb sells could be written by the browser that buys it', v_n;
  end if;

  -- (e) EXECUTED, END TO END, on a synthetic account inside a discarded
  --     subtransaction. Everything above this is text and catalogue; this is the
  --     only part that proves gems actually move and only once.
  if to_regprocedure('public.hr_create_character(int)') is null then
    raise exception 'GATE(e) CANNOT RUN: hr_create_character missing';
  end if;
  select unlock_id, cost_gems into v_id, v_cost
    from public.hr_gem_unlocks where not free order by cost_gems limit 1;
  select unlock_id into v_free from public.hr_gem_unlocks where free order by unlock_id limit 1;
  if v_id is null or v_free is null then
    raise exception 'GATE(e) CANNOT RUN: the catalogue has no priced row and/or no free row (%/%)',
      v_id, v_free;
  end if;
  begin  -- ── SUBTRANSACTION ────────────────────────────────────────────────
    insert into auth.users (id) values (v_uid);
    perform set_config('request.jwt.claim.sub', v_uid::text, true);
    v_r := public.hr_create_character(0);
    if v_r->>'created' <> 'true' then
      raise exception 'GATE(e): no probe character: %', v_r; end if;

    -- (e1) THE FREE ROW IS ALREADY OWNED AND IS NOT FOR SALE. Both halves: a
    --      fresh character owns theme:default without paying, and asking to buy
    --      it is refused rather than sold for nothing.
    v_env := public.hr_state_of(v_uid, 0);
    if not ((v_env->'gem_unlocks') @> to_jsonb(v_free)) then
      raise exception 'GATE(e1): a fresh character does not own the FREE % — the starting theme '
                      'would be unequippable the moment the client reads ownership server-first',
                      v_free;
    end if;
    if (v_env->'gem_unlocks') @> to_jsonb(v_id) then
      raise exception 'GATE(e1): a fresh character already owns the PRICED % — the projection is '
                      'not reading ownership at all', v_id;
    end if;
    v_r := public.hr_buy_gem_unlock__ungated(v_free, 0, gen_random_uuid());
    if v_r->>'error' is distinct from 'not_for_sale' then
      raise exception 'GATE(e1): buying the free row answered % — it must be not_for_sale, or a '
                      '0-gem purchase path exists', v_r;
    end if;

    -- (e2) NO GEMS, NO PURCHASE. Run BEFORE any gems are granted, so the refusal
    --      is the shipped default rather than something this probe arranged.
    select coalesce(gems, 0) into v_gems0 from public.player_state
     where user_id = v_uid and slot = 0;
    if v_gems0 >= v_cost then
      raise exception 'GATE(e2) CANNOT RUN: a new character starts with % gems, which is enough '
                      'for the cheapest offer (%) — this probe proves nothing', v_gems0, v_cost;
    end if;
    v_r := public.hr_buy_gem_unlock__ungated(v_id, 0, gen_random_uuid());
    if v_r->>'error' is distinct from 'insufficient_gems' then
      raise exception 'GATE(e2): a broke character was answered % buying % — it must be '
                      'insufficient_gems', v_r, v_id;
    end if;
    if (public.hr_gem_unlocks_of(v_uid, 0)) @> to_jsonb(v_id) then
      raise exception 'GATE(e2): the REFUSED purchase granted the unlock anyway';
    end if;

    -- (e3) THE HAPPY PATH. Gems are placed on the row directly (this is a
    --      synthetic probe, not a player — no faucet is exercised), then the
    --      purchase must debit EXACTLY the catalogue price, grant the flag, and
    --      show up on the envelope.
    update public.player_state set gems = v_cost + 1
     where user_id = v_uid and slot = 0;
    v_r := public.hr_buy_gem_unlock__ungated(v_id, 0, '00000000-0000-4000-8000-0000b5460aa1');
    if coalesce(v_r->>'ok','false') <> 'true' then
      raise exception 'GATE(e3): a funded purchase of % was refused: %', v_id, v_r;
    end if;
    if (v_r->>'gems')::bigint <> 1 then
      raise exception 'GATE(e3): the debit left % gems, expected 1 (cost %) — the price charged is '
                      'not the catalogue price', v_r->>'gems', v_cost;
    end if;
    if not ((v_r->'gem_unlocks') @> to_jsonb(v_id)) then
      raise exception 'GATE(e3): the verb''s own answer does not carry the thing just bought';
    end if;
    if not exists (select 1 from public.player_progress
                    where user_id = v_uid and slot = 0 and kind = 'flag'
                      and key = v_id and period_key = '' and value > 0) then
      raise exception 'GATE(e3): no flag row was written — the gems went nowhere';
    end if;
    -- THE ENVELOPE AND THE VERDICT MUST AGREE. A projection the purchase path
    -- does not honour is worse than no projection: the player would see it owned
    -- and be refused on use (tests/renown-projection.mjs R3's rule).
    v_env := public.hr_state_of(v_uid, 0);
    if (v_env->'gem_unlocks') is distinct from (v_r->'gem_unlocks') then
      raise exception 'GATE(e3): hr_state_of (%) and the purchase verdict (%) disagree about the '
                      'owned set', v_env->'gem_unlocks', v_r->'gem_unlocks';
    end if;
    -- ONE journal row, carrying the SIGNED movement.
    select count(*) into v_n from public.player_ledger
     where user_id = v_uid and kind = 'gem_unlock';
    if v_n <> 1 then raise exception 'GATE(e3): % ledger rows for one purchase', v_n; end if;
    if (select (meta->>'gems')::bigint from public.player_ledger
         where user_id = v_uid and kind = 'gem_unlock' limit 1) <> -v_cost then
      raise exception 'GATE(e3): the journal does not record the signed gem movement';
    end if;

    -- (e4) THE REPLAY. The SAME idempotency key must answer the SAME envelope
    --      and debit nothing — this is the property a retrying client depends on
    --      and the one a double-tap would otherwise break.
    v_r := public.hr_buy_gem_unlock__ungated(v_id, 0, '00000000-0000-4000-8000-0000b5460aa1');
    if coalesce(v_r->>'replayed','false') <> 'true' then
      raise exception 'GATE(e4): the replayed key was not answered from the cache: %', v_r;
    end if;
    if (select gems from public.player_state where user_id = v_uid and slot = 0) <> 1 then
      raise exception 'GATE(e4): the replay MOVED GEMS — a retry charges twice';
    end if;

    -- (e5) AND A FRESH KEY ON AN OWNED UNLOCK IS already_owned, NOT a second
    --      sale. The idempotency cache is not what protects the balance here.
    v_r := public.hr_buy_gem_unlock__ungated(v_id, 0, gen_random_uuid());
    if v_r->>'error' is distinct from 'already_owned' then
      raise exception 'GATE(e5): re-buying an owned unlock with a fresh key answered % — it must '
                      'be already_owned', v_r;
    end if;
    if (select gems from public.player_state where user_id = v_uid and slot = 0) <> 1 then
      raise exception 'GATE(e5): re-buying an owned unlock CHARGED AGAIN';
    end if;

    -- (e6) A FORGED ID BUYS NOTHING AND COSTS NOTHING.
    v_r := public.hr_buy_gem_unlock__ungated('theme:free_money', 0, gen_random_uuid());
    if v_r->>'error' is distinct from 'unknown_unlock' then
      raise exception 'GATE(e6): an uncatalogued id answered %', v_r;
    end if;
    if (select gems from public.player_state where user_id = v_uid and slot = 0) <> 1 then
      raise exception 'GATE(e6): an uncatalogued id MOVED GEMS';
    end if;

    -- (e7) THE RULING, EXECUTED: OWNERSHIP IS PER ACCOUNT. A SECOND character of
    --      the same account must SEE the unlock slot 0 bought and must be
    --      REFUSED a second purchase of it — otherwise every multi-character
    --      player pays the premium price once per hero. The hero slot is granted
    --      through the real entitlement flag rather than by forging a row, so
    --      hr_create_character's own gate is exercised rather than bypassed.
    insert into public.player_progress
      (user_id, slot, kind, key, value, period_key, updated_at)
    values (v_uid, 0, 'flag', 'character_slot:1', 1, '', now())
    on conflict (user_id, slot, kind, key, period_key) do update set value = 1;
    v_r := public.hr_create_character(1);
    if v_r->>'created' <> 'true' then
      raise exception 'GATE(e7) CANNOT RUN: the second character was refused (%) — the account '
                      'entitlement flag did not take', v_r;
    end if;
    if not ((public.hr_gem_unlocks_of(v_uid, 1)) @> to_jsonb(v_id)) then
      raise exception 'GATE(e7): hero 2 does not own the % hero 1 bought (%) — ownership is per '
                      'ACCOUNT (game-designer ruling 2026-09-14) and this read is slot-scoped',
                      v_id, public.hr_gem_unlocks_of(v_uid, 1);
    end if;
    if not (((public.hr_state_of(v_uid, 1))->'gem_unlocks') @> to_jsonb(v_id)) then
      raise exception 'GATE(e7): hero 2''s ENVELOPE does not carry the account''s unlock';
    end if;
    update public.player_state set gems = 999999 where user_id = v_uid and slot = 1;

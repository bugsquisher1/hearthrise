#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/gen-storage-chests.mjs — GENERATE THE DEPOT-SPACE CATALOGUE.
//
// src/data/homestead-tiers.js is the single source of the account depot's
// space: DEPOT_BASE_STACKS and the STORAGE_CHESTS rows (id, name, stacks, the
// property tier each needs, its cost in gold + materials). Postgres must know
// them to enforce what only it can: the depot's capacity (hr_bank_move) and the
// price, order and gate of a chest (hr_storage_chest_build). Emitted here as
// `hr_storage_chests` / `hr_depot_config`; a new chest is a data row + this regen.
//
//   Regenerate:  node tools/gen-storage-chests.mjs
//   Verify:      node tools/gen-storage-chests.mjs --check     (exit 1 on drift)
//   Selftest:    node tools/gen-storage-chests.mjs --selftest  (the refusals bite)
//
// THE ROWS ARE UPSERTED, NEVER DELETED AND REINSERTED: account_storage_chests
// points at hr_storage_chests, so a delete-and-insert regen would refuse (or, with
// a cascade, demolish every built chest). A chest removed from the data is
// deleted, which REFUSES while any account has built it — loudly, by design.
//
// REFUSES (throws, nothing written): a bad id or name, a duplicate id, stacks
// outside 1..1000, a tier outside the property ladder or below the chest before
// it, a cost with no gold, a material that is not an item, a base outside 1..1000.
// ════════════════════════════════════════════════════════════════════════
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { isMain } from '../tests/_is-main.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_FILE = '2026-11-28-storage-chests-catalogue.generated.sql';
const OUT = join(ROOT, 'supabase', 'migrations', OUT_FILE);

const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";

/** The generated SQL for these rows. Throws on anything the server would have to guess about. */
export function buildSql(H, itemIds) {
  const base = H.DEPOT_BASE_STACKS;
  if (!Number.isInteger(base) || base < 1 || base > 1000) throw new Error('gen-storage-chests: DEPOT_BASE_STACKS must be an integer in 1..1000');
  const rows = H.STORAGE_CHESTS;
  if (!Array.isArray(rows) || !rows.length) throw new Error('gen-storage-chests: no STORAGE_CHESTS rows');
  const seen = new Set();
  let prevTier = 0;
  rows.forEach((c, i) => {
    if (!/^[a-z0-9_]{1,40}$/.test(String(c.id))) throw new Error('gen-storage-chests: bad chest id ' + c.id);
    if (seen.has(c.id)) throw new Error('gen-storage-chests: duplicate chest id ' + c.id);
    seen.add(c.id);
    if (typeof c.name !== 'string' || c.name.length < 3 || c.name.length > 40) throw new Error('gen-storage-chests: ' + c.id + ' has no proper name');
    if (!Number.isInteger(c.stacks) || c.stacks < 1 || c.stacks > 1000) throw new Error('gen-storage-chests: ' + c.id + ' stacks outside 1..1000');
    if (!Number.isInteger(c.tier) || c.tier < 0 || c.tier >= H.PROPERTY_TIERS.length) throw new Error('gen-storage-chests: ' + c.id + ' tier is not a property tier');
    if (c.tier < prevTier) throw new Error('gen-storage-chests: ' + c.id + ' asks a lower property tier than the chest before it');
    prevTier = c.tier;
    const cost = c.cost || {};
    if (!Number.isSafeInteger(cost.gold) || cost.gold < 1) throw new Error('gen-storage-chests: ' + c.id + ' costs no gold');
    for (const [k, v] of Object.entries(cost)) {
      if (k === 'gold') continue;
      if (!itemIds.has(k)) throw new Error('gen-storage-chests: ' + c.id + ' asks for ' + k + ', which is not an item');
      if (!Number.isInteger(v) || v < 1 || v > 100000) throw new Error('gen-storage-chests: ' + c.id + ' material ' + k + ' qty outside 1..100000');
    }
  });
  const items = (c) => JSON.stringify(Object.fromEntries(Object.entries(c.cost).filter(([k]) => k !== 'gold').sort(([a], [b]) => (a < b ? -1 : 1))));
  const values = rows.map((c, i) => `  (${lit(c.id)}, ${lit(c.name)}, ${i + 1}, ${c.stacks}, ${c.tier}, ${c.cost.gold}, ${lit(items(c))}::jsonb)`);
  const total = rows.reduce((a, c) => a + c.stacks, 0);
  return `-- ════════════════════════════════════════════════════════════════════════
-- Generated by tools/gen-storage-chests.mjs from src/data/homestead-tiers.js
-- (DEPOT_BASE_STACKS, STORAGE_CHESTS). Do not hand-edit:
--   Any hand edit FAILS \`node tools/gen-storage-chests.mjs --check\`.
-- STAGED (lane/c-account-shared). The account depot's space: a base every account
-- has, and the chests an account can build (one each, in order) to add to it.
-- Read by 2026-11-28-storage-chests.sql (hr_depot_cap, hr_storage_chest_build),
-- which applies AFTER this file. Rows are UPSERTED (account_storage_chests
-- references hr_storage_chests); a removed row is deleted. No begin/commit.
-- ════════════════════════════════════════════════════════════════════════

create table if not exists public.hr_storage_chests (
  chest_id          text    primary key check (chest_id ~ '^[a-z0-9_]{1,40}$'),
  name              text    not null check (length(name) between 3 and 40),
  ord               int     not null unique check (ord >= 1),
  stacks            int     not null check (stacks between 1 and 1000),
  req_property_tier int     not null check (req_property_tier between 0 and 5),
  gold              bigint  not null check (gold >= 1),
  items             jsonb   not null default '{}'::jsonb check (jsonb_typeof(items) = 'object')
);
create table if not exists public.hr_depot_config (
  only_row    boolean primary key default true check (only_row),
  base_stacks int     not null check (base_stacks between 1 and 1000)
);
do $mig$
declare v_t text;
begin
  foreach v_t in array array['hr_storage_chests', 'hr_depot_config'] loop
    execute format('alter table public.%I enable row level security', v_t);
    execute format('revoke all on public.%I from public, anon, authenticated, service_role', v_t);
  end loop;
end $mig$;

-- ord is unique: park the old order out of the way before the upsert re-numbers it.
update public.hr_storage_chests set ord = ord + 1000000;
insert into public.hr_storage_chests (chest_id, name, ord, stacks, req_property_tier, gold, items) values
${values.join(',\n')}
  on conflict (chest_id) do update set name = excluded.name, ord = excluded.ord, stacks = excluded.stacks,
    req_property_tier = excluded.req_property_tier, gold = excluded.gold, items = excluded.items;
delete from public.hr_storage_chests where chest_id <> all (array[${rows.map((c) => lit(c.id)).join(', ')}]);

insert into public.hr_depot_config (only_row, base_stacks) values (true, ${base})
  on conflict (only_row) do update set base_stacks = excluded.base_stacks;

-- SELF-CHECK (CLAUDE.md §4): the rows are exactly the data's; every material is an item; no client reaches them.
do $$
declare v_role text;
begin
  if (select count(*) from public.hr_storage_chests) <> ${rows.length}
     or (select sum(stacks) from public.hr_storage_chests) <> ${total}
     or (select base_stacks from public.hr_depot_config) <> ${base} then
    raise exception 'storage-chests-catalogue: the rows are not the generated set'; end if;
  if exists (select 1 from public.hr_storage_chests c, jsonb_object_keys(c.items) k
              where not exists (select 1 from public.hr_items i where i.item_id = k)) then
    raise exception 'storage-chests-catalogue: a chest asks for a material that is not in hr_items'; end if;
  foreach v_role in array array['anon', 'authenticated'] loop
    if has_table_privilege(v_role, 'public.hr_storage_chests', 'select,insert,update,delete')
       or has_table_privilege(v_role, 'public.hr_depot_config', 'select,insert,update,delete') then
      raise exception 'storage-chests-catalogue: % reaches the catalogue', v_role; end if;
  end loop;
  raise notice 'storage-chests-catalogue: base ${base} stacks, ${rows.length} chests (+${total}); all green';
end $$;
`;
}

async function inputs(root) {
  const H = await import(pathToFileURL(join(root, 'src', 'data', 'homestead-tiers.js')).href);
  const I = await import(pathToFileURL(join(root, 'src', 'data', 'items.js')).href);
  const list = I.ITEMS || I.default;
  const ids = new Set(Array.isArray(list) ? list.map((x) => x.id) : Object.keys(list || {}));
  if (ids.size < 10) throw new Error('gen-storage-chests: src/data/items.js gave no item ids');
  return { H, ids };
}

async function selftest() {
  const { H, ids } = await inputs(ROOT);
  let bad = 0;
  const expectThrow = (name, fn) => { try { fn(); console.error('  MISSED  ' + name); bad++; } catch { console.log('  caught  ' + name); } };
  const withRow = (patch) => ({ ...H, STORAGE_CHESTS: H.STORAGE_CHESTS.map((c, i) => (i === 1 ? { ...c, ...patch } : c)) });
  expectThrow('a material that is not an item', () => buildSql(withRow({ cost: { gold: 10, moonstone_dust: 3 } }), ids));
  expectThrow('a chest that costs no gold', () => buildSql(withRow({ cost: { gold: 0 } }), ids));
  expectThrow('a duplicate id', () => buildSql(withRow({ id: H.STORAGE_CHESTS[0].id }), ids));
  expectThrow('stacks out of range', () => buildSql(withRow({ stacks: 0 }), ids));
  expectThrow('a tier below the chest before it', () => buildSql({ ...H, STORAGE_CHESTS: [{ ...H.STORAGE_CHESTS[1], tier: 2 }, { ...H.STORAGE_CHESTS[0], tier: 1 }] }, ids));
  expectThrow('a tier off the property ladder', () => buildSql(withRow({ tier: 99 }), ids));
  expectThrow('a base out of range', () => buildSql({ ...H, DEPOT_BASE_STACKS: 0 }, ids));
  if (!/on conflict \(chest_id\) do update/.test(buildSql(H, ids))) { console.error('  MISSED  the rows are not upserted'); bad++; }
  if (bad) { console.error('gen-storage-chests --selftest: ' + bad + ' refusal(s) did not bite'); process.exit(1); }
  console.log('gen-storage-chests --selftest: every refusal bites');
}

async function main() {
  if (process.argv.includes('--selftest')) return selftest();
  const { H, ids } = await inputs(ROOT);
  const wanted = buildSql(H, ids);
  if (process.argv.includes('--check')) {
    const have = await readFile(OUT, 'utf8').catch(() => '');
    if (have.replace(/\r\n/g, '\n') !== wanted) {
      console.error('gen-storage-chests --check FAILED: ' + OUT_FILE + ' is stale. Run: node tools/gen-storage-chests.mjs');
      process.exit(1);
    }
    console.log('gen-storage-chests --check: catalogue matches src/data/homestead-tiers.js');
    return;
  }
  await writeFile(OUT, wanted);
  console.log('gen-storage-chests: wrote ' + OUT_FILE);
}

if (isMain(import.meta.url)) main();

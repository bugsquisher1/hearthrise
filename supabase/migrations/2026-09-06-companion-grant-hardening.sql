-- ── 4. BEHAVIOUR — driven through the REAL RPC, rolled back (HRG28) ───────
-- Every probe below runs inside ONE subtransaction that is deliberately
-- aborted. Any assertion that fires raises a NON-HRG28 error, which the handler
-- does not catch, so it aborts the whole migration — a half-applied gate is
-- impossible, and so is a leaked probe row or a mutated catalogue.
do $$
declare
  v_uid   uuid := '00000000-0000-4000-8000-0000c0a91a70'::uuid;
  v_r     jsonb;
  v_env   jsonb;
  v_meta  jsonb;
  v_ver   bigint;
  v_led   bigint;
  v_state text;
  v_msg   text;
begin
  if to_regprocedure('public.hr_create_character(int)') is null then
    raise exception '§4 CANNOT RUN: hr_create_character is missing — apply '
                    '2026-08-14-character-bootstrap.sql first. A skipped check is not a passed one.';
  end if;

  begin  -- ── subtransaction, rolled back ────────────────────────────────────
    insert into auth.users (id) values (v_uid);
    perform set_config('request.jwt.claim.sub', v_uid::text, true);
    perform public.hr_create_character(0);

    -- ── (a) THE CONTROL: an ordinary grant is UNCHANGED. Row, version bump,
    --        owned projection, and still equippable. If this fails, everything
    --        below is measuring a broken verb rather than the hardening.
    select version into v_ver from public.player_state where user_id = v_uid and slot = 0;
    v_r := public.hr_companion_grant(0, 'badger', 'boss:i_said_so', gen_random_uuid());
    if coalesce(v_r->>'ok', 'false') <> 'true' then
      raise exception '§4(a) CONTROL FAILED: a legitimate badger grant was refused (%)', v_r;
    end if;
    if not exists (select 1 from public.player_progress where user_id = v_uid and slot = 0
                    and kind = 'unlock' and key = 'companion:badger' and value = 1) then
      raise exception '§4(a): the ownership row was not written';
    end if;
    if (select version from public.player_state where user_id = v_uid and slot = 0) <> v_ver + 1 then
      raise exception '§4(a): the grant did not bump the version';
    end if;
    v_env := public.hr_state_of(v_uid, 0);
    if not (v_env->'companions'->'owned' @> ('["badger"]')::jsonb) then
      raise exception '§4(a): hr_state_of does not project badger in owned: %',
        v_env->'companions'->'owned';
    end if;
    if coalesce((public.hr_companion_equip(0, 'badger', false))->>'ok', 'false') <> 'true' then
      raise exception '§4(a): a granted companion could not be equipped';
    end if;

    -- ── (b) C3 — THE LEDGER IS HONEST ABOUT WHICH FIELD IS EVIDENCE.
    --        The claim above ('boss:i_said_so') deliberately CONTRADICTS the
    --        catalogue ('drop'), so the two fields cannot be confused for one
    --        another and a fixture built from the wrong one cannot pass.
    select meta into v_meta from public.player_ledger
     where user_id = v_uid and slot = 0 and intent = 'companion_grant'
     order by id desc limit 1;
    if v_meta is null then raise exception '§4(b): the grant wrote no ledger row'; end if;
    if not (v_meta ? 'claimed_source') then
      raise exception '§4(b) C3: the ledger meta carries no claimed_source: %', v_meta;
    end if;
    if v_meta ? 'source' then
      raise exception '§4(b) C3: the ledger meta STILL carries the bare client key `source` beside '
                      'the server-derived catalogue_source: %', v_meta;
    end if;
    if v_meta->>'claimed_source' is distinct from 'boss:i_said_so' then
      raise exception '§4(b) C3: claimed_source is % — it must be the CLIENT''s string verbatim, '
                      'or the ledger is not recording what was claimed', v_meta->>'claimed_source';
    end if;
    if v_meta->>'catalogue_source' is distinct from 'drop' then
      raise exception '§4(b) C3: catalogue_source is % — it must be the SERVER''s own allowlist '
                      'value (badger = drop), unaffected by the client''s claim',
                      v_meta->>'catalogue_source';
    end if;

    -- ── (c) REPLAY is already_owned: no second row, no second ledger row, no
    --        second version bump. (Unchanged behaviour, re-proved.)
    select version into v_ver from public.player_state where user_id = v_uid and slot = 0;
    select count(*) into v_led from public.player_ledger
     where user_id = v_uid and intent = 'companion_grant';
    v_r := public.hr_companion_grant(0, 'badger', 'drop:again', gen_random_uuid());
    if coalesce(v_r->>'already_owned', 'false') <> 'true' then
      raise exception '§4(c): a replay was not reported already_owned (%)', v_r;
    end if;
    if (select version from public.player_state where user_id = v_uid and slot = 0) <> v_ver
       or (select count(*) from public.player_ledger
            where user_id = v_uid and intent = 'companion_grant') <> v_led then
      raise exception '§4(c): a replay wrote state';
    end if;

    -- ── (d) THE MINT GATE IS UNCHANGED: an unknown id and a SHOP companion are
    --        both still refused not_grantable.
    v_r := public.hr_companion_grant(0, 'any_op_companion', 'drop:x', gen_random_uuid());
    if v_r->>'error' is distinct from 'not_grantable' then
      raise exception '§4(d): an unknown id answered % (expected not_grantable)', v_r;
    end if;
    v_r := public.hr_companion_grant(0, 'sparrow', 'shop', gen_random_uuid());
    if v_r->>'error' is distinct from 'not_grantable' then
      raise exception '§4(d): the shop companion sparrow answered % (expected not_grantable — a '
                      'free shop pet is exactly the mint this gate refuses)', v_r;
    end if;

    -- ══ (e) C2 — WITHOUT THE EGG, NOTHING HAPPENS ════════════════════════════
    select version into v_ver from public.player_state where user_id = v_uid and slot = 0;
    select count(*) into v_led from public.player_ledger
     where user_id = v_uid and intent = 'companion_grant';
    v_r := public.hr_companion_grant(0, 'whelp', 'hatch:dragon_egg', gen_random_uuid());
    if coalesce(v_r->>'ok', 'true') <> 'false' or v_r->>'error' is distinct from 'missing_req_item' then
      raise exception '§4(e) C2: whelp was granted WITHOUT its req_item (%). The control still '
                      'measures and does not decide — it is still fake.', v_r;
    end if;
    if v_r->>'item' is distinct from 'dragon_egg' then
      raise exception '§4(e) C2: the refusal does not name the item it wants (%)', v_r;
    end if;
    if exists (select 1 from public.player_progress where user_id = v_uid and slot = 0
                and kind = 'unlock' and key = 'companion:whelp') then
      raise exception '§4(e) C2: refused, but the ownership row was written anyway';
    end if;
    if (select version from public.player_state where user_id = v_uid and slot = 0) <> v_ver then
      raise exception '§4(e) C2: a refused grant bumped the version';
    end if;
    if (select count(*) from public.player_ledger
         where user_id = v_uid and intent = 'companion_grant') <> v_led then
      raise exception '§4(e) C2: a refused grant wrote a ledger row';
    end if;
    if not exists (select 1 from public.hr_rejections where user_id = v_uid
                    and intent = 'companion_grant' and code = 'missing_req_item') then
      raise exception '§4(e) C2: the refusal was not journalled. "Journalled the way the verb''s '
                      'other refusals are" is the condition, not a nicety — an unjournalled refusal '
                      'is an invisible one.';
    end if;

    -- ══ (f) C1 — THE MISSING CATALOGUE ROW IS A MACHINE CODE, AND IT COSTS
    --        THE PLAYER NOTHING. Run on the ONE companion with a req_item, so
    --        the same probe proves both properties at once.
    --
    --   ⚠ IN ITS OWN NESTED SUBTRANSACTION (HRG29), and the catalogue row is
    --     restored BY THAT ROLLBACK rather than by an INSERT. Two reasons, and
    --     the second is not cosmetic:
    --       · a restore statement can be wrong, or be edited out; a rollback
    --         cannot. The deletion is structurally incapable of escaping.
    --       · this file must not contain an INSERT statement against
    --         public.hr_unlocks — not even a commented one.
    --         tests/unlock-catalogue-ownership.mjs derives the catalogue's
    --         repair list by scanning every manifest file's TEXT for exactly
    --         that statement, and a file that only touches hr_unlocks inside a
    --         rolled-back probe would be mis-classified as a seeder that must be
    --         re-applied after a wholesale wipe. It is not one. (Measured: the
    --         first draft used a restore INSERT and turned that guard red.)
    insert into public.player_inventory (user_id, slot, item_id, qty)
      values (v_uid, 0, 'dragon_egg', 2)
      on conflict (user_id, slot, item_id) do update set qty = excluded.qty;
    begin
      delete from public.hr_unlocks where unlock_id = 'companion:whelp';
      begin
        v_r := public.hr_companion_grant(0, 'whelp', 'hatch:dragon_egg', gen_random_uuid());
      exception when others then
        raise exception '§4(f) C1: with companion:whelp absent from hr_unlocks the RPC still RAISES '
                        '(% / %) instead of returning a machine code. That raise is the PostgREST 500 '
                        'a client cannot tell from an outage — the whole condition.', sqlstate, sqlerrm;
      end;
      if v_r->>'error' is distinct from 'unknown_unlock:companion:whelp' then
        raise exception '§4(f) C1: expected error unknown_unlock:companion:whelp, got %', v_r;
      end if;
      if coalesce(v_r->>'ok', 'true') <> 'false' then
        raise exception '§4(f) C1: the refusal reported ok (%)', v_r;
      end if;
      if coalesce((v_r->'detail'->>'raced')::boolean, true) <> false then
        raise exception '§4(f) C1: the refusal should be marked raced=false — Layer A answered '
                        'before anything was locked or spent (%)', v_r;
      end if;
      if (select qty from public.player_inventory
           where user_id = v_uid and slot = 0 and item_id = 'dragon_egg') <> 2 then
        raise exception '§4(f) C1: the refusal CONSUMED the req_item. A refusal that eats the '
                        'player''s egg and grants nothing is worse than the 500 it replaced.';
      end if;
      if exists (select 1 from public.player_progress where user_id = v_uid and slot = 0
                  and kind = 'unlock' and key = 'companion:whelp') then
        raise exception '§4(f) C1: refused, but the ownership row was written';
      end if;
      if not exists (select 1 from public.hr_rejections where user_id = v_uid
                      and intent = 'companion_grant' and code = 'unknown_unlock') then
        raise exception '§4(f) C1: the refusal was not journalled';
      end if;
      raise exception using errcode = 'HRG29', message = '§4(f) done — restoring companion:whelp';
    exception when sqlstate 'HRG29' then
      null;   -- the catalogue row is back, by rollback
    end;
    if not exists (select 1 from public.hr_unlocks where unlock_id = 'companion:whelp'
                    and progress_kind = 'unlock' and merge = 'max' and max_value = 1
                    and rungs = array[1]::int[]) then
      raise exception '§4(f): the nested rollback did NOT restore companion:whelp. Every catalogue '
                      'mutation in this gate depends on that rollback; if it does not happen the '
                      'database is left missing a storage home.';
    end if;

    -- ══ (g) C2, THE POSITIVE CONTROL. (e) and (f) are both REFUSALS; a pair of
    --        refusals proves nothing unless the same call SUCCEEDS when its
    --        precondition is met. With 2 eggs held and the catalogue row back,
    --        whelp grants and EXACTLY ONE egg is consumed.
    v_r := public.hr_companion_grant(0, 'whelp', 'hatch:dragon_egg', gen_random_uuid());
    if coalesce(v_r->>'ok', 'false') <> 'true' then
      raise exception '§4(g) CONTROL FAILED: whelp refused with the egg held and the catalogue row '
                      'present (%). C2 would then be refusing everything, not enforcing anything.', v_r;

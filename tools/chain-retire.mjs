#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════
// tools/chain-retire.mjs — TAKE A DEAD GENERATED CATALOGUE OUT OF THE REPLAY, WITH ITS PROOF
// (Fable's architecture audit 2026-11-18, item 6).
//
//   node tools/chain-retire.mjs --list               the candidates, and why every other catalogue is kept
//   node tools/chain-retire.mjs --retire --all       retire every candidate, PROVEN (below), or nothing
//   node tools/chain-retire.mjs --retire <file>...   the same for named candidates
//   node tools/chain-retire.mjs --selftest           the candidate rules on planted chains (no database)
//
// A CANDIDATE is a generated catalogue C ("Generated by tools/<gen>") that
//   · is APPLIED (production ran it; a STAGED file is the apply plan and is not touched),
//   · writes rows only (no function, trigger or drop: tests/live-hash-drift.mjs attributes bodies
//     per file, and no file it names may leave), and no guard, tool or src file names it in code,
//   · is fully replaced by a LATER file S of the same generator: S deletes (or truncates) and
//     re-inserts every table C writes,
//   · and no guard or tool names, in code, any file strictly between C and S: no guard can stop a
//     replay inside the gap (upTo, a patch scope) and see the catalogue C would have left there.
// THE PROOF (--retire): the chain is replayed with and without the set, and the END STATE must be
// identical: schema-drift's fingerprint, every public column with its ordinal, every sequence, and
// an md5 over every row of every public and cron table. A file inside a gap that read C's rows at
// apply time is judged by the same replay (its self-check runs; anything it derived is in the rows).
// On any difference the files go back and the tool exits 1.
//
// RETIRED, NOT DELETED: the file moves to supabase/migrations-retired/ (the replay skips it) and its
// sidecar keeps its note and records {seq, superseded_by, proof}. Production ran it; git keeps it;
// the apply record still explains it (tests/apply-order-honesty.mjs counts a retired file as known).
// ════════════════════════════════════════════════════════════════════════
